/**
 * Чистые правила «ткнуть» (TeamSpeak-style) — БЕЗ базы, Redis и часов внутри.
 *
 * Тык по замыслу ГРОМКИЙ: у получателя всплывает окно, играет звук и мигает окно в панели задач.
 * Значит это же и готовый инструмент травли, а GusVoice раздаётся как turnkey с открытой
 * регистрацией. Поэтому правила здесь — не украшение: ошибка тут даёт не «неудобно», а
 * «незнакомец долбится в окно, пока не закроешь приложение».
 */

/** Не чаще одного тыка ОДНОМУ человеку за это время. */
export const POKE_COOLDOWN_MS = 30_000;

/**
 * Сколько тыков ВСЕГО может прилететь одному человеку за окно, от кого угодно (#122).
 *
 * 🔴 Кулдаун выше — на ПАРУ «кто→кого», и это правильно: общий счётчик на отправителя запретил бы
 * позвать двоих подряд. Но следствие было дырой: пятнадцать человек могли ткнуть одного подряд, и
 * каждый формально в своём праве. Селом завалить одного получалось бесплатно и без монет.
 *
 * ⚠️ Потолок сам по себе травлю НЕ предотвращает — он её нормирует: село может доставлять предел
 * каждый день. Настоящая защита — личный выключатель (`targetOptedOut`). Потолок нужен против
 * ВСПЛЕСКА, выключатель — против всего остального.
 *
 * Числа выбраны так, чтобы обычное «зайдите в канал» от двоих-троих проходило свободно.
 */
export const POKE_RECEIVE_LIMIT = 6;
export const POKE_RECEIVE_WINDOW_MS = 10 * 60_000;

/** Ключ счётчика полученных тыков: считаем по ПОЛУЧАТЕЛЮ, отправитель тут не важен. */
export function pokeReceiveKey(toUserId: string): string {
  return `pokercv:${toUserId}`;
}

/** Максимум символов в сообщении. Это окрик, а не переписка — длинному тексту место в ЛС. */
export const POKE_MAX_LEN = 100;

/**
 * Ключ кулдауна: пара «кто → кого», а не просто отправитель.
 *
 * ⚠️ Именно пара. Общий счётчик на отправителя запретил бы позвать двоих подряд (обычное дело:
 * «зайдите в канал»), а счётчик на получателя дал бы толпе долбить его по очереди.
 */
export function pokeCooldownKey(fromUserId: string, toUserId: string): string {
  return `poke:${fromUserId}:${toUserId}`;
}

/**
 * Привести сообщение к тому, что уедет получателю. Пустое — это нормально: тык без текста
 * («эй») осмыслен сам по себе, как и в TeamSpeak.
 *
 * ⚠️ Переводы строк схлопываются в пробел: получатель видит текст в МОДАЛКЕ, и десять переводов
 * строки растянули бы её на весь экран — это тоже способ мешать, только тихий.
 */
export function pokeMessage(raw: string | undefined): string {
  const flat = (raw ?? '').replace(/\s+/g, ' ').trim();
  // ⚠️ Режем по СИМВОЛАМ, а не по code units (нашёл Codex). `slice(0, 100)` на строке из эмодзи
  // разрубает суррогатную пару пополам, и получатель видит «крякозябру» в конце; заодно обещанные
  // «100 символов» на самом деле означали бы 100 code units, то есть 50 эмодзи.
  const chars = Array.from(flat);
  return chars.length > POKE_MAX_LEN ? chars.slice(0, POKE_MAX_LEN).join('') : flat;
}

export type PokeBlock =
  | null
  | 'self'
  | 'not-in-voice'
  | 'forbidden'
  | 'cooldown'
  | 'dnd'
  /** Человек отключил приём тыков на этом сервере. */
  | 'opted-out'
  /** Человеку уже прилетело слишком много за окно — от кого угодно. */
  | 'flooded';

export interface PokeInput {
  fromUserId: string;
  toUserId: string;
  /** Есть ли у отправителя право `POKE_MEMBERS` в ЭТОМ канале (учитывая оверрайды). */
  allowed: boolean;
  /** Сидит ли получатель прямо сейчас в этом голосовом канале (по данным presence). */
  targetInChannel: boolean;
  /** У получателя статус «не беспокоить». */
  targetDnd: boolean;
  /** Кулдаун ещё не истёк (ключ в Redis жив). */
  onCooldown: boolean;
  /** Получатель отключил приём тыков на этом сервере. */
  targetOptedOut: boolean;
  /** Сколько тыков получатель уже принял за окно (от всех). */
  targetReceived: number;
}

/**
 * Можно ли ткнуть. Возвращает причину отказа или `null`.
 *
 * ⚠️ Порядок проверок — часть правила, а не вкусовщина: `self` и `forbidden` идут ДО `dnd`, иначе
 * отправитель по коду ответа узнавал бы чужой статус «не беспокоить» там, где вообще не имел права
 * на действие. Статус — не секрет, он и так виден точкой, но раздавать его отказами не нужно.
 */
export function pokeBlock(i: PokeInput): PokeBlock {
  if (i.fromUserId === i.toUserId) return 'self';
  if (!i.allowed) return 'forbidden';
  // Ткнуть можно только того, кто сидит в голосовом канале: тык зовёт голосом, а не в переписке.
  if (!i.targetInChannel) return 'not-in-voice';
  if (i.targetDnd) return 'dnd';
  // ⚠️ Выключатель и потолок — ПОСЛЕ `dnd` и права, но ДО кулдауна: они про получателя, и отправителю
  // важнее узнать, что человека сейчас трогать нельзя вообще, чем что он поторопился.
  if (i.targetOptedOut) return 'opted-out';
  if (i.targetReceived >= POKE_RECEIVE_LIMIT) return 'flooded';
  if (i.onCooldown) return 'cooldown';
  return null;
}


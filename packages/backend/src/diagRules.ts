/**
 * Чистые правила приёма отчётов диагностики (#100) — без Fastify и без БД, чтобы их можно было
 * покрыть тестами (Codex просил именно такие выносы: «считает — живёт отдельно»).
 */

/** Замер раз в 15с; 960 срезов = 4 часа непрерывного показа. Дольше одного сеанса не бывает. */
export const MAX_SAMPLES = 960;

/** Меток «сломалось» за сеанс разумно единицы; 200 — потолок против залипшей кнопки. */
export const MAX_MARKS = 200;

/**
 * Отчёт за гранью разумного? Считаем по числу срезов и меток, а не по байтам: байты зависят от
 * количества процессов на машине, а смысл ограничения — «это уже не один сеанс показа».
 */
export function diagReportTooBig(samples: number, marks: number): boolean {
  return samples > MAX_SAMPLES || marks > MAX_MARKS;
}

/**
 * Разобрать срезы ПОШТУЧНО: годные оставить, негодные сосчитать.
 *
 * 🔴 Ради этой функции всё и переписано. Раньше массив разбирался целиком, и ОДИН негодный срез
 * стоил ВСЕГО отчёта: клиент получал 400, глушил его и продолжал слать такие же — телеметрия
 * человека замолкала насмерть. 2026-08-22 после появления второго слоя качества часть чисел стала
 * приезжать `null`; отбилось 86 отчётов из 284, и за сутки не сохранилось НИ ОДНОГО среза с
 * показом при 3511 срезах вообще. Потеря одного среза — мелочь, потеря всей телеметрии — авария.
 *
 * `parse` возвращает `undefined` для негодного среза. Число выброшенных возвращаем наружу, а не
 * прячем: молча терять данные — ровно та беда, из-за которой этот разбор и понадобился.
 */
export function partitionSamples<T>(
  raw: readonly unknown[],
  parse: (x: unknown) => T | undefined,
): { ok: T[]; dropped: number } {
  const ok: T[] = [];
  let dropped = 0;
  for (const item of raw) {
    const parsed = parse(item);
    if (parsed === undefined) dropped += 1;
    else ok.push(parsed);
  }
  return { ok, dropped };
}

/**
 * Выбросить из среза все ПУСТЫЕ значения (рекурсивно, вглубь объектов и массивов).
 *
 * 🔴 Ради этого всё и делалось. Нечисловое значение (NaN, бесконечность) при отправке превращается
 * в JSON в `null`, а схема на такое отвечает отказом — причём «значение по умолчанию» НЕ спасает:
 * оно срабатывает только на ОТСУТСТВУЮЩЕЕ поле, а не на пустое. Проверено на живой схеме:
 * `{}` → принято с нулём, `{gpu_pct: null}` → «ожидалось число», отказ.
 *
 * Из-за этого один сорвавшийся счётчик (хоть загрузка видеокарты) убивал ВЕСЬ срез, а раньше — и
 * весь отчёт: у одного человека из 21 среза доезжало 2. Убрав пустые поля, мы возвращаем их в
 * положение «отсутствует», и дальше решает схема: где есть умолчание — подставит его, где поле
 * необязательное — обойдётся без него.
 *
 * ⚠️ Мы НЕ придумываем данные: пустое поле означает «измерить не удалось», и после очистки оно
 * либо отсутствует, либо становится нулём — ровно тем, что и раньше значило «нет данных».
 */
export function stripNulls<T>(value: T): T {
  if (Array.isArray(value)) return value.map((v) => stripNulls(v)) as unknown as T;
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
      if (v === null) continue;
      out[k] = stripNulls(v);
    }
    return out as unknown as T;
  }
  return value;
}

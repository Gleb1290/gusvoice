/**
 * Бонус по клику — «вылезающий гусь» (план, модель G).
 *
 * 🔴 **Зачем он вообще.** Это единственное дешёвое доказательство присутствия: спящий человек не
 * кликнет, а честному сидящему клик не стоит ничего. Приём проверен масштабом Twitch, где баллы
 * раз в четверть часа выдают только по нажатию.
 *
 * 🔴 **Бонус — НАДБАВКА, а не замена базовой ставки.** Человек в полноэкранной игре гуся не увидит.
 * Замени клик начисление — и фича стала бы налогом на играющих, то есть на основной сценарий
 * продукта. Пропустил гуся — просто не получил надбавку.
 *
 * 🔴 **Расписание и одноразовость живут на СЕРВЕРЕ.** Вкладка не должна ни выдумывать награду, ни
 * придерживать предложение, чтобы показать его позже. Клиент получает идентификатор и срок, и
 * единственное, что он может, — предъявить идентификатор обратно.
 */

/**
 * Сколько живёт ЖЕТОН предложения — только как защита от мусора в Redis, а НЕ как срок годности.
 *
 * 🔴 **Гусь ждёт, пока его не нажмут** (решение подтверждено 03.09: «должны жить вечно как
 * в твиче»), и с 07.09 это стало буквально: откат до следующего отсчитывается от ПОИМКИ, поэтому
 * непойманного гуся больше некому сменить — он висит один и ждёт. Раньше срок был «интервал плюс
 * пять минут», и это имело смысл, пока метроном тикал сам по себе.
 *
 * ⚠️ Ноль здесь ставить нельзя: ключ без срока переживёт и уход человека с сервера, и выключение
 * экономики. Неделя — заведомо больше любой осмысленной паузы и заведомо меньше вечности.
 * ⚠️ Число НЕ зависит от `gooseMinutes`: это не часть правил экономики, а уборка за собой.
 */
export const GOOSE_TOKEN_TTL_MS = 7 * 24 * 60 * 60_000;

export interface GooseSettings {
  /** Размер надбавки в монетах; `0` — гуся нет вовсе. */
  gooseBonus: number;
  /** Через сколько минут ПОСЛЕ ПОИМКИ гусь может выглянуть снова. */
  gooseMinutes: number;
}

/** Настройки, которых хватает, чтобы назвать цену конкретной поимки. */
export interface GooseBonusSettings extends GooseSettings {
  /** Надбавка, если поймали В ДЕАФЕНЕ. */
  gooseDeafenedBonus: number;
}

/**
 * Выходить ли гусю при такой обстановке (решение 07.09).
 *
 * 🔴 **Один в канале — гуся нет вовсе.** Голосу одиночество режет ставку до `alonePercent` (у нас
 * четверть), а гусь платил одинаково и одному, и в компании — и тем разбавлял главный рычаг
 * экономики с шестикратного до 2.25-кратного. Дешевле всего это чинится не множителем, а
 * отсутствием предложения: надбавка за компанию, которой нет, — это просто не надбавка.
 *
 * ⚠️ Именно `peers`, а не «канал не пустой»: гусь смотрит на то же число, что и `companyPercent`,
 * иначе два правила про одно и то же разъедутся.
 * ⚠️ Деафен здесь НЕ проверяется: он не отменяет гуся, а удешевляет его (`gooseBonusFor`). Человек
 * в деафене в канале присутствует, и доказательство присутствия с него по-прежнему берём.
 */
export function gooseOfferAllowed(at: { peers: number }): boolean {
  return at.peers > 0;
}

/**
 * Сколько монет стоит ЭТА поимка.
 *
 * 🔴 Состояние берётся в момент ПОИМКИ, а не выхода гуся. С отсчётом отката от поимки гусь ждёт
 * сколько угодно, и его обстановка на момент появления к моменту клика бывает многочасовой
 * давности: пообещав по ней, мы платили бы за вчерашний деафен и наоборот.
 * ⚠️ Не выходит за пределы `gooseBonus`: удешевление — это удешевление, и настройка, выставленная
 * больше основной надбавки, не должна превращать деафен в выгодную позу.
 */
export function gooseBonusFor(s: GooseBonusSettings, at: { deafened: boolean }): number {
  if (!at.deafened) return s.gooseBonus;
  return Math.max(0, Math.min(s.gooseBonus, s.gooseDeafenedBonus));
}

/** Включён ли гусь на этом сервере. */
export function gooseEnabled(s: GooseSettings): boolean {
  return s.gooseBonus > 0 && s.gooseMinutes > 0;
}

/**
 * Ключ «откат ещё не вышел». Живёт `gooseMinutes` и не даёт выглянуть следующему гусю.
 *
 * 🔴 **Ставится в момент ПОИМКИ, а не выхода гуся** (решение 07.09). Раньше метроном тикал
 * сам по себе: пропустил — потерял, и надбавка доставалась за скорость реакции, а не за
 * присутствие. Теперь пропустить нельзя, можно только отложить: следующий гусь придёт через
 * `gooseMinutes` после того, как заберут этого.
 * ⚠️ Прямое следствие, которое надо понимать: это НЕ уменьшает поток, а перераспределяет его.
 * Темп становится `60 / (gooseMinutes + задержка)` в час — быстрый кликер получает столько же,
 * сколько и раньше, а играющий в полноэкранке перестаёт терять. Размер режут другие два правила.
 *
 * ⚠️ Ключ на ПАРУ сервер-человек, а не на канал: откат про человека, и переход из канала в
 * канал не должен обнулять ожидание — иначе бонус фармится перескакиванием.
 */
export function gooseCooldownKey(serverId: string, userId: string): string {
  return `goose:cool:${serverId}:${userId}`;
}

/**
 * Ключ-жетон конкретного предложения. Забрать = удалить этот ключ.
 *
 * 🔴 Идентификатор предложения лежит В ИМЕНИ ключа, а не в значении, и это не косметика: удаление
 * по точному имени атомарно само по себе, и первый же вернувший идентификатор забирает бонус, а
 * второй получает ноль удалённых ключей. Храни мы идентификатор значением, пришлось бы читать,
 * сравнивать и удалять тремя шагами — а между ними пролезает второе нажатие.
 */
export function gooseTokenKey(serverId: string, userId: string, offerId: string): string {
  return `goose:tok:${serverId}:${userId}:${offerId}`;
}

/** Сколько живёт жетон: см. `GOOSE_TOKEN_TTL_MS` — это уборка за собой, а не срок годности. */
export function gooseTokenTtlMs(): number {
  return GOOSE_TOKEN_TTL_MS;
}

/**
 * Ключ «какое предложение сейчас висит» — ИМЯ постоянное, значение = идентификатор.
 *
 * 🔴 Нужен, чтобы гусь ПЕРЕЖИЛ перезагрузку страницы. Предложение приходит одним пушем и больше
 * нигде не лежит: обновил вкладку — и живой гусь стал невидимым до следующего, хотя жетон цел.
 * По этому ключу снимок экономики возвращает текущее предложение, и клиент восстанавливает кнопку.
 * ⚠️ Забирают по-прежнему ЖЕТОНОМ с идентификатором в имени — гонку двух нажатий решает он.
 */
export function gooseCurrentKey(serverId: string, userId: string): string {
  return `goose:cur:${serverId}:${userId}`;
}

export type GooseClaimBlock = null | 'expired' | 'unavailable';


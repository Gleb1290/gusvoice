export interface TipSplit {
  /** Списывается с отправителя. */
  debit: number;
  /** Доходит до получателя. */
  credit: number;
  /** Сгорает — это и есть сток экономики. */
  burned: number;
}

/**
 * Разложить жест на списание, зачисление и сгоревшее.
 *
 * 🔴 **Налог — это не наказание, а два механизма разом.** Против альтов: ферма на пустых аккаунтах
 * перестаёт окупаться сама, без ловли и банов. И как сток: у валюты обязан быть слив, иначе балансы
 * пухнут и покупки обесцениваются.
 *
 * ⚠️ Округление ВНИЗ в пользу сгорания, а не получателя. Разница — максимум монета, но направление
 * должно быть зафиксировано: иначе на мелких суммах налог тихо превращался бы в ноль, и вся защита
 * от альтов исчезала бы ровно там, где ей место — на копеечных переводах пачками.
 */
export function tipSplit(amount: number, taxPercent: number): TipSplit {
  const debit = Math.max(0, Math.floor(amount));
  const tax = Math.min(100, Math.max(0, Math.floor(taxPercent)));
  const credit = Math.floor((debit * (100 - tax)) / 100);
  return { debit, credit, burned: debit - credit };
}


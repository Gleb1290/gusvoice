/**
 * Чистые правила «типнуть» (жест из Доты: зажал Alt, ткнул в друга, ему упало немного монет) —
 * БЕЗ базы, Redis и часов внутри.
 *
 * Родня `pokeRules.ts` и писано по тем же причинам: жест публичный (звук слышит весь канал) и
 * денежный, поэтому ошибка тут — не «неудобно», а «у человека пропали монеты» либо «в канале
 * бесконечно пищит». Порядок проверок — часть правила, а не вкусовщина.
 */

/** Не чаще одного типа ОДНОМУ человеку за это время. Жест, а не кнопка перевода. */
export const TIP_COOLDOWN_MS = 10_000;

/**
 * Ключ кулдауна — пара «кто → кому», как у тыка.
 *
 * ⚠️ Именно пара: общий счётчик на отправителя запретил бы поблагодарить двоих подряд (обычное дело
 * после хорошей катки), а счётчик на получателя дал бы толпе затыкать его по очереди.
 */
export function tipCooldownKey(fromUserId: string, toUserId: string): string {
  return `tip:${fromUserId}:${toUserId}`;
}

export interface TipSettings {
  /** Сколько списывается с отправителя за один жест. */
  tipAmount: number;
  /** Процент, который сгорает по дороге. Анти-альт и одновременно сток. */
  tipTaxPercent: number;
  /** Максимум ОТДАННОГО за сутки. 0 — без предела. */
  tipDailyOut: number;
  /** Максимум ПОЛУЧЕННОГО за сутки от всех вместе. 0 — без предела. */
  tipDailyIn: number;
  /**
   * Максимум, который ОДИН человек может донести ОДНОМУ за сутки. 0 — без предела.
   *
   * 🔴 Против того, чтобы один отправитель в одиночку забил получателю весь суточный приём (#124,
   * В2): двадцать типов по 5 при кулдауне пары 10 секунд — это 200 секунд работы, после которых
   * человека до конца суток не может типнуть больше никто, а он двадцать раз услышал «динь».
   * ⚠️ Массовый тип от РАЗНЫХ людей этот потолок не трогает: он про пару, а не про сумму от всех.
   */
  tipDailyPair: number;
}

export type TipBlock =
  | null
  | 'self'
  | 'disabled'
  | 'not-together'
  | 'opted-out'
  | 'self-opted-out'
  | 'cooldown'
  | 'poor'
  | 'out-limit'
  | 'in-limit'
  | 'pair-limit';

export interface TipInput {
  fromUserId: string;
  toUserId: string;
  /** Включена ли экономика на этом сервере. */
  economyEnabled: boolean;
  /** Сидят ли оба прямо сейчас в ОДНОМ голосовом канале (по данным presence). */
  together: boolean;
  /**
   * ОТПРАВИТЕЛЬ отказался от участия в экономике.
   *
   * 🔴 Было пропущено: проверялся только получатель, и человек, сказавший «не участвую», монеты
   * раздавать мог (нашёл Codex). Контракт `optedOut` — «ни начисления, ни типов», и обе половины
   * обязаны работать, иначе выключатель наполовину декоративный.
   */
  senderOptedOut: boolean;
  /** Получатель отказался от участия в экономике. */
  targetOptedOut: boolean;
  /** Кулдаун на эту пару ещё жив. */
  onCooldown: boolean;
  /** Баланс отправителя. */
  balance: number;
  /** Сколько отправитель уже отдал за эти сутки. */
  givenToday: number;
  /** Сколько получатель уже получил за эти сутки. */
  receivedToday: number;
}

/**
 * Можно ли типнуть. Возвращает причину отказа или `null`.
 *
 * ⚠️ Порядок: `self`, `disabled` и `not-together` идут ДО всего денежного, иначе по коду отказа
 * можно было бы выяснять чужой баланс и суточные лимиты там, где действие вообще не разрешено.
 *
 * 🔴 **`together` обязателен.** Тип — жест тому, с кем ты прямо сейчас сидишь, ровно как в Доте.
 * Перевод «кому угодно откуда угодно» — это уже банк, а не жест, и заводить его не надо.
 *
 * ⚠️ Как АНТИ-АЛЬТ `together` почти ничего не стоит, и обещать этого не надо (#124, Д4): ферма
 * копит начислением, а значит сидит в канале часами — быть «в канале в момент перевода» ей ничего
 * не стоит. Ферму ограничивают три числа: `dailyCap`, `tipDailyOut` и особенно `tipDailyPair`
 * (сколько один доносит одному за сутки). Разбор — в плане, раздел «минимальное совместное
 * присутствие — вычеркнуто».
 */
export function tipBlock(i: TipInput, s: TipSettings): TipBlock {
  if (i.fromUserId === i.toUserId) return 'self';
  if (!i.economyEnabled) return 'disabled';
  // Свой отказ — раньше чужого: человеку про ЕГО собственную настройку сказать можно прямо, и
  // выяснять при этом нечего.
  if (i.senderOptedOut) return 'self-opted-out';
  if (!i.together) return 'not-together';
  if (i.targetOptedOut) return 'opted-out';
  if (i.onCooldown) return 'cooldown';
  if (i.balance < s.tipAmount) return 'poor';
  // Предел ОТДАЧИ — по списанному: у отправителя уходит вся сумма целиком, включая налог.
  if (s.tipDailyOut > 0 && i.givenToday + s.tipAmount > s.tipDailyOut) return 'out-limit';
  // 🔴 А предел ПРИЁМА — по ДОШЕДШЕМУ, а не по списанному (нашёл Codex). Здесь сравнивалась грязная
  // сумма, а транзакция перевода сравнивает чистую: при цене 5 и налоге 20 % законный тип получал
  // ложный отказ «его сегодня уже засыпали», хотя до получателя дошло бы 4 и транзакция приняла бы.
  // Два места, считавшие один предел по-разному, — это и есть определение расхождения контракта.
  if (s.tipDailyIn > 0 && i.receivedToday + tipSplit(s.tipAmount, s.tipTaxPercent).credit > s.tipDailyIn) {
    return 'in-limit';
  }
  return null;
}


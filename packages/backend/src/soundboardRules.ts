/**
 * Саундборд: короткие сэмплы, которые любой участник выстреливает в голосовой канал за монеты (#21).
 *
 * 🔴 **Почему платный, а не бесплатный с кулдауном.** Саундборд не начинали именно из-за спама, и
 * любое бесплатное ограничение оказывается либо слишком строгим, либо не работающим. Монеты дают
 * тормоз даром: они кончаются, и каждый выстрел — осознанная трата. Это же и ответ на «а если
 * человек будет жать без остановки»: он не сможет, у него не хватит.
 *
 * 🔴 **Звук едет КОМАНДОЙ по сокету, а каждый клиент играет его у себя** — а не публикуется треком в
 * LiveKit, как предполагала исходная формулировка #21. Разница существенная, поэтому вот причины:
 *
 * - Публикация трека означает, что браузер стреляющего заводит ВТОРУЮ дорожку звука и тут же её
 *   снимает. Это пересогласование соединения на каждый выстрел и вход в ровно ту часть медиа-стека,
 *   где мы исторически кровоточим: WebView2 на десктопе, WebView на Android, дважды укусившая
 *   ловушка числа каналов в микрофонной цепи. Комедийный звук не стоит такого риска.
 * - Файлы уже лежат публичными ссылками в хранилище, а у клиента уже есть проигрывание звуков
 *   событий с готовым разрешением «канал → сервер → синтез». Выстрел — это тот же путь с явным
 *   идентификатором сэмпла вместо имени события.
 * - Оно правильно складывается с показом экрана: нативный захват берёт «звук минус голоса
 *   GusVoice», то есть выстрел НЕ попадёт в поток показывающего — и хорошо, зрители всё равно
 *   услышат его своим клиентом, а не вторым эхом.
 *
 * ⚠️ Чем платим за это: выстрела не будет в записи разговора (её у нас нет) и на него не действует
 * персональная громкость участника (он не голос, а звук интерфейса). Оба следствия осознанные.
 */

/** Сколько сэмплов держит один сервер. */
export const SOUNDBOARD_MAX_CLIPS = 24;

/**
 * Потолок размера файла — вдвое строже, чем у звуков событий (512 КБ).
 *
 * ⚠️ Звук события играется по случаю, а сэмпл саундборда — по желанию и часто. Каждый выстрел это
 * загрузка файла у КАЖДОГО, кто сидит в канале, и лишние сотни килобайт бьют по мобильным.
 */
export const SOUNDBOARD_MAX_BYTES = 256 * 1024;

/**
 * Потолок длительности, секунды.
 *
 * ⚠️ Проверяется НА КЛИЕНТЕ перед загрузкой, потому что сервер не декодирует звук — по байтам
 * длительность не узнать, тихий моно-MP3 на низком битрейте укладывает минуты в наш размер. Это
 * честное ограничение доверием: загружать может только держатель права на звуки, то есть человек,
 * которому владелец сервера уже доверил звуковую часть. Обходится — но обходит его тот, кто и так
 * может залить в канал что угодно.
 */
export const SOUNDBOARD_MAX_SECONDS = 8;

/**
 * Пауза между выстрелами В КАНАЛЕ — не у покупателя, а у всех сразу.
 *
 * 🔴 Это НЕ дубль денежного тормоза, а другое ограничение. Монеты сдерживают одного человека, но
 * пятеро с полными кошельками нажимают одновременно — и в канале получается каша из наложенных
 * сэмплов, где не слышно ни одного. Общая пауза гарантирует, что выстрел успевает прозвучать.
 * ⚠️ Захватывается ДО списания: отказ по ней не должен стоить денег.
 */
export const SOUNDBOARD_CHANNEL_COOLDOWN_MS = 4000;

/** Ключ общей паузы канала. */
export function soundboardChannelKey(channelId: string): string {
  return `sb:ch:${channelId}`;
}

/** Пределы имени: коротко, потому что оно подписывает кнопку в сетке. */
export const SOUNDBOARD_NAME_MAX = 24;

/**
 * Имя сэмпла из внешнего мира → пригодное для показа, или `null`, если такое принимать нельзя.
 *
 * ⚠️ Схлопывает пробелы и режет края: имя рисуется на кнопке, и «  бах   » с невидимыми краями
 * ломает выравнивание сетки, а «бах\nбах» — её высоту.
 */
export function soundboardName(raw: string): string | null {
  const s = raw.replace(/\s+/g, ' ').trim();
  if (!s) return null;
  if (s.length > SOUNDBOARD_NAME_MAX) return null;
  return s;
}

export type ClipBlock = null | 'unknown-clip' | 'wrong-server' | 'channel-busy';

export interface ClipInput {
  /** Сэмпл, найденный по идентификатору, или `null`, если такого нет. */
  clip: { id: string; serverId: string } | null;
  /** Сервер, в чьём канале жмут кнопку. */
  serverId: string;
  /** Занят ли канал предыдущим выстрелом. */
  channelBusy: boolean;
}

/**
 * Можно ли выстрелить ЭТИМ сэмплом — проверки, которых нет в общей покупке.
 *
 * 🔴 Принадлежность серверу проверяется отдельно и обязательно: идентификаторы сэмплов ничем не
 * защищены, и без этой проверки участник одного сервера подставил бы в запрос чужой идентификатор и
 * выстрелил в своём канале звуком с сервера, куда его не звали. Никакой платы это бы не обошло —
 * просто утечка чужого содержимого.
 */
export function clipBlock(i: ClipInput): ClipBlock {
  if (!i.clip) return 'unknown-clip';
  if (i.clip.serverId !== i.serverId) return 'wrong-server';
  if (i.channelBusy) return 'channel-busy';
  return null;
}


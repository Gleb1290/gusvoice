/**
 * Цена ЭТОГО звука В МОНЕТАХ: своя, если задана, иначе общая из каталога (та приходит сюда уже
 * переведённой по текущей ставке).
 *
 * 🔴 **`null` — это «своей цены нет», а не «бесплатно»** (запрос 02.09: «звуки могут быть не
 * одной цены — будут ультимативные и так себе»). Разница принципиальная: уже залитые звуки и свежий
 * turnkey-сервер обязаны работать без единой настройки, а ноль — это осмысленная цена «даром», и
 * владелец должен уметь её поставить осознанно.
 *
 * 🔴 **Именно монеты, а не минуты сидения** (решение 04.09, миграция 0057). Весь остальной
 * прайс живёт в минутах, чтобы сдвиг ставки его не переоценивал, — но эти цены назначают руками и
 * по одному звуку, глядя на балансы людей, и там минуты только мешают. Плата за решение: сдвинув
 * ставку, цены звуков придётся пересмотреть тоже руками.
 *
 * ⚠️ Отрицательное и дробное схлопываем: цена приходит из формы, а форма врёт. Отрицательная цена
 * означала бы доплату за выстрел.
 */
export function clipPriceCoins(own: number | null | undefined, fallback: number): number {
  if (own === null || own === undefined || !Number.isFinite(own)) return fallback;
  return Math.max(0, Math.floor(own));
}


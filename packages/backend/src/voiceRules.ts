import { isAdmin, Permission } from '@gusvoice/shared';
import type { MemberContext } from './permissions.js';

/**
 * Правила голосовой модерации — чистые, БЕЗ импорта базы.
 *
 * Вынесено из `routes/voice.ts` по просьбе Codex (2026-07-27): сам расчёт чистый, но импорт файла
 * роута тянет env и поднимает Pool/Redis — тест падает раньше первой проверки. Тот же случай, что
 * `pollRules.ts` и `afkRules.ts`. Импорт `MemberContext` строго type-only: на рантайме он стирается,
 * поэтому `permissions.ts` (а с ним и `db`) сюда не приезжает.
 */

/**
 * Ранг для ГОЛОСОВОЙ модерации.
 *
 * Отличается от `highestPosition` ровно одним: разводит владельца и администратора. Там оба дают
 * `+∞`, и это верно для сравнения «строго ниже» (кик/бан/роли). Но голосовая иерархия ослаблена до
 * «строго выше» (см. `voiceHierarchyBlock`), а `∞ > ∞` = false — с общим рангом админ получил бы
 * право двигать и мутить ВЛАДЕЛЬЦА. Поэтому владелец здесь строго выше любого админа.
 */
export function voiceRank(ctx: MemberContext): number {
  if (ctx.isOwner) return Number.POSITIVE_INFINITY;
  // Выше любой возможной позиции роли, но ниже владельца.
  if (isAdmin(ctx.serverPermissions)) return Number.MAX_SAFE_INTEGER;
  return ctx.roles.reduce((max, r) => Math.max(max, r.position), 0);
}

/**
 * Обходит ли актор защиту по старшинству при ПЕРЕМЕЩЕНИИ между голосовыми каналами.
 *
 * Зачем: владелец по определению `+∞`, поэтому сдвинуть его не мог никто — а на дружеском сервере
 * ровно этого и хотят («затащи меня в канал»). Право `MOVE_ANYONE` снимает щит адресно: владелец
 * выдаёт его одной выбранной группе (выдать может ТОЛЬКО он — см. `PROTECTED_PERMISSIONS`).
 *
 * ⚠️ Проверка БУКВАЛЬНО по биту, без обычной поблажки `isAdmin`. Пусти сюда админа — и щит владельца
 * пропал бы для каждого администратора сразу, то есть право перестало бы быть адресным. Владелец
 * получает бит естественно: его `serverPermissions` = `ALL_PERMISSIONS`.
 *
 * ⚠️ Только перемещение. Мут и отключение из голоса иерархию уважают по-прежнему: «перетащи меня» и
 * «заткни меня» — очень разные разрешения, и второе владелец никому не давал.
 */
export function movesAnyone(ctx: MemberContext): boolean {
  return (ctx.serverPermissions & Permission.MOVE_ANYONE) === Permission.MOVE_ANYONE;
}

/**
 * Пускать ли голосовое модерирующее действие. Возвращает текст отказа или `null`.
 *
 * Вынесено из роута по просьбе Codex (2026-08-01): раньше решение жило в `voiceHierarchyBlock`
 * вперемешку с загрузкой контекстов, и проверить можно было только наличие бита. Главное
 * ограничение #98 при этом не доказывалось ничем — а именно оно и есть весь смысл права:
 * **`MOVE_ANYONE` снимает щит ТОЛЬКО для перемещения.** Мут и отключение из голоса иерархию
 * уважают по-прежнему, потому что «перетащи меня» и «заткни меня» — очень разные разрешения, и
 * второе владелец никому не давал. Ошибка здесь дала бы выбранной роли право мутить владельца.
 *
 * ⚠️ Иерархия голоса ослаблена до СТРОГО `>` (#86, решение 2026-07-27): равные ранги друг
 * друга модерировать МОГУТ. На дружеском сервере роль это скорее «группа», чем ступень власти, и
 * двое с одной ролью не могли перетащить друг друга между каналами. На кик/бан/роли это НЕ
 * распространяется — там `>=` остаётся.
 *
 * ⚠️ `null` в акторе или цели = «не участник» → не блокируем: допуск к действию проверяется ДО
 * этого, по правам канала, и удваивать его отказом «по иерархии» значило бы врать про причину.
 */
export function voiceHierarchyDecision(
  actor: MemberContext | null,
  target: MemberContext | null,
  isMove: boolean,
): string | null {
  if (!actor || !target) return null;
  if (isMove && movesAnyone(actor)) return null;
  if (voiceRank(target) > voiceRank(actor)) {
    return 'нельзя модерировать того, чья роль выше твоей';
  }
  return null;
}

import type { VoiceParticipant } from '@gusvoice/shared';

/**
 * Чистые правила учёта присутствия в голосе — БЕЗ базы, Redis и часов внутри.
 *
 * Это ШАГ 0 экономики GusCoins («сухой прогон», `docs/guscoins-plan.md`): неделю копим СЫРЫЕ факты,
 * монет никто не видит и потратить их нельзя.
 *
 * 🔴 **Пишем секунды и обстановку, а НЕ монеты.** Ставка, множитель компании, затухание и потолок
 * ещё не назначены — их назначат по этим же данным. Запиши мы сразу монеты, любая последующая
 * правка ставки сделала бы прошлое неправильным, и «а сколько бы вышло при другой ставке» стало бы
 * неотвечаемым вопросом. По сырым секундам пересчитать можно ЛЮБУЮ формулу задним числом; по
 * посчитанным монетам — никакую.
 *
 * Время везде приходит аргументом: иначе «прошло ровно столько-то» невоспроизводимо в тесте.
 */

/** Как часто снимается срез. */
export const SAMPLE_PERIOD_MS = 60_000;

/**
 * Потолок засчитываемого за ОДИН срез.
 *
 * ⚠️ Нужен потому, что тикер может опоздать: бэкенд перезапустили, база тормозила, процесс не
 * получал управления. Без потолка одна такая пауза превратилась бы в час «присутствия», которого
 * никто не наблюдал. Правило простое: засчитываем не больше, чем видели своими глазами, с запасом
 * на обычные задержки.
 */
export const MAX_SAMPLE_MS = 5 * SAMPLE_PERIOD_MS;

export interface ChannelSnapshot {
  channelId: string;
  serverId: string;
  participants: VoiceParticipant[];
}

/** Один засчитанный отрезок присутствия одного человека. */
export interface ActivitySample {
  serverId: string;
  userId: string;
  channelId: string;
  /** Сколько секунд засчитано этим срезом (уже с учётом потолка). */
  seconds: number;
  /** Сколько ДРУГИХ живых людей было в канале в этот момент. */
  peers: number;
  /**
   * Выключил микрофон САМ.
   *
   * 🔴 Раньше здесь было «сам ИЛИ модератор», и это делало право `MUTE_MEMBERS` денежным рычагом:
   * стоит владельцу опустить `mutedPercent`, и мьют от модератора начинает молча резать жертве
   * заработок, а прекратить это она не может (#124, В1/К1). Решение модератора теперь рядом,
   * отдельным полем, и в формулу не попадает.
   */
  muted: boolean;
  /** Замьютил модератор. Факт записываем, на начисление он не влияет. */
  serverMuted: boolean;
  deafened: boolean;
  screensharing: boolean;
  /**
   * Человек в статусе «отошёл» — сам поставил или увела автоматика (запрос 04.09).
   *
   * 🔴 Зачем отдельно от мьюта. Мьют не штрафуется намеренно: выключенный микрофон не означает
   * отсутствия. Но ровно этим и открывался обход — выключить микрофон НА ЖЕЛЕЗЕ (приложение об этом
   * не знает вовсе) и уйти, пока капает полная ставка. «Отошёл» закрывает именно это: автоматика
   * считает простой на уровне ОС, поэтому играющий человек в него не попадает, а ушедший от
   * компьютера — попадает через десять минут.
   */
  away: boolean;
}

export interface PlanResult {
  samples: ActivitySample[];
  /**
   * ПОЛНЫЙ новый набор курсоров (userId → момент этого среза), а не дельта.
   *
   * ⚠️ Именно полный: вызывающая сторона заменяет им прежний целиком, поэтому ушедшие из голоса
   * выпадают сами. Это не оптимизация, а правило — см. `planSamples`.
   */
  cursors: Map<string, number>;
  /** Скольких человек застали сразу в двух каналах (лишние сессии отброшены). */
  duplicates: number;
}

/** Сколько в канале ДРУГИХ людей (сам человек не считается). */
export function peersOf(participants: VoiceParticipant[], userId: string): number {
  let n = 0;
  for (const p of participants) if (p.userId !== userId) n++;
  return n;
}

/**
 * Выбрать ОДНУ сессию человека, если его застали в нескольких каналах разом.
 *
 * Так бывает без всякого злого умысла: десктоп на одном сервере и вкладка браузера на другом — две
 * живые комнаты LiveKit (`#108` вышибает только второй ДЕСКТОП, браузер рядом живёт). Засчитывать
 * обе значило бы платить дважды за одно и то же время.
 *
 * ⚠️ Выбор ДЕТЕРМИНИРОВАННЫЙ (по `channelId`), а не «первая попавшаяся»: порядок ключей в Redis
 * ничем не гарантирован, и человек иначе прыгал бы между каналами от среза к срезу — в статистике
 * это выглядело бы как метания, которых не было.
 * ⚠️ Момент входа для выбора «старшей» сессии тут недоступен: `VoiceParticipant` его не несёт
 * (в LiveKit он есть — `joinedAtMs`, — но presence его не сохраняет). Для сухого прогона это
 * неважно: любая из двух сессий даёт то же самое время присутствия.
 */
export function pickSession(candidates: ChannelSnapshot[]): ChannelSnapshot {
  let best = candidates[0];
  for (const c of candidates) if (c.channelId < best.channelId) best = c;
  return best;
}

/**
 * Посчитать засчитываемое время между прошлым срезом и текущим.
 *
 * `last === undefined` — человека в прошлый раз не видели: он только что зашёл, либо бэкенд
 * перезапустился и курсоры не пережили этого. **Возвращаем 0.** Мы не знаем, что происходило до
 * первого наблюдения, и додумывать это в плюс себе нельзя: пропущенная минута на перезапуске —
 * ерунда, а придуманный час — испорченные данные, ради которых прогон и затевался.
 */
export function creditedMs(now: number, last: number | undefined): number {
  if (last === undefined) return 0;
  const elapsed = now - last;
  if (elapsed <= 0) return 0; // часы прыгнули назад / повторный вызов с тем же now
  return Math.min(elapsed, MAX_SAMPLE_MS);
}

/**
 * Собрать срез: что записать в журнал и какими станут курсоры.
 *
 * ⚠️ Возвращаемые курсоры — ПОЛНЫЙ новый набор, только по тем, кого видно сейчас. Ушедший из
 * голоса выпадает, и при следующем заходе его первый срез снова даст 0 (см. `creditedMs`). Так
 * перерыв между заходами не может быть засчитан ни при каких обстоятельствах — а именно этого мы и
 * добиваемся: «ушёл на ночь, вернулся утром» не должно выглядеть как ночь в канале.
 *
 * Срезы с нулевым временем не записываются вовсе: строка «0 секунд» ничего не сообщает, а объём
 * журнала растит. ⚠️ Отсечка идёт по СЕКУНДАМ после округления, а не по миллисекундам — иначе
 * огрызок короче полсекунды проходил бы проверку и всё равно записывался нулём.
 */
export function planSamples(
  channels: ChannelSnapshot[],
  cursors: Map<string, number>,
  now: number,
  /** Кто сейчас «отошёл». Статус живёт в БД, presence о нём не знает — передаём снаружи. */
  awayUserIds: ReadonlySet<string> = new Set(),
): PlanResult {
  // Сначала собираем ВСЕ сессии каждого человека — только так виден случай «сразу в двух каналах».
  const byUser = new Map<string, ChannelSnapshot[]>();
  for (const ch of channels) {
    for (const p of ch.participants) {
      const list = byUser.get(p.userId);
      if (list) list.push(ch);
      else byUser.set(p.userId, [ch]);
    }
  }

  const samples: ActivitySample[] = [];
  const next = new Map<string, number>();
  let duplicates = 0;

  for (const [userId, sessions] of byUser) {
    if (sessions.length > 1) duplicates++;
    const chosen = sessions.length === 1 ? sessions[0] : pickSession(sessions);
    const me = chosen.participants.find((p) => p.userId === userId)!;

    // Курсор двигаем ВСЕГДА, даже когда засчитывать нечего: иначе человек, чей первый срез дал 0,
    // навсегда остался бы без курсора и не заработал бы никогда.
    const ms = creditedMs(now, cursors.get(userId));
    next.set(userId, now);
    // ⚠️ Отсекаем по СЕКУНДАМ, а не по миллисекундам (нашёл Codex). `ms > 0` меньше половины
    // секунды после округления превращается в запись «0 секунд» — то есть строку, которая ничего не
    // сообщает, но занимает место и портит любой `count(*)`. Цена отсечения — потерянный огрызок
    // короче полсекунды: на минутном тикере это шум, а не данные.
    const seconds = Math.round(ms / 1000);
    if (seconds <= 0) continue;

    samples.push({
      serverId: chosen.serverId,
      userId,
      channelId: chosen.channelId,
      seconds,
      peers: peersOf(chosen.participants, userId),
      // ⚠️ БЕЗ `|| me.serverMuted` — см. поле `muted` выше (#124, В1).
      muted: me.muted,
      serverMuted: me.serverMuted,
      deafened: me.deafened,
      screensharing: me.screensharing,
      away: awayUserIds.has(userId),
    });
  }

  return { samples, cursors: next, duplicates };
}

/**
 * Защита федеративных маршрутов: частота запросов и повтор перехваченного запроса (#148).
 *
 * Обе меры подсмотрены у соседей по задаче — в Backspace, где федерация работает дольше нашей. Там
 * они появились не от хорошей жизни, и чинить это лучше до того, как федерацию включат, а не после.
 *
 * Модуль ЧИСТЫЙ: ни Redis, ни env, ни сети — только правила. Привязка к живому Redis — в
 * `guardsRuntime.ts`; без такого разделения эти правила нельзя было бы проверить, не подняв Redis.
 */

import { createHash } from 'node:crypto';
import { CLOCK_SKEW_TOLERANCE_S, SIGNATURE_TTL_S } from './httpSignature.js';

/**
 * Пределы частоты. Разные для разных маршрутов, потому что и смысл разный: заявку на связку шлют раз
 * в жизни, события — постоянно.
 */
export const FED_LIMITS = {
  /** Заявка на связку: адресов, с которых она приходит, у нас нет заранее, поэтому считаем по адресу. */
  linkRequest: { max: 10, windowS: 600 },
  /** Подтверждение связки — столько же: это парный к заявке запрос. */
  linkConfirm: { max: 10, windowS: 600 },
  /** События: считаем по связке. Живой инстанс шлёт их пачками, поэтому предел заметно выше. */
  events: { max: 600, windowS: 60 },
  /**
   * Каталог и список серверов (F2, план §4.1.1 «запросов каталога/ч»). Считаем по связке.
   *
   * ⚠️ Предел с запасом на СТРАНИЦЫ: полная сверка каталога на тысячу человек это несколько запросов
   * подряд, и предел, рассчитанный на «раз в 15 минут», обрубил бы её на середине — причём выглядело
   * бы это как «сосед отдаёт только начало списка».
   */
  directory: { max: 240, windowS: 3600 },
  /**
   * Забор журнала ЛС (`GET /fed/v1/conv/changes`) и полный проход по беседе (`/fed/v1/conv/:id/export`) — исправления ревью
   * 12.10, п. 1. Считаем по связке ОТДЕЛЬНО от каталога: звонок в дверь на каждое сообщение и страницы полного прохода
   * выжигали общий с каталогом и аватарами предел 240/ч, и переписка стояла до часа.
   */
  convPull: { max: 1200, windowS: 3600 },
  /**
   * Заведение гостевой сессии (F3, §5.5). Считаем по СВЯЗКЕ: один живой инстанс с тремя десятками
   * людей укладывается с запасом, а поток чужих токенов упирается в стену.
   */
  guestSession: { max: 240, windowS: 3600 },
  /**
   * Предпросмотр ссылки (§4.2.1). 🔴 Предел здесь и есть защита от ПОДБОРА кода: предпросмотр
   * доступен всякому, кто знает код, а код — шесть символов.
   */
  invitePreview: { max: 120, windowS: 3600 },
  /**
   * Файл вложения ЛС соседу (Э3, `GET /fed/v1/att/:id`). Считаем по связке: сосед копирует каждое фото и голосовое
   * переписки отдельным запросом, лента с альбомами — десятки подряд.
   */
  attachment: { max: 1800, windowS: 3600 },
  /**
   * Мгновенное ЛС (Э4, `POST /fed/v1/ephemeral`, `dm3`). Считаем по связке: отправитель шлёт «печатает» одного человека в одной
   * беседе не чаще раза в 3 с и «в сети» — на смену и раз в минуту; 600/мин — запас на сотню одновременно печатающих.
   */
  ephemeral: { max: 600, windowS: 60 },
  /**
   * Приглашение на звонок 1:1 (Э6, `POST /fed/v1/call/invite`, `dmcall1`). Считаем по связке: человек звонит не чаще 10 раз в
   * минуту (`routes/calls.ts`), 120/мин — запас на дюжину одновременно звонящих.
   */
  call: { max: 120, windowS: 60 },
  /**
   * Запрос участника хосту группы со смешанным составом (Э7 часть 1, `POST /fed/v1/conv/group/op`, `dmgroup1`): выйти, удалить,
   * позвать, переименовать. По связке: человек делает не больше 20 таких действий за 10 с (`routes/convGroups.ts`).
   */
  group: { max: 120, windowS: 60 },
  /**
   * По АДРЕСУ отправителя — ДО проверки подписи (аудит 19.09, F-07).
   *
   * 🔴 Раньше счётчики по связке стояли до подписи и ключевались `instance_id` ИЗ ЗАПРОСА: посторонний
   * называл id соседа (он публичен в визитке) и 240 пустыми запросами на час закрывал честному соседу
   * каталог, аватары, сверку членств и догон «выйти везде», а его гостям — вход. Теперь до подписи
   * считаем по адресу (у инстанса соседа адресов один-два, у постороннего — свои), а по связке —
   * только после верной подписи, когда `instance_id` доказан.
   */
  peerAddress: { max: 600, windowS: 60 },
  /** Заведение гостевой сессии по адресу: за одним адресом сидит весь офис соседа, предел щедрый. */
  guestSessionAddress: { max: 300, windowS: 3600 },
} as const;

/**
 * Сколько событий принимаем одной пачкой (аудит 19.09, F-14).
 *
 * Предел `events` считает ЗАПРОСЫ, а в одном теле помещаются тысячи мелких событий, каждое — по
 * нескольку запросов в базу строго по очереди. Честный отправитель режет по 50 (`outbox.ts`);
 * больше сотни — это не связка, а нагрузка, и отказ целиком.
 */
export const EVENTS_BATCH_MAX = 100;

/**
 * Проверка частоты — ДО проверки подписи.
 *
 * 🔴 Порядок принципиален: проверка подписи это криптография по телу запроса, то есть сама по себе
 * работа. Поставь её первой — и поток мусорных запросов заставит нас считать подписи, что и есть
 * отказ в обслуживании. Дешёвый счётчик впереди дорогой проверки.
 */
export function fedRateKey(kind: keyof typeof FED_LIMITS, who: string): {
  key: string;
  max: number;
  windowS: number;
} {
  const limit = FED_LIMITS[kind];
  return { key: `fed:${kind}:${who}`, max: limit.max, windowS: limit.windowS };
}

/**
 * Сколько помним подписи. Окно жизни подписи плюс допуск часов с обеих сторон и небольшой запас:
 * пока подпись может быть принята, её отпечаток обязан лежать у нас.
 */
const NONCE_TTL_S = SIGNATURE_TTL_S + CLOCK_SKEW_TOLERANCE_S * 2 + 30;

/**
 * Сколько помним одноразовые метки токенов личности (F3, §5.5).
 *
 * Токен живёт две минуты; метка обязана пережить его с запасом на разъехавшиеся часы обеих сторон —
 * иначе «просроченный» у нас токен, ещё живой по часам дома, прошёл бы второй раз.
 */
const IDENTITY_JTI_TTL_S = 300;

/**
 * Предъявляли ли нам этот токен личности раньше.
 *
 * 🔴 Запись и проверка — ОДНОЙ командой (`NX` + `EX`): между «посмотрели» и «записали» не должно
 * быть щели, в которую пролезет второй такой же запрос, пришедший параллельно. Ровно те же грабли,
 * что и у меток подписей ниже.
 */
export async function seenIdentityJtiWith(store: NonceStore, jti: string): Promise<boolean> {
  if (jti.length === 0) return true;
  try {
    const stored = await store.set(`fed:jti:${signatureFingerprint(jti)}`, '1', 'EX', IDENTITY_JTI_TTL_S, 'NX');
    return stored === null;
  } catch {
    // Redis недоступен: считаем токен НЕ виденным. Отказывать всем гостям из-за нашей неудачи хуже,
    // чем принять один токен дважды в течение двух минут, — но это осознанный размен, а не недосмотр.
    return false;
  }
}

/**
 * Видели ли мы эту подпись раньше.
 *
 * 🔴 Зачем, если подпись живёт всего минуту: минуты достаточно. Перехвативший запрос (лежащий
 * посередине прокси, лог обратного прокси, чужой сниффер в сети) может отправить ТОТ ЖЕ запрос
 * повторно, и он пройдёт все проверки — подпись верна, срок не вышел, тело совпадает. Для чтения это
 * неважно, но событие «человека забанили» или «человек вышел из сервера», применённое дважды, уже
 * меняет состояние.
 *
 * Помним отпечаток подписи, а не её саму: подпись длинная, а в Redis ей лежать десятками тысяч.
 *
 * ⚠️ Если Redis недоступен — пропускаем. Потерять федерацию целиком из-за недоступного кеша хуже,
 * чем принять повтор: остальные проверки (подпись, срок, номер события) никуда не делись, а у
 * событий состояния дедуп по номеру и так есть.
 */
export function signatureFingerprint(signatureHeader: string): string {
  return createHash('sha256').update(signatureHeader, 'utf8').digest('base64url').slice(0, 32);
}

/** Что нам нужно от Redis — ровно одна команда. Так защиту можно проверить без живого Redis. */
export interface NonceStore {
  set(key: string, value: string, ex: 'EX', ttl: number, nx: 'NX'): Promise<string | null>;
}

/** Само правило, с подставляемым хранилищем. */
export async function seenSignatureWith(store: NonceStore, signatureHeader: string): Promise<boolean> {
  // Пустой заголовок — не «не видели», а неправильный вызов: сюда попадают только проверенные
  // запросы, у которых подпись есть. Считаем повтором, чтобы такой вызов не проехал молча.
  if (signatureHeader.length === 0) return true;
  try {
    // NX и EX одной командой: между проверкой и записью не должно быть щели, в которую пролезет
    // второй такой же запрос, пришедший параллельно.
    const stored = await store.set(`fed:nonce:${signatureFingerprint(signatureHeader)}`, '1', 'EX', NONCE_TTL_S, 'NX');
    return stored === null;
  } catch {
    return false;
  }
}


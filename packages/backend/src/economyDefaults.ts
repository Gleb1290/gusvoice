/**
 * Настройки экономики для сервера, где её ЕЩЁ НЕ НАСТРАИВАЛИ.
 *
 * 🔴 **Зачем это существует.** Строка `server_economy` появляется только при первом сохранении
 * настроек, а до тех пор `GET /servers/:id/economy` отдавал `settings: null` — и панель владельца
 * вечно висела на «Загрузка…». Получалась курица и яйцо: включить экономику первый раз было НЕГДЕ,
 * потому что открыть панель можно было только там, где её уже включили. Поймано 04.09 на боевом
 * сервере, ровно в момент включения фичи людям.
 *
 * 🔴 **Числа берутся ИЗ САМОЙ СХЕМЫ** (`getTableColumns` → `column.default`), а не переписываются
 * рядом. Копия умолчаний — это ещё одна модель, которая расходится с боевой молча; сегодня же на
 * этом обожглись с эталоном статистики, где разъехавшиеся числа завышали доход вчетверо. Здесь
 * источник ровно один: таблица.
 *
 * ⚠️ Умолчания — это ещё НЕ включённая экономика: `enabled` в схеме `false`, и панель открывается
 * выключенной. Строка появится, когда владелец сохранит первое изменение.
 */
import { getTableColumns } from 'drizzle-orm';
import type { ServerEconomy } from './coins.js';
import { serverEconomy } from './db/schema.js';

/**
 * ⚠️ Тип из `coins.ts` берётся ТОЛЬКО как тип (`import type`), а форма собирается здесь. Обычный
 * импорт потянул бы `coins.ts` → `db/index.ts` → `env.ts`, и модуль перестал бы существовать без
 * DATABASE_URL — то есть его нельзя было бы проверить тестом, ради которого он и написан.
 */
export function economyDefaults(serverId: string): ServerEconomy {
  const row: Record<string, unknown> = { serverId };
  for (const [key, col] of Object.entries(getTableColumns(serverEconomy))) {
    if (key === 'serverId') continue;
    // Колонки без умолчания (иконка, отметки ретро и первого включения) честно пустые: их значение
    // появляется только вместе с реальным действием.
    row[key] = col.hasDefault ? (col.default ?? null) : null;
  }
  return row as unknown as ServerEconomy;
}

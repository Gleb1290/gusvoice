/**
 * Строка с потолком длины, которая ОБРЕЗАЕТ, а не отбивает.
 *
 * 🔴 Ровно на этом мы потеряли сутки телеметрии. У `enc.encoder` стоял `.max(64)`, а когда показ стал
 * публиковаться двумя слоями, libwebrtc начал отдавать составное имя вида
 * `SimulcastEncoderAdapter (NVIDIA H264 Encoder, NVIDIA H264 Encoder)` — 66 символов. Схема отбивала
 * КАЖДЫЙ срез с показом, у одного человека 118 подряд.
 *
 * Потолок здесь нужен только чтобы чужая строка не раздула базу. Для этой цели обрезка ничем не хуже
 * отказа — а вот цена отказа оказалась несоизмеримой: вместо длинного имени мы теряли весь замер.
 * Косметическое ограничение не должно уничтожать данные.
 */
const cappedString = (max: number) => z.string().transform((s) => s.slice(0, max));

/** Загрузка блоков видеокарты у одного владельца, % (см. `gpu_by`). Ключ `3d` — как в Rust. */

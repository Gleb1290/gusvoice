/**
 * Схема отчёта диагностики (#100) — ЧИСТАЯ: только zod, ни Fastify, ни БД, ни браузера.
 *
 * Вынесено по просьбе Codex: пока схема жила внутри роута, её нельзя было проверить тестом, а
 * ошибка здесь молча переписывает смысл исторических данных. Самый опасный пример прямо ниже —
 * `sharing` с `.default(1)`: поменяй умолчание на 0, и вся прошлая выборка задним числом станет
 * «фоном», хотя тогда сбор шёл ТОЛЬКО во время показа.
 */
import { z } from 'zod';
import { MAX_SAMPLES, partitionSamples, stripNulls } from './diagRules.js';

/**
 * Строка с потолком длины, которая ОБРЕЗАЕТ, а не отбивает.
 *
 * 🔴 Ровно на этом мы потеряли сутки телеметрии. У `enc.encoder` стоял `.max(64)`, а когда показ стал
 * публиковаться двумя слоями, libwebrtc начал отдавать составное имя вида
 * `SimulcastEncoderAdapter (NVIDIA H264 Encoder, NVIDIA H264 Encoder)` — 66 символов. Схема отбивала
 * КАЖДЫЙ срез с показом, у одного человека 118 подряд.
 *
 * Потолок здесь нужен только чтобы чужая строка не раздула базу. Для этой цели обрезка ничем не хуже
 * отказа — а вот цена отказа оказалась несоизмеримой: вместо длинного имени мы теряли весь замер.
 * Косметическое ограничение не должно уничтожать данные.
 */
const cappedString = (max: number) => z.string().transform((s) => s.slice(0, max));

const Sample = z.object({
  t: z.number(),
  /**
   * Фаза среза: 0 — человек просто сидит в голосе, 1 — идёт показ экрана.
   *
   * Сбор начинается со ВХОДА В КАНАЛ, а не со старта показа, именно ради этой разметки: без фоновых
   * срезов «до» нельзя отделить нагрузку, которую добавил показ, от той, что машина ела и так.
   * `.default(1)` именно потому, что отчёты клиентов прошлых версий этого поля не несут — а там сбор
   * шёл ТОЛЬКО во время показа, то есть все их срезы по смыслу единицы. Ноль по умолчанию задним
   * числом переписал бы всю прошлую выборку в «фон». Разметка по времени — `shares` в контексте.
   */
  sharing: z.union([z.literal(0), z.literal(1)]).default(1),
  procs: z.array(
    z.object({
      name: cappedString(64),
      pid: z.number(),
      handles: z.number(),
      gdi: z.number(),
      user: z.number(),
      ws_mb: z.number(),
      gpu_dedicated_mb: z.number(),
      gpu_shared_mb: z.number(),
      /**
       * Доля процессора ИМЕННО этого процесса, нормированная на все ядра (100 = вся машина, как в
       * диспетчере задач). Необязательное — отчёты клиентов прошлых версий его не несут.
       *
       * Зачем: общая загрузка без этого нечитаема. У человека при старте показа процессор прыгал
       * с 19 до 47 %, и понять, наши это проценты или его игры, было НЕЧЕМ — а от ответа зависит,
       * оптимизировать нам конвейер захвата или нет.
       */
      cpu_pct: z.number().optional(),
      /**
       * Виртуальная память процесса (commit). НЕ дубль `ws_mb`: рабочий набор — что сейчас в
       * оперативке, commit — что забронировано у системы. Кончается всегда второе.
       */
      commit_mb: z.number().optional(),
    }),
  ),
  gpu_adapter_total_mb: z.number(),
  /**
   * Настоящее состояние видеокарты (NVML). Необязательное сразу по двум причинам: у людей с AMD или
   * Intel этих данных нет в принципе, и отчёты от клиентов ДО этой версии их не несут.
   *
   * Зачем именно эти поля: процент загрузки видеокарты сам по себе ничего не доказывает — на рабочем
   * столе карта роняет частоту почти на порядок (замеряли: 210 МГц против 2130 максимума при
   * «загрузке 18%»), так что без частоты и состояния производительности «занята на 75%» нечитаемо.
   * А `vram_total_mb` — единственный способ понять, упирается человек в видеопамять или нет; именно
   * переполнение видеопамяти даёт рывки в играх, которые люди описывают как «всё лагает».
   */
  gpu: z
    .object({
      name: cappedString(64),
      vram_used_mb: z.number(),
      vram_total_mb: z.number(),
      clock_mhz: z.number(),
      clock_max_mhz: z.number(),
      mem_clock_mhz: z.number(),
      pstate: z.number(),
      throttle_reasons: z.number(),
      util_gpu: z.number(),
      util_mem: z.number(),
      util_encoder: z.number(),
      power_w: z.number(),
      power_limit_w: z.number(),
      temp_c: z.number(),
    })
    .optional(),
  /**
   * Метрики кодирования исходящего видео — под «рваные кадры». Системные счётчики про поток не знают
   * ничего; `limitation` же прямо называет, во что упёрся кодировщик (процессор, канал, разрешение).
   */
  enc: z
    .object({
      frames_encoded: z.number(),
      frames_sent: z.number(),
      fps: z.number(),
      limitation: cappedString(32),
      limited_cpu_s: z.number(),
      limited_bw_s: z.number(),
      pli: z.number(),
      nack: z.number(),
      width: z.number(),
      height: z.number(),
      target_bitrate: z.number(),
      encode_ms_per_frame: z.number(),
      /**
       * Дальше — только НАТИВНЫЙ показ (на десктопе он всегда такой). Метрики берутся из Rust:
       * нативный показ публикует отдельный участник со своим соединением, и у основного клиента
       * исходящего видео нет вовсе — из-за этого метрики кодирования не собрались ни разу у тех,
       * ради кого делались.
       *
       * `encoder` — прямой ответ на «почему при показе лагает игра»: `NvCodec…` значит аппаратный
       * кодировщик, `OpenH264`/`libvpx` — софтверный, который ест процессор поверх игры.
       */
      encoder: cappedString(128).optional(),
      power_efficient: z.boolean().optional(),
      rtt_ms: z.number().optional(),
      fraction_lost: z.number().optional(),
      packets_lost: z.number().optional(),
      resolution_changes: z.number().optional(),
      key_frames: z.number().optional(),
      codec: cappedString(128).optional(),
      /**
       * Самолечение залипшего показа (#111): сколько раз публикация пересоздавалась сама и сколько
       * секунд подряд залипание держится в момент среза.
       *
       * 🔴 Ради этой пары самолечение вообще можно выпускать. Механизм, который тихо перезапускает
       * показ, без счётчика прячет от нас настоящую беду: картинка «как будто наладилась», а
       * сколько раз её для этого чинили — неизвестно. `heals` у того, кто не жаловался, = ложное
       * срабатывание; `stuck_s` без последующего `heals` = порог промахнулся мимо настоящего.
       */
      heals: z.number().optional(),
      stuck_s: z.number().optional(),
    })
    .optional(),
  /**
   * Конвейер ЗАХВАТА — до кодирования (2026-08-22).
   *
   * 🔴 Разбор упёрся в стену: 4 кадра вместо 30, кодировщик простаивает, упор в процессор, наш
   * процесс занимает ровно одно ядро — 250 мс на кадр. Перевод кадра 2560×1440 стоит порядка 10 мс,
   * и куда девались остальные 96 % времени, сказать было нечем. Эти поля делят время на «снять» и
   * «подготовить» и заодно косвенно говорят, каким способом снимается экран: быстрый путь через
   * видеокарту — единицы миллисекунд, старый через копирование всего экрана — сотни.
   *
   * `src_*` — РЕАЛЬНЫЙ размер источника, не путать с `enc.width/height` (те про сеть). Снижение
   * качества показа не уменьшает работу над исходником, и без этих чисел это не видно.
   */
  cap: z
    .object({
      capture_ms: z.number(),
      convert_ms: z.number(),
      src_width: z.number(),
      src_height: z.number(),
      frames_captured: z.number(),
      frames_late: z.number(),
      /**
       * Время захвата за последние ~5 секунд (#111) — в отличие от `capture_ms`, среднего с начала
       * показа. После часа тяжёлой игры среднее остаётся высоким навсегда, и по нему нельзя понять,
       * освободилась ли видеокарта; а именно от этого зависит, залипание перед нами или честная
       * нагрузка.
       */
      capture_ms_now: z.number().optional(),
    })
    .optional(),
  /**
   * Сторона ЗРИТЕЛЯ — что человек ПРИНИМАЕТ.
   *
   * 🔴 Самая большая дыра, закрытая последней. Пульсация картинки у всего канала (#109) шла от
   * ОДНОГО зрителя, просившего опорные кадры полтора раза в секунду; чтобы его найти, пришлось
   * руками читать логи сервера. `pli_sent` — ровно то число, которое сделало бы виновника видимым
   * за минуту вместо часа. Меряется ВСЕГДА, а не только при показе: тот зритель сам не показывал.
   */
  sub: z
    .object({
      streams: z.number(),
      pli_sent: z.number(),
      packets_lost: z.number(),
      jitter_ms: z.number(),
      fps_min: z.number(),
    })
    .optional(),
  /**
   * Отвечает ли оболочка (`explorer`) и доходят ли до нас клавиши.
   *
   * 🔴 Появилось после разбора живого случая: Alt+Tab и «Пуск» мертвы, а Alt+F4 и Ctrl+Shift+Esc
   * работают — то есть отказала ОБОЛОЧКА, а не ввод, и в счётчиках объектов это не видно вообще
   * (они ровные). `hook_idle_ms` в паре с `input_idle_ms` ловит второй случай: человек вводит, а
   * низкоуровневый хук молчит = Windows выбросила его из цепочки за неответ, молча.
   * Всё необязательное — отчёты клиентов прошлых версий этих полей не несут.
   */
  shell_hung: z.boolean().optional(),
  taskbar_hung: z.boolean().optional(),
  input_idle_ms: z.number().optional(),
  hook_idle_ms: z.number().optional(),
  /** Объекты по ВСЕЙ системе + сколько процессов не удалось открыть (сумма настолько же неполна). */
  sys_gdi_total: z.number().optional(),
  sys_user_total: z.number().optional(),
  sys_procs_denied: z.number().optional(),
  // Общая нагрузка. `.default(0)` — чтобы отчёты от клиентов ДО этой версии не отбивались целиком:
  // старые срезы этих полей не несут, но остальное в них по-прежнему ценно.
  cpu_pct: z.number().default(0),
  gpu_pct: z.number().default(0),
  ram_used_mb: z.number().default(0),
  ram_total_mb: z.number().default(0),
  /**
   * ВИРТУАЛЬНАЯ память системы (commit) — оперативка плюс файл подкачки.
   *
   * 🔴 Появилось после аварии 2026-08-22: Windows объявила «слишком мало виртуальной памяти», клиент
   * упал на неудачном выделении, а `ram_used_mb` показывал спокойные 24 из 47 ГБ. Мерили не ту
   * величину, и отказ был невидим в принципе. Необязательные — отчёты прошлых версий их не несут.
   */
  commit_used_mb: z.number().optional(),
  commit_total_mb: z.number().optional(),
  /**
   * Число логических ядер. Без него доля процессора НЕЧИТАЕМА: она нормирована на все ядра, поэтому
   * «8 %» на 12 потоках — занятое ядро целиком, а на 4 потоках — треть ядра.
   */
  cores: z.number().optional(),
});

const Body = z.object({
  kind: z.literal('screenshare'),
  /**
   * Контекст сессии: версия, ОС, длительность, плюс `shares` — когда включали показ и с какими
   * настройками. Без этого цифры не с чем соотнести.
   */
  context: z.record(z.unknown()),
  /** Метки «сломалось» — момент, когда человек нажал хоткей. Ради них всё и затевалось. */
  marks: z.array(z.number()).max(200),
  /**
   * 🔴 Срезы разбираем ПОШТУЧНО и негодные выбрасываем, а не отбиваем отчёт целиком.
   *
   * Раньше здесь стоял `z.array(Sample)`, и один негодный срез стоил ВСЕГО отчёта: клиент получал
   * 400, глушил его и продолжал слать такие же — телеметрия человека замолкала насмерть. Так и
   * случилось 2026-08-22 после появления второго слоя качества: часть чисел приезжала `null`,
   * отбивалось 86 отчётов из 284, и за сутки не сохранилось НИ ОДНОГО среза с показом.
   * Сколько выброшено — видно в `samplesDropped` (см. ниже): молча терять данные нельзя.
   */
  samples: z
    .array(z.unknown())
    .max(MAX_SAMPLES)
    .transform((arr) => {
      // 🔴 Запоминаем ПЕРВУЮ причину отказа. Счётчик потерь без причины — тупик: видно, что данные
      // теряются, и нельзя понять почему. Ровно в такой тупик упёрлись 2026-08-22 на отчёте, где
      // из двадцати одного среза доехало два.
      let firstError: string | undefined;
      const r = partitionSamples(arr, (x) => {
        // Пустые поля убираем ДО разбора: иначе один сорвавшийся счётчик убивает весь срез, а
        // умолчание в схеме от пустого значения не защищает (см. `stripNulls`).
        const p = Sample.safeParse(stripNulls(x));
        if (p.success) return p.data;
        if (!firstError) {
          const i = p.error.issues[0];
          firstError = `${i?.path?.join('.') || '(корень)'}: ${i?.message ?? 'неизвестно'}`;
        }
        return undefined;
      });
      return { ...r, firstError };
    }),
});

/** Разобрать тело отчёта. `null` — тело не подходит под схему (роут отвечает 400). */
export function parseDiagReport(body: unknown): z.infer<typeof Body> | null {
  const r = Body.safeParse(body);
  return r.success ? r.data : null;
}

/**
 * Чистые правила начисления ГусКоинов — БЕЗ базы, Redis и часов внутри.
 *
 * План целиком — `docs/guscoins-plan.md`, зонтик — #117. Здесь живёт вся арифметика экономики,
 * и цена ошибки тут выше обычной: это чужие деньги, а спор «почему мне начислили столько» разрешают
 * ровно этим кодом.
 *
 * 🔴 **Ни одного числа в коде.** Ставка, множители, потолок, затухание и налог приходят из настроек
 * сервера (ползунки в админке — требование к фиче). Константы здесь только структурные: длина
 * периода ставки и точность дробей.
 */

/** Ставка задаётся «за 5 минут» — как у Twitch и Arcane, чтобы порядок величин был привычным. */
export const RATE_PERIOD_S = 300;

/**
 * Точность накопления дробей.
 *
 * 🔴 Без неё экономика молча обкрадывает людей. Срез снимается раз в минуту, а ставка задана за
 * пять: при 10 монетах за 5 минут за минуту выходит 2 монеты, но при 7 — уже 1.4, и округление вниз
 * на каждом срезе теряло бы почти по половине монеты шестьдесят раз в час. Поэтому считаем в
 * тысячных и переносим остаток в следующий срез.
 */
export const MILLI = 1000;

/** Настройки экономики сервера — ровно то, что крутится ползунками. */
export interface EconomySettings {
  /** Монет за 5 минут присутствия при обычной компании (вдвоём). */
  ratePer5min: number;
  /** Процент ставки, когда человек в канале ОДИН. Ноль — не начислять вовсе. */
  alonePercent: number;
  /** Процент ставки, когда в канале трое и больше. */
  companyPercent: number;
  /** Максимум монет за сутки. 0 — без потолка. */
  dailyCap: number;
  /** После скольких минут в голосе за сутки ставка начинает резаться. 0 — не резать. */
  decayAfterMinutes: number;
  /** Во сколько процентов превращается ставка на каждом следующем таком отрезке. */
  decayPercent: number;
  /** Процент ставки, когда микрофон выключен. 100 — без штрафа (умолчание). */
  mutedPercent: number;
  /** Процент ставки с надетым «не слышу». Умолчание — четверть. */
  deafenedPercent: number;
  /**
   * Процент ставки в статусе «отошёл». Умолчание — четверть, как у «не слышу».
   * 🔴 Ради него всё и затевалось: без него «выключил микрофон на железе и ушёл» приносило полную
   * ставку до самого потолка, и честному сидению это проигрывало (запрос 04.09).
   */
  awayPercent: number;
  /**
   * Через сколько минут ПРИСУТСТВИЯ выплачивать накопленное. Умолчание — 10.
   *
   * ⚠️ Не путать со ставкой «за 5 минут» (`RATE_PERIOD_S`): та задаёт ЦЕНУ времени, эта — ШАГ
   * выплаты. Числа разные по смыслу, сводить в одно нельзя.
   */
  payoutMinutes: number;
  /**
   * Доначислять ли разницу при повышении ставки. К самой арифметике начисления отношения не имеет —
   * лежит здесь, потому что это одна из ручек владельца и ездит вместе с остальными.
   */
  compensateOnRaise: boolean;
}

/**
 * Состояние кошелька, которое участвует в расчёте одного среза.
 *
 * 🔴 **Заморозка недосиженного времени — это ОТСУТСТВИЕ механизма, и в этом её надёжность.**
 * Никакой сессии, таймера и события «человек ушёл»: отключился — эти поля просто перестали расти,
 * вернулся — снова растут. Переживает перезапуск бэкенда, падение и неделю отсутствия, потому что
 * лежит в строке кошелька, а не в памяти.
 * ⚠️ Тем и отличается от курсоров в `voiceActivity.ts`: те намеренно живут только в памяти, чтобы
 * долгий простой не мог быть записан как присутствие. Здесь требование обратное.
 */
export interface AccrualState {
  /**
   * Невыплаченная ЦЕННОСТЬ в тысячных монеты.
   *
   * 🔴 Ценность, а не секунды. Множители застывают здесь в момент среза; копили бы секунды —
   * девять минут в одиночку (25 %) и минута в компании (150 %) оплатились бы все десять по 150 %.
   */
  pendingMilli: number;
  /** Засчитанное присутствие с прошлой выплаты. */
  pendingSeconds: number;
  /**
   * Из чего сложится ближайшая выплата. Копится вместе с `pendingMilli` и обнуляется вместе с ней.
   *
   * 🔴 Нужно, чтобы журнал отвечал на «почему столько», а не только «сколько». Выплата собирается
   * из десятка срезов с разной обстановкой — к моменту выплаты она уже забыта, если её не копить.
   * ⚠️ Дельты СО ЗНАКОМ: множитель компании бывает надбавкой.
   * Инвариант: `baseMilli + deltaPresenceMilli + deltaCompanyMilli + deltaDecayMilli === pendingMilli`.
   */
  baseMilli: number;
  deltaPresenceMilli: number;
  deltaCompanyMilli: number;
  deltaDecayMilli: number;
  /** Сколько секунд в голосе уже засчитано за эти сутки (для затухания). */
  secondsToday: number;
  /** Сколько монет уже начислено за эти сутки (для потолка). */
  earnedToday: number;
}

/**
 * Один срез присутствия — то, что записал сборщик статистики.
 *
 * 🔴 **Статуса («в сети» / «отошёл» / «не беспокоить») здесь НЕТ и не будет.** Статус — это
 * сообщение другим людям, а не свидетельство отсутствия: человек ставит «нет на месте», чтобы его
 * не дёргали, и продолжает сидеть и играть со всеми. Начислять по нему — значит штрафовать за
 * вежливость и превращать выбор статуса в экономическое решение (решение 2026-08-28).
 *
 * По той же причине сюда не приехал и признак простоя ОС (`gv_os_idle_ms`): он есть только на
 * Windows-десктопе (то есть был бы налогом на тех, кто с телефона и из браузера) и не видит
 * геймпад — то есть промахивался бы ровно по играющим, которых мы как раз и хотим награждать.
 *
 * Фарм сдерживают не признаки присутствия, а экономика: множитель компании, суточный потолок и
 * затухание. Они работают одинаково на всех платформах и ничего не требуют от человека.
 */
export interface AccrualSample {
  seconds: number;
  /** Сколько ДРУГИХ людей было в канале. */
  peers: number;
  /**
   * ⚠️ Мьют и «не слышу» — единственные признаки состояния, которые сюда попали, и оба дают
   * ПРОЦЕНТ ставки под ползунком владельца, а не запрет. См. `presencePercent`.
   */
  muted: boolean;
  deafened: boolean;
  /** Человек «отошёл» — сам или автоматикой по простою ОС. Сильнее мьюта и «не слышу». */
  away: boolean;
}

/**
 * Из чего сложилась выплата — то, что уедет в журнал и покажется человеку словами.
 *
 * Всё в тысячных монеты, чтобы не терять точность на объяснении; в текст переводит клиент.
 */
export interface AccrualBreakdown {
  /** Сколько секунд присутствия оплачено этой выплатой. */
  seconds: number;
  /** Ставка за это время без единого множителя. */
  baseMilli: number;
  /** Вклад мьюта и «не слышу» (≤ 0). */
  presenceMilli: number;
  /** Вклад компании: минус в одиночку, ПЛЮС втроём и больше. */
  companyMilli: number;
  /** Вклад затухания (≤ 0). */
  decayMilli: number;
  /** Срезал ли итог суточный потолок — самая непонятная для человека причина. */
  cappedByDaily: boolean;
}

export interface AccrualResult {
  /** Сколько целых монет начислить прямо сейчас. */
  coins: number;
  /** Новое состояние кошелька. */
  next: AccrualState;
  /** Заполнен ТОЛЬКО когда монеты действительно начислены: объяснять нечего, пока не выплатили. */
  breakdown?: AccrualBreakdown;
}

/**
 * Множитель компании в процентах.
 *
 * 🔴 Главный анти-фарм-рычаг: чтобы фармить ночью в одиночку, надо смириться с четвертью ставки, а
 * чтобы получать полную — нужен живой человек рядом, то есть сговор двоих. Это же совпадает со
 * смыслом продукта: монеты за то, что вы общаетесь, а не за то, что процесс запущен.
 *
 * ⚠️ Один в канале — НЕ ноль по умолчанию (так решено): тот, кто зашёл первым и ждёт друзей,
 * должен получать. Пустой канал никого не притягивает, и за привычку «сижу, подтягивайтесь» стоит
 * немного платить.
 */
/**
 * Множитель за состояние микрофона и наушников, в процентах.
 *
 * 🔴 Умолчания (решение 2026-08-28): **мьют — 100 %, «не слышу» — 25 %.** Выключенный
 * микрофон НЕ означает отсутствия: человек слушает, читает чат, играет со всеми — просто дома
 * шумно или он ест. Штраф за это наказывал бы за вежливость к остальным. «Не слышу» — признак
 * другого рода: человек в разговоре не участвует вовсе, и четверть честнее и нуля (он всё-таки в
 * канале), и полной ставки.
 *
 * ⚠️ **«Не слышу» ПЕРЕКРЫВАЕТ мьют, множители не перемножаются.** Клиент при деафене глушит и
 * микрофон, поэтому такой срез приходит с обоими признаками сразу; перемножь их — и владелец,
 * поставивший мьюту 50 %, неожиданно получил бы 12.5 % вместо своих 25 %. Это не два независимых
 * состояния, а одно более сильное поверх другого.
 */
export function presencePercent(sample: AccrualSample, s: EconomySettings): number {
  /**
   * 🔴 «Отошёл» СИЛЬНЕЕ всех остальных состояний (04.09). Мьют не штрафуется намеренно — человек
   * слушает; «не слышу» даёт четверть — он в канале, но вне разговора. «Отошёл» означает, что его
   * нет у компьютера вовсе, и это единственное состояние, где полная ставка была бы платой за
   * пустое кресло. Им же закрывается обход «выключить микрофон на железе и уйти»: приложение о таком
   * мьюте не знает, а простой на уровне ОС видит.
   * ⚠️ Не перемножаем с мьютом по той же причине, что и «не слышу»: это одно состояние поверх
   * другого, а не два независимых.
   */
  if (sample.away) return s.awayPercent;
  if (sample.deafened) return s.deafenedPercent;
  if (sample.muted) return s.mutedPercent;
  return 100;
}

export function companyPercent(peers: number, s: EconomySettings): number {
  if (peers <= 0) return s.alonePercent;
  if (peers === 1) return 100;
  return s.companyPercent;
}

/**
 * Множитель затухания в процентах по тому, сколько человек уже просидел за сутки.
 *
 * Ступенчатый: каждый следующий отрезок длиной `decayAfterMinutes` умножает ставку ещё раз. При
 * пороге в 2 часа и 50 % это даёт привычное «первые два часа полностью, следующие два — вполовину,
 * дальше вчетверо» — и ночь превращается в копейки без единого запрета.
 *
 * ⚠️ Считается по НАЧАЛУ среза, а не по концу: иначе срез, пересёкший порог, целиком проваливался
 * бы в следующую ступень, и человек терял бы монеты за минуты, отсиженные ещё по полной ставке.
 */
export function decayPercent(secondsToday: number, s: EconomySettings): number {
  if (s.decayAfterMinutes <= 0 || s.decayPercent >= 100) return 100;
  const step = s.decayAfterMinutes * 60;
  const blocks = Math.floor(Math.max(0, secondsToday) / step);
  if (blocks <= 0) return 100;
  // Возводим в степень через цикл, а не `**`, чтобы остаться в целых процентах и не поймать
  // накопленную ошибку double на длинных сутках.
  let pct = 100;
  for (let i = 0; i < blocks; i++) {
    pct = Math.floor((pct * s.decayPercent) / 100);
    if (pct === 0) return 0; // дальше всё равно ноль — незачем крутить дальше
  }
  return pct;
}

/** Шаг выплаты в секундах присутствия. Минимум одна минута — ноль означал бы выплату на каждом срезе. */
export function payoutPeriodS(s: EconomySettings): number {
  return Math.max(60, Math.floor(s.payoutMinutes) * 60);
}

/**
 * Посчитать начисление за один срез.
 *
 * Срез снимается раз в минуту, а ВЫПЛАТА происходит раз в `payoutMinutes` присутствия. Между
 * выплатами посчитанная ценность копится в `pendingMilli`, а засчитанное время — в
 * `pendingSeconds`.
 *
 * 🔴 **Зачем разное зерно.** Минутный срез нужен, чтобы честно знать обстановку: сколько людей было
 * рядом и был ли выключен микрофон. Десятиминутный срез этого не скажет, а весь анти-фарм держится
 * ровно на этом. Выплата же редкая, чтобы прирост читался событием, а не незаметной капелью.
 *
 * Порядок множителей: ставка, потом состояние микрофона, потом компания, потом затухание, и в самом
 * конце — суточный потолок. Потолок последний намеренно: он предохранитель, а не участник формулы.
 *
 * ⚠️ `secondsToday` растёт ДАЖЕ когда монет не начислили (мьют, потолок, ноль по компании). Это не
 * оплошность: затухание меряет, сколько человек провёл в канале, а не сколько заработал. Иначе
 * посидевший три часа в мьюте возвращался бы к полной ставке, будто только зашёл.
 */
export function accrue(sample: AccrualSample, state: AccrualState, s: EconomySettings): AccrualResult {
  const seconds = Math.max(0, Math.floor(sample.seconds));
  const next: AccrualState = {
    pendingMilli: state.pendingMilli,
    pendingSeconds: state.pendingSeconds,
    baseMilli: state.baseMilli,
    deltaPresenceMilli: state.deltaPresenceMilli,
    deltaCompanyMilli: state.deltaCompanyMilli,
    deltaDecayMilli: state.deltaDecayMilli,
    secondsToday: state.secondsToday + seconds,
    earnedToday: state.earnedToday,
  };
  if (seconds === 0) return { coins: 0, next };

  // Потолок на сегодня выбран — дальше не копим ВОВСЕ, а не копим впрок. Иначе накопленное за ночь
  // вывалилось бы одной кучей ровно в полночь, когда потолок сбросится.
  if (s.dailyCap > 0 && state.earnedToday >= s.dailyCap) return { coins: 0, next };

  const rateMilli = Math.round((seconds * s.ratePer5min * MILLI) / RATE_PERIOD_S);
  const withPresence = Math.floor((rateMilli * presencePercent(sample, s)) / 100);
  const withCompany = Math.floor((withPresence * companyPercent(sample.peers, s)) / 100);
  const withDecay = Math.floor((withCompany * decayPercent(state.secondsToday, s)) / 100);

  next.pendingMilli = state.pendingMilli + withDecay;
  next.pendingSeconds = state.pendingSeconds + seconds;
  // Вклад каждого множителя — разностями между соседними шагами. Так объяснение считается ровно из
  // тех же чисел, что и сама сумма, и разойтись с ней не может.
  next.baseMilli = state.baseMilli + rateMilli;
  next.deltaPresenceMilli = state.deltaPresenceMilli + (withPresence - rateMilli);
  next.deltaCompanyMilli = state.deltaCompanyMilli + (withCompany - withPresence);
  next.deltaDecayMilli = state.deltaDecayMilli + (withDecay - withCompany);

  // Ещё не досидел до выплаты — ценность и время остаются в кошельке. Отключится сейчас — они там
  // и замёрзнут до его возвращения.
  if (next.pendingSeconds < payoutPeriodS(s)) return { coins: 0, next };

  let coins = Math.floor(next.pendingMilli / MILLI);
  let rest = next.pendingMilli % MILLI;
  let cappedByDaily = false;

  if (s.dailyCap > 0) {
    const room = Math.max(0, s.dailyCap - state.earnedToday);
    if (coins >= room) {
      coins = room;
      cappedByDaily = true;
      // Упёрлись в потолок — остаток дробей выбрасываем, по той же причине, что и выше.
      rest = 0;
    }
  }

  /**
   * 🔴 Период прошёл, а целой монеты не набралось — значит выплаты НЕ БЫЛО, и обнулять накопленное
   * нельзя (нашёл Codex, воспроизведено).
   *
   * Ловится при малой ставке: `ratePer5min=1`, `payoutMinutes=1` — каждую минуту набегает 0.2
   * монеты, ворота периода открыты каждый раз, а монета появляется только на пятый заход. Раньше
   * первые четыре захода стирали разбор, оставляя жить одни дроби, и в журнал уходило «одна монета
   * за 60 секунд и 0.2 монеты работы»: сама монета начислена верно, но объяснить её нечем, а
   * остальные 0.8 не объяснены вовсе. Ради такого объяснения журнал и заводился.
   *
   * ⚠️ Оговорка про потолок суток — СТРАХОВКА, а не живая ветка: выбранный потолок отсекается
   * раньше (см. ранний выход выше), поэтому «монет ноль И упёрлись в потолок» сейчас недостижимо.
   * Оставлено намеренно — если тот ранний выход когда-нибудь уберут, без неё дроби, выброшенные
   * потолком НАМЕРЕННО, начали бы копиться и вернулись бы следующим днём.
   */
  if (coins <= 0 && !cappedByDaily) return { coins: 0, next };

  const breakdown: AccrualBreakdown = {
    seconds: next.pendingSeconds,
    baseMilli: next.baseMilli,
    presenceMilli: next.deltaPresenceMilli,
    companyMilli: next.deltaCompanyMilli,
    decayMilli: next.deltaDecayMilli,
    cappedByDaily,
  };

  next.pendingMilli = rest;
  // Обнуляем, а НЕ вычитаем период: выплатили всю накопленную ценность целиком, значит и отсчёт
  // времени до следующей выплаты начинается с нуля. Вычитание оставило бы «оплаченные» секунды
  // работать на следующую выплату второй раз.
  next.pendingSeconds = 0;
  // Разбор уехал в журнал — копим следующий с чистого листа.
  next.baseMilli = 0;
  next.deltaPresenceMilli = 0;
  next.deltaCompanyMilli = 0;
  next.deltaDecayMilli = 0;
  next.earnedToday = state.earnedToday + coins;
  return { coins, next, breakdown };
}

/**
 * Часовой пояс, по которому считаются сутки экономики (Москва, UTC+3).
 *
 * 🔴 Нужен именно он, а не UTC: сутки обязаны совпадать с календарным днём ТОГО, КТО СИДИТ В
 * КАНАЛЕ. По UTC «полночь» наступала бы в три часа ночи по Москве — то есть посреди вечера у
 * половины людей, и суточный потолок сбрасывался бы им прямо во время посиделки.
 */
export const DAY_TZ_OFFSET_HOURS = 3;

/**
 * Ключ суток для среза: `ГГГГ-ММ-ДД` местной даты, к которой он относится.
 *
 * Граница — **местная полночь** (так решено). Прибавляем смещение пояса и берём дату: так
 * «сегодня» в экономике означает ровно то же, что «сегодня» в разговоре.
 *
 * ⚠️ Известное следствие, оставленное осознанно: полуночники, сидящие в канале в 00:00, получают
 * сброс потолка и затухания посреди вечера — одна посиделка разрезается на «до» и «после».
 * Альтернатива (граница под утро) выглядела бы для человека произвольной, а совпадение с
 * календарным днём объяснимо без единого слова.
 */
export function dayKey(at: Date): string {
  const local = new Date(at.getTime() + DAY_TZ_OFFSET_HOURS * 60 * 60 * 1000);
  return local.toISOString().slice(0, 10);
}

/**
 * Начало суток, к которым относится этот момент, — та самая местная полночь из `dayKey`.
 *
 * ⚠️ Нужна там, где суточное окно спрашивают у БАЗЫ (например «сколько этот человек прислал тому за
 * сегодня» по журналу): счётчики в кошельке для пары не годятся, а строковый ключ суток в `WHERE`
 * не поставишь. Считается из того же смещения, что и `dayKey`, — иначе «сегодня» у счётчиков и
 * «сегодня» у журнала разъехались бы на три часа.
 */
export function dayStart(at: Date): Date {
  const local = new Date(at.getTime() + DAY_TZ_OFFSET_HOURS * 60 * 60 * 1000);
  const midnightLocal = Date.UTC(local.getUTCFullYear(), local.getUTCMonth(), local.getUTCDate());
  return new Date(midnightLocal - DAY_TZ_OFFSET_HOURS * 60 * 60 * 1000);
}

/**
 * Идентификатор сезона: время года плюс год.
 *
 * ⚠️ Зима переходит через Новый год, поэтому декабрь относится к зиме СЛЕДУЮЩЕГО года — иначе
 * «зима 2026» означала бы два разных куска календаря, разнесённые на одиннадцать месяцев.
 */
/**
 * Длина сезона.
 *
 * 🔴 Помесячная разбивка — по запросу. Времена года дают долгий сезон (три месяца), и это
 * осознанный выбор ради «старожилы не занимают топ навсегда»; но у него есть обратная сторона —
 * смысл появляется только к концу, а корона меняется четыре раза в год. Месяц даёт двенадцать
 * поводов и живую гонку. Что лучше для семнадцати друзей — решать по живому, поэтому это ползунок,
 * а не константа.
 *
 * ⚠️ **Смена разбивки — это смена календарной сетки, а не «новый сезон с этого момента».** Новый
 * сезон — то окно новой сетки, в котором мы уже находимся, и заработанное с его начала уже в нём.
 * Старый сезон подводится досрочно только за часть ДО начала нового окна (`freezeWindow`), счётчики
 * кошельков пересчитываются по журналу (`rebaseWallets` в `seasons.ts`). 🔴 Разбивку обязан
 * получать КАЖДЫЙ вызов `seasonId`/`rollPeriods` — умолчание `quarter` существует только ради
 * старых тестов. Аудит 03.09 нашёл три вызова без неё, и на помесячном сервере они давали нулевой
 * счётчик в кошельке, подпись «Осень» вместо «Сентябрь» и обнуление сезона обоим при каждом типе.
 */
export type SeasonLength = 'quarter' | 'month';

/**
 * Идентификатор сезона.
 *
 * ⚠️ Помесячные идентификаторы начинаются с `m` (`m2026-09`) намеренно: по формату всегда видно,
 * какой разбивкой сделан сезон, и `seasonRange` не приходится ничего угадывать. Разбор старых
 * записей после смены ползунка от этого продолжает работать.
 */
export function seasonId(at: Date, length: SeasonLength = 'quarter'): string {
  if (length === 'month') {
    const local = new Date(at.getTime() + DAY_TZ_OFFSET_HOURS * 60 * 60 * 1000);
    return `m${local.getUTCFullYear()}-${String(local.getUTCMonth() + 1).padStart(2, '0')}`;
  }
  return quarterSeasonId(at);
}

function quarterSeasonId(at: Date): string {
  // ⚠️ В ТОМ ЖЕ ПОЯСЕ, что и сутки (#124, С6). Раньше здесь стоял чистый UTC, и сезон переключался
  // в 03:00 по Москве: первые три часа 1 декабря числились ещё осенью, а подпись «Зима 2026/27» у
  // полуночников в новогоднюю ночь врала. Одна валюта — одни часы; две разные границы в одной
  // фиче никто не удержит в голове.
  const local = new Date(at.getTime() + DAY_TZ_OFFSET_HOURS * 60 * 60 * 1000);
  const m = local.getUTCMonth(); // 0..11
  const y = local.getUTCFullYear();
  if (m === 11) return `winter-${y + 1}`; // декабрь — уже зима будущего года
  if (m <= 1) return `winter-${y}`;
  if (m <= 4) return `spring-${y}`;
  if (m <= 7) return `summer-${y}`;
  return `autumn-${y}`;
}

/**
 * Границы сезона как МОМЕНТЫ времени.
 *
 * 🔴 Нужны для заморозки итогов: победитель считается по ЖУРНАЛУ за окно сезона, а не по счётчику
 * `season_earned`. Счётчик обнуляется лениво, у каждого в свой момент, и человек, чей тик успел
 * пройти в новом сезоне раньше заморозки, выпал бы из итогов вовсе. Журнал такого порядка не знает.
 *
 * ⚠️ Границы в том же поясе, что и сутки (UTC+3): сезон обязан меняться тогда же, когда меняется
 * дата, иначе первые три часа первого декабря числятся в разных сезонах у разных подсистем.
 * ⚠️ Зима переходит через Новый год: `winter-2027` — это декабрь 2026 плюс январь и февраль 2027.
 */
export function seasonRange(id: string): { from: Date; to: Date } {
  const local = (y: number, monthIndex: number) =>
    new Date(Date.UTC(y, monthIndex, 1) - DAY_TZ_OFFSET_HOURS * 60 * 60 * 1000);
  // Помесячный сезон: `m2026-09`.
  if (/^m\d{4}-\d{2}$/.test(id)) {
    const y = Number(id.slice(1, 5));
    const m = Number(id.slice(6, 8)) - 1;
    return { from: local(y, m), to: local(y, m + 1) };
  }
  const [kind, yearRaw] = id.split('-');
  const year = Number(yearRaw);
  switch (kind) {
    case 'winter':
      // Декабрь ПРОШЛОГО года — начало зимы этого.
      return { from: local(year - 1, 11), to: local(year, 2) };
    case 'spring':
      return { from: local(year, 2), to: local(year, 5) };
    case 'summer':
      return { from: local(year, 5), to: local(year, 8) };
    default:
      return { from: local(year, 8), to: local(year, 11) };
  }
}

/**
 * Окно, за которое морозятся итоги сезона `finished`, когда текущим стал `current`; `null`, если
 * морозить нечего.
 *
 * На естественной границе это всё окно сезона: новый начинается ровно там, где кончился старый.
 * При смене разбивки — только часть старого окна ДО начала нового: переключили осень на месяцы
 * 15 октября — осень подводится за сентябрь, а октябрь целиком принадлежит сезону «Октябрь». Так
 * каждая монета журнала попадает ровно в один замороженный итог.
 *
 * 🔴 Сезон, начавшийся в том же окне, что и новый, не подводится вовсе: переключили на месяцы
 * третьего сентября — осень и сентябрь начались в один день, и трёхдневная осень с короной за неё
 * была бы нелепостью. Она просто продолжается под именем «Сентябрь». Правило одно на оба
 * направления: возврат к временам года двадцатого сентября тоже ничего не морозит — сентябрь
 * поглощён осенью, и первого декабря осень подведётся целиком.
 *
 * ⚠️ Возврат к длинной сетке ПОСЛЕ уже закрытых коротких сезонов считает их месяцы второй раз —
 * в итоге длинного. Это честный итог длинного сезона, а не ошибка; резать его по уже выданным
 * коронам значило бы подводить осень без сентября.
 */
export function freezeWindow(finished: string, current: string): { from: Date; to: Date } | null {
  const f = seasonRange(finished);
  const c = seasonRange(current);
  const to = new Date(Math.min(f.to.getTime(), c.from.getTime()));
  return to.getTime() > f.from.getTime() ? { from: f.from, to } : null;
}

/**
 * Носится ли корона за итог, замороженный в момент `frozenAt`, прямо сейчас.
 *
 * 🔴 Корона живёт в том сезоне, в котором её выдали, и ровно один сезон: сезон момента заморозки
 * сравнивается с сезоном «сейчас», оба по ТЕКУЩЕЙ разбивке. Момент заморозки от разбивки не
 * зависит, поэтому переключение сетки корону не роняет. Прежнее правило сравнивало по моменту
 * ОКОНЧАНИЯ закрытого сезона: осень, подведённая досрочно в октябре, кончается первого декабря, и
 * под месяцами это уже «Декабрь» — корона пропадала сразу после переключения и всплывала спустя
 * полтора месяца, когда её сезон давно прошёл.
 */
export function wearsCrown(frozenAt: Date, now: Date, length: SeasonLength): boolean {
  return seasonId(frozenAt, length) === seasonId(now, length);
}

/**
 * Причины журнала, которые считаются ЗАРАБОТКОМ.
 *
 * 🔴 Ровно те же, от которых растут `earned_total`/`season_earned` (`countsAsEarned`). Входящие
 * типы, выдачи модератора, доначисление при смене ставки и покупки сюда НЕ входят — иначе место в
 * сезонной таблице покупалось бы переводом с альта, ради чего альтов и заводят.
 * ⚠️ Список ОДИН на весь проект: разойдись он с `countsAsEarned` — замороженные итоги перестали бы
 * совпадать с тем, что люди видели в кошельке весь сезон.
 */
/**
 * Причины, считающиеся ЗАРАБОТАННЫМ — то, что растит место в сезонной таблице.
 *
 * 🔴 Сюда попадают только СВОИ источники: голос, пойманный гусь, стрик и ретроначисление за них же.
 * Входящие типы и выдачи модератора не попадают НИКОГДА — иначе место в таблице покупается
 * переводом с альта, ровно ради чего альтов и заводят.
 * ⚠️ Список обязан совпадать с тем, что реально пишет `countsAsEarned`/`creditVoiceTx`. Забудешь
 * дописать новый источник — заморозка итогов сезона недосчитает его, а кошелёк посчитает: место в
 * таблице разъедется с числом в кошельке, и объяснить это будет нечем.
 */
/**
 * План на смену ставки: проходить ли по кошелькам и тратить ли тумблер (вынос по разбору Codex).
 *
 * 🔴 Раньше это решение было размазано по маршруту тремя условиями, и проверить одноразовость было
 * НЕЧЕМ: тест доказывал лишь, что повторный вызов чистой `raiseCompensation` даёт то же число, —
 * то есть арифметику, а не правило. А правило тут главное: забытый включённым тумблер превращает
 * калибровку в станок (на каждом «вверх» доначисляет, на «вниз» не отыгрывает).
 */

/**
 * Надо ли вообще идти по кошелькам.
 *
 * ⚠️ Проверка «ставка выросла» здесь, а не в цикле: раньше маршрут ходил по ВСЕМ кошелькам даже
 * когда ставку опустили, и каждому считал ноль. На сервере с сотней кошельков это сотня лишних
 * запросов на каждое движение любого другого ползунка.
 */
export function shouldCompensate(toggleOn: boolean, before: number | undefined, after: number): boolean {
  if (!toggleOn) return false;
  if (before === undefined || before <= 0) return false;
  return after > before;
}

/**
 * Гасить ли тумблер по итогам прохода.
 *
 * 🔴 Гасим ТОЛЬКО если что-то реально доначислилось. Ставку подняли, а кошельки пустые — повышения
 * фактически не произошло, и тумблер, взведённый под одно осознанное повышение, обязан дожить до
 * настоящего.
 */
export function shouldSpendToggle(compensated: number): boolean {
  return compensated > 0;
}

export const EARNED_REASONS = ['voice', 'retro', 'goose', 'streak'] as const;

export const SEASON_LABEL: Record<string, string> = {
  winter: 'Зима',
  spring: 'Весна',
  summer: 'Лето',
  autumn: 'Осень',
};

/** Человеческое имя сезона: `winter-2027` → «Зима 2026/27». */
const MONTH_NAMES = [
  'Январь', 'Февраль', 'Март', 'Апрель', 'Май', 'Июнь',
  'Июль', 'Август', 'Сентябрь', 'Октябрь', 'Ноябрь', 'Декабрь',
];

export function seasonName(id: string): string {
  if (/^m\d{4}-\d{2}$/.test(id)) {
    return `${MONTH_NAMES[Number(id.slice(6, 8)) - 1]} ${id.slice(1, 5)}`;
  }
  const [kind, yearRaw] = id.split('-');
  const label = SEASON_LABEL[kind] ?? kind;
  const year = Number(yearRaw);
  if (!Number.isFinite(year)) return label;
  // Зима лежит на стыке двух лет — подписываем обоими, иначе непонятно, о какой именно речь.
  return kind === 'winter' ? `${label} ${year - 1}/${String(year).slice(2)}` : `${label} ${year}`;
}

/**
 * Привести состояние кошелька к текущим суткам и сезону.
 *
 * Ленивое: сравниваем сохранённые ключи с нынешними и обнуляем, что протухло. Так переход переживает
 * и простой сервера, и человека, не заходившего полгода, — ловить конкретную полночь не нужно.
 *
 * 🔴 Сезон обнуляет ТОЛЬКО счётчик сезона. Ни `balance`, ни `earned_total` не трогаются: смена
 * сезона, отбирающая накопленное, читается как кража.
 * ⚠️ Для ТАБЛИЦЫ ЛИДЕРОВ одного этого мало — тот, кто не заходил с зимы, обнулит свой счётчик только
 * собственным тиком и до тех пор висел бы весной в топе. Запрос топа обязан фильтровать по текущему
 * `season_id` (поймал Codex).
 */
export function rollPeriods<T extends { day: string; seasonId: string; secondsToday: number; earnedToday: number; seasonEarned: number }>(
  state: T,
  now: Date,
  length: SeasonLength = 'quarter',
): T {
  const day = dayKey(now);
  const season = seasonId(now, length);
  const next = { ...state };
  if (next.day !== day) {
    next.day = day;
    next.secondsToday = 0;
    next.earnedToday = 0;
    // 🔴 `pendingMilli` и `pendingSeconds` полночь НЕ трогает. Раньше здесь обнулялись дроби — они
    // стоили меньше монеты. Теперь это накопленная ценность недосиженного отрезка, и обнулить её
    // значит отнять у человека до десяти минут заработанного за то, что он сидел на границе суток.
    // Сбрасываются только СУТОЧНЫЕ счётчики — потолок и затухание.
  }
  if (next.seasonId !== season) {
    next.seasonId = season;
    next.seasonEarned = 0;
  }
  return next;
}

/**
 * Куда лечь заработанному: в счётчик ТЕКУЩЕГО сезона, с правильной меткой.
 *
 * 🔴 **Зачем отдельно от `rollPeriods`.** Тот приводит к сезону кошелёк ЦЕЛИКОМ (вместе с сутками) и
 * живёт в начислении за голос. А монеты приходят и мимо него — ретро, гусь, стрик, покупки, — и там
 * счётчик сезона рос, а метка `season_id` оставалась пустой. Последствия поймали 04.09 на первом
 * же дне живой экономики:
 *   • таблица лидеров фильтрует по `season_id = <текущий>`, и 8 человек с ретро в неё не попали
 *     вовсе — при непустом счётчике;
 *   • а у тех пятерых, кто успел посидеть в голосе, `rollPeriods` увидел «сезон сменился» (пусто ≠
 *     `autumn-2026`) и ОБНУЛИЛ счётчик: ретро сгорело из сезонного зачёта, 93 монеты вместо трёх
 *     тысяч.
 *
 * ⚠️ Метку ставим ВСЕГДА, даже когда `earned = 0`: пустая метка — это и есть та мина, а движение
 * монет по кошельку и есть момент, когда её честно обезвредить.
 */
export function seasonBump(
  prevSeasonId: string | null | undefined,
  season: string,
  prevSeasonEarned: number,
  earned: number,
): { seasonId: string; seasonEarned: number } {
  const same = prevSeasonId === season;
  return { seasonId: season, seasonEarned: (same ? prevSeasonEarned : 0) + Math.max(0, earned) };
}

/**
 * Граница между ретроначислением и живым начислением (#124, Д1).
 *
 * 🔴 Дыра, которая сработала бы в первый же запуск: ретро брало ВСЮ историю присутствия, а тикер
 * платит за неё же с момента включения экономики. Включил в пятницу, нажал «ретро» в воскресенье —
 * пятница и суббота оплачены дважды. Отметка «ретро уже выдано» ловила только второе ретро.
 *
 * Ответ: ретро платит строго ЗА ВРЕМЯ ДО `accrualSince`. Отметки нет (ретро жмут раньше, чем
 * включают) — значит вживую ещё ничего не начислялось, и граница — «сейчас».
 */
export function retroCutoff(accrualSince: Date | null | undefined, now: Date): Date {
  return accrualSince ?? now;
}

/**
 * Момент включения, который надо записать этим PATCH-ом, или `null`, если записывать нечего.
 *
 * ⚠️ Ставится ОДИН раз. Повторное включение после выключения границу не двигает: сдвинь её — и
 * ретро оплатит второй раз период, за который тикер уже заплатил. Цена — время «выключенного»
 * промежутка не оплачивает никто, и это правильная сторона ошибки.
 */
export function accrualStamp(current: Date | null | undefined, patchEnabled: boolean | undefined, now: Date): Date | null {
  if (current) return null;
  return patchEnabled === true ? now : null;
}

/**
 * Отсечь срезы, попадающие в живое начисление.
 *
 * ⚠️ Дублирует условие SQL-запроса намеренно. Запрос — это оптимизация (не тащить лишнее из базы),
 * а гарантия «за это уже платили» обязана держаться там, где её видно тесту. Строго `<`: срез
 * ровно в момент включения относим к живому начислению — ошибаться надо в сторону НЕ заплатить
 * дважды.
 */
export function beforeCutoff<T extends { at: Date }>(samples: T[], until: Date): T[] {
  return samples.filter((s) => s.at.getTime() < until.getTime());
}


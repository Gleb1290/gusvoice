/**
 * Уровни и звания — чистые правила, без базы и часов (этап 4, #117).
 *
 * 🔴 **ОДНА ШКАЛА: заработанные монеты, без коэффициентов за источник** (решение 03.09).
 * Сидение, пойманный гусь и стрик несут в уровень ровно те монеты, которые дали, и никакого
 * перевзвешивания сверху нет.
 *
 * Прежняя версия считала отдельные «очки участия» из трёх источников со своими весами (минута = 1,
 * бонус = 30, признавший человек = 20). Это развернули, и по делу: **вторую единицу измерения
 * пришлось бы объяснять**. «Ты накопил столько, но вот это ценится меньше, а вон то больше» — фраза,
 * которую невозможно уместить в интерфейс. Монеты человек и так видит; этап, выраженный в них,
 * объяснять не надо вовсе.
 *
 * 🔴 **Считаем от `earnedTotal`, а не от баланса.** Баланс тратится, и уровень от него падал бы при
 * каждой покупке. `earnedTotal` только растёт.
 *
 * 🔴 **Полученные типы в уровень НЕ идут вовсе** (решение 03.09, и это сказано человеку прямо
 * в кошельке). Тип кладёт монеты на баланс, но не в `earnedTotal` — по конструкции, иначе уровень
 * дарился бы с альта. Раньше «признание» было третьим источником по запросу; теперь решено
 * иначе, и умолчание об этом было бы хуже самого правила: человек, которого много типают, ждал бы
 * роста и не понимал, почему его нет.
 *
 * ⚠️ Следствие, принятое сознательно: уровень зависит от ставки. Поднимут её вдвое — все начнут
 * расти вдвое быстрее. Но упасть уровень не может никогда: `earnedTotal` монотонен.
 */

/**
 * Сколько ЗАРАБОТАННЫХ МОНЕТ нужно на этот уровень (нарастающим итогом).
 *
 * 🔴 Кривая квадратичная и остаётся такой (решение 03.09: «левелы нелинейны»). «Линейно» в той
 * формулировке относилось к ШКАЛЕ — одна единица без весов, — а не к шагу между уровнями. Ровный шаг
 * пустил бы старожила в бесконечный отрыв; квадрат его сдерживает, а первые уровни всё равно берутся
 * за вечер. Отраслевая норма: боты уровней в Discord строят кривую так же.
 *
 * 🔴 **Множитель 40 — по НЕДЕЛЕ ЖИВЫХ ДАННЫХ (04.09).** Прежний множитель 100 подбирался под
 * «средний человек зарабатывает около 800 монет в день» — оценку, которая, как выяснилось, завышала
 * доход вчетверо (разбор в шапке `economyStats.ts`). Настоящая медиана — **247 монет в день**, и
 * лестница оказалась растянута втрое: «Матёрый гусь» выходил не за 13 дней, а за 40, «Легенда стаи»
 * не за сезон, а за 274 дня — то есть до неё не дошёл бы никто и никогда.
 *
 * При 40 замысел восстановлен: «Матёрый гусь» ≈ 16 дней, «Легенда стаи» ≈ 110 дней (сезон с
 * небольшим), «Тот самый Гусь» ≈ полгода.
 * ⚠️ Числа остаются круглыми НАМЕРЕННО: «Матёрый гусь — 4000 монет» читается и запоминается.
 * ⚠️ Понижение порогов безопасно в любой момент: `earnedTotal` не меняется, звания только РАСТУТ.
 * Обратное движение — нет: у людей отобрались бы уже показанные звания.
 */
export function pointsForLevel(level: number): number {
  if (level <= 0) return 0;
  return 40 * level * level;
}

/**
 * Звания.
 *
 * ⚠️ Это ПЛЕЙСХОЛДЕРЫ под гусиную тему — названия выбирает владелец проекта. Список подобран так, чтобы менять
 * можно было одну строку: код нигде не завязан на конкретные слова.
 */
export const LEVEL_TITLES: { from: number; title: string }[] = [
  { from: 0, title: 'Птенец' },
  { from: 3, title: 'Гусёнок' },
  { from: 6, title: 'Свой в стае' },
  { from: 10, title: 'Матёрый гусь' },
  { from: 15, title: 'Вожак' },
  { from: 20, title: 'Старейшина' },
  { from: 26, title: 'Легенда стаи' },
  { from: 33, title: 'Тот самый Гусь' },
];

export function titleFor(level: number): string {
  let title = LEVEL_TITLES[0].title;
  for (const t of LEVEL_TITLES) if (level >= t.from) title = t.title;
  return title;
}

/** Одна ступень лестницы званий: звание и сколько заработанных монет на него нужно. */
export interface LevelStage {
  title: string;
  at: number;
}

/**
 * Лестница званий В ЧИСЛАХ — то, что показывают человеку в кошельке.
 *
 * 🔴 Запрос 03.09: «надо чтоб было видно прям этапы в числах, и этапы должны достигаться циферками
 * пользователя». Числа здесь — заработанные монеты, те же, что он видит в строке «за всё время»;
 * никакой второй единицы объяснять не надо.
 * ⚠️ Один источник с `LEVEL_TITLES`/`pointsForLevel`: дублировать лестницу на клиенте значило бы
 * показывать людям пороги, которых сервер не знает.
 */
export function levelStages(): LevelStage[] {
  return LEVEL_TITLES.map((t) => ({ title: t.title, at: pointsForLevel(t.from) }));
}

export interface LevelState {
  level: number;
  title: string;
  points: number;
  /** Сколько очков нужно на следующий уровень (нарастающим итогом). */
  nextAt: number;
  /** Доля пути до следующего уровня, 0…1 — для полоски. */
  progress: number;
}

/**
 * Уровень по очкам участия.
 *
 * ⚠️ После обращения кривой идёт страховка циклами: на ровных порогах накопленная погрешность с
 * плавающей точкой иначе заставляла бы уровень мигать туда-сюда.
 */
export function levelFor(points: number): LevelState {
  const p = Math.max(0, Number.isFinite(points) ? Math.floor(points) : 0);
  let level = Math.floor(Math.sqrt(p / 100));
  while (pointsForLevel(level + 1) <= p) level++;
  while (level > 0 && pointsForLevel(level) > p) level--;

  const at = pointsForLevel(level);
  const nextAt = pointsForLevel(level + 1);
  const span = Math.max(1, nextAt - at);
  return {
    level,
    title: titleFor(level),
    points: p,
    nextAt,
    progress: Math.min(1, Math.max(0, (p - at) / span)),
  };
}

/**
 * Уровень прямо из кошелька — то, чем пользуются маршруты.
 *
 * ⚠️ Берём ТОЛЬКО `earnedTotal`. Ни `balance` (он тратится — уровень падал бы при покупке), ни
 * полученные типы (их в `earnedTotal` нет по конструкции, иначе уровень дарился бы с альта).
 */
export function levelOf(w: { earnedTotal: number }): LevelState {
  return levelFor(w.earnedTotal);
}

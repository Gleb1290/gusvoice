/**
 * Ключ из внешнего мира → позиция каталога, или `null`. Строку от клиента иначе не принять.
 *
 * ⚠️ Через `Object.hasOwn`, а не простым индексом: обычный литерал наследует `constructor`,
 * `toString` и прочее от прототипа, и `SHOP_CATALOG['constructor']` вернул бы функцию вместо
 * `undefined`. Дальше по коду это «позиция каталога» без цены и без адресата — поймано тестом.
 */
export function shopItem(key: string): ShopItemSpec | null {
  if (!Object.hasOwn(SHOP_CATALOG, key)) return null;
  return (SHOP_CATALOG as Record<string, ShopItemSpec>)[key];
}

/**
 * Цена в монетах по цене в минутах и текущей ставке.
 *
 * 🔴 ОДНА формула на весь проект, и считает её сервер в момент покупки. Округление ВВЕРХ: цена не
 * должна проваливаться в ноль на дешёвых наградах при низкой ставке — бесплатная награда это не
 * щедрость, а дыра в стоке.
 * ⚠️ Ставка ноль означает, что монеты не начисляются вовсе; тогда и цена нулевая, и покупать не за
 * что — этот случай отсекается отдельно, здесь честно возвращаем ноль.
 */
export function priceCoins(priceMinutes: number, ratePer5min: number): number {
  const minutes = Math.max(0, Math.floor(priceMinutes));
  const rate = Math.max(0, Math.floor(ratePer5min));
  if (minutes === 0 || rate === 0) return 0;
  return Math.ceil((minutes * 60 * rate) / RATE_PERIOD_S);
}

/**
 * Цена анимированного аватара НА СЕРВЕРЕ, в минутах: своя цена сервера, но не ниже цены инстанса.
 *
 * 🔴 **Две ступени, и у каждой свой хозяин** (решение 14.09). Пол задаёт держатель инстанса —
 * аватар единственная награда, расходующая его хранилище и трафик постоянно (02.09). Сверху
 * владелец сервера вправе наценить: ему виднее, сколько зарабатывают его люди. Ниже пола — нельзя,
 * иначе владелец обошёл бы инстанс одной записью в каталог, ради чего строку сервера раньше и
 * игнорировали целиком.
 *
 * ⚠️ `max`, а не «сервер, если задан»: пол может ПОДНЯТЬСЯ уже после того, как владелец назначил
 * свою цену. Тогда его прежнее число окажется ниже пола — и выиграть обязан пол, без правок в базе.
 * ⚠️ `null`/`undefined` — своей цены нет (строку создал тумблер продажи, миграция 0059).
 */
export function avatarMinutesFor(instanceMinutes: number, serverMinutes: number | null | undefined): number {
  const floor = Math.max(0, Math.floor(instanceMinutes));
  if (serverMinutes === null || serverMinutes === undefined || !Number.isFinite(serverMinutes)) return floor;
  return Math.max(floor, Math.floor(serverMinutes));
}

/**
 * Можно ли владельцу сервера СОХРАНИТЬ такую цену аватара.
 *
 * 🔴 Отказ явный, а не молчаливое прижатие к полу. Прижми мы молча — владелец ввёл бы 1000, увидел
 * 1500 и решил бы, что поле сломано. Отказ с числом пола объясняет правило в момент ошибки.
 * ⚠️ Ровно пол — можно: «не ниже», а не «выше».
 */
export function avatarPriceAllowed(instanceMinutes: number, requestedMinutes: number): boolean {
  return Math.floor(requestedMinutes) >= Math.max(0, Math.floor(instanceMinutes));
}

/** Сколько минут сидения нужно, чтобы окупить эту цену — для подписи в каталоге. */
export function minutesForPrice(coins: number, ratePer5min: number): number {
  if (ratePer5min <= 0) return 0;
  return Math.ceil((coins * RATE_PERIOD_S) / (60 * ratePer5min));
}


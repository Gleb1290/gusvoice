/**
 * Чистые правила магазина наград — БЕЗ базы, Redis и часов внутри.
 *
 * Третий модуль правил экономики рядом с `coinRules.ts` (начисление) и `tipRules.ts` (перевод).
 * Отдельный по той же причине, что и они: покупка — операция над чужими деньгами, и ошибка тут не
 * «неудобно», а «списали и не выдали».
 *
 * 🔴 **Цена живёт в МИНУТАХ сидения, а не в монетах.** В монеты её переводит СЕРВЕР в момент
 * покупки по текущей ставке — не клиент и не каталог. Иначе один сдвиг ползунка ставки разом ломает
 * весь прайс: вчера награда стоила вечер, сегодня пять минут. Приём взят у Twitch, где цены наград
 * и назначают в минутах просмотра.
 */


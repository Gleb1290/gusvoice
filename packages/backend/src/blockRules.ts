/**
 * Чёрный список личных сообщений — чистые правила (#212, этап 0 ЛС, Р12). Без базы и сети.
 *
 * 🔴 Решение владельца 28.09: «как в Telegram» — заблокированный НИЧЕГО не узнаёт. Отказ с текстом
 * («человек ограничил сообщения») был бы проще, но он и есть сообщение о блокировке: его видно, и из-за
 * него блокировки обходят, заводя второй аккаунт. Поэтому у заблокированного всё выглядит как обычно,
 * а до того, кто заблокировал, не доходит ничего нового.
 *
 * ⚠️ Граница «минимального» списка: онлайн в ОБЩИХ серверах виден всем их участникам по устройству
 * присутствия, и прятать его от одного человека здесь не беремся — это этап 5 («кто может мне писать»).
 */

/** Что делать с новым личным сообщением, если получатель мог заблокировать автора. */
export interface DmDeliveryPlan {
  /** Пометить `withheld`: получатель не увидит его никогда. */
  withheld: boolean;
  /** Прислать получателю `dm.channel`/`dm.create` и разбудить его телефон. */
  notifyRecipient: boolean;
  /**
   * Сдвинуть время беседы. Строка беседы общая, и сдвиг поднял бы беседу в списке получателя — то есть
   * выдал бы ему, что заблокированный пишет. Автору его клиент поднимает беседу сам.
   */
  bumpConversation: boolean;
}

export function dmDeliveryPlan(recipientBlockedAuthor: boolean): DmDeliveryPlan {
  return recipientBlockedAuthor
    ? { withheld: true, notifyRecipient: false, bumpConversation: false }
    : { withheld: false, notifyRecipient: true, bumpConversation: true };
}

/** Видно ли сообщение этому человеку: придержанное видит только его автор. */
export function visibleToViewer(m: { withheld: boolean; authorId: string }, viewerId: string): boolean {
  return !m.withheld || m.authorId === viewerId;
}

/**
 * Доходит ли до собеседника действие автора — реакция и «печатает». Заблокированному молча подтверждаем у
 * него самого, собеседник не узнаёт ничего (реакции заблокированного скрыты и в истории — `dmReactionsFor`).
 *
 * ⚠️ Правка и удаление УЖЕ доставленного сообщения сюда не входят и доходят всегда (28.09, поймано на стенде):
 * база их хранит, и после перезагрузки собеседник всё равно видит новый текст или пустое место — придержанная
 * только вживую, правка давала два разных экрана одной переписки. Прятать правки заблокированного значит
 * хранить версии текста; это «кто может мне писать», этап 5. Придержанное (`withheld`) не доходит никогда.
 */
export function reachesPeer(peerBlockedActor: boolean): boolean {
  return !peerBlockedActor;
}

-- Кто поставил текущий статус: автоматика или человек (#118).
--
-- 🔴 Зачем на СЕРВЕРЕ, а не в localStorage клиента, как было. Статус общий для всех клиентов
-- человека, а признак «увели мы» лежал у каждого клиента свой. Из-за этого снять авто-«отошёл»
-- мог только тот клиент, который его поставил: любой другой (десктоп против браузера, телефон
-- против ПК, почищенные данные сайта) видел `away`, но признака у него не было — и не возвращал
-- статус НИКОГДА, сколько бы человек ни говорил и ни играл. Лечилось только руками.
--
-- Побочно закрывается второй дефект того же механизма: клиент ставил признак ДО сетевого вызова и
-- глотал его ошибку. Запрос падал — признак говорил «увели», а статус оставался `online`, и
-- авто-«отошёл» в этом клиенте умирал насовсем. Теперь признак и статус меняются одним UPDATE,
-- разъехаться им негде.
--
-- Умолчание `false` = «поставил человек»: для существующих строк это безопаснее, чем `true`.
-- Ошибочное `false` всего лишь не даст автоматике снять статус (человек снимет сам, как и раньше);
-- ошибочное `true` дало бы ей право перетереть статус, выставленный руками.
ALTER TABLE users ADD COLUMN IF NOT EXISTS presence_auto boolean NOT NULL DEFAULT false;

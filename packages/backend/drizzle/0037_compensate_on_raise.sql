-- Компенсировать ли людям повышение ставки (#117, решение 2026-08-30).
--
-- 🔴 Требование: «ползунки первый месяц я буду трогать часто, у людей из кошельков ничего не должно
-- испаряться». Отсюда УМОЛЧАНИЕ — `false`: при обычной калибровке балансы не трогаются вовсе, число
-- в кошельке не может уменьшиться ни при каком движении ползунка.
--
-- Включённый тумблер добавляет разницу при ПОВЫШЕНИИ ставки (при понижении не отнимает никогда).
-- ⚠️ Держать его включённым постоянно не стоит: на качелях вверх-вниз балансы раздуваются сверх
-- справедливого. Это режим для одного осознанного крупного повышения, а не для калибровки.
ALTER TABLE server_economy ADD COLUMN IF NOT EXISTS compensate_on_raise boolean NOT NULL DEFAULT false;

-- Журнал оповещений держателю о состоянии федерации (#139 F5, план §5.10).
--
-- **Зачем таблица, а не просто письмо по событию.** У каждого повода свой промежуток повтора: «связка
-- лежит» напоминает о себе раз в шесть часов, «ключ истекает» — раз в сутки, «нужна другая версия» —
-- один раз, пока версия та же. Без записи «когда слали в прошлый раз» это невозможно: инстанс либо
-- молчал бы после первого письма, либо слал бы их каждый круг проверки, и держатель перестал бы их
-- читать — а вместе с ними и те, что важны.
--
-- 🔴 Запись ПЕРЕЖИВАЕТ перезапуск намеренно. Держать это в памяти процесса означало бы, что каждая
-- выкатка бэкенда обнуляет счёт и письма идут заново — на инстансе, который обновляется по нескольку
-- раз в день, это превратило бы оповещения в шум.
CREATE TABLE IF NOT EXISTS federation_alerts (
  -- link-down | link-restored | key-expiring | version-needed | signature-storm | trust-lost |
  -- report-received — перечень и промежутки повтора живут в `alertRules.ts`.
  kind TEXT NOT NULL,
  -- Про какую связку. ПУСТАЯ СТРОКА — повод про нас самих (например, истекает свой ключ подписи).
  -- ⚠️ Не NULL: колонка входит в первичный ключ, а NULL в ключе Postgres не допускает — две записи
  -- «про нас» просто не отличились бы друг от друга.
  instance_id TEXT NOT NULL DEFAULT '',
  -- Чем этот повод отличается от такого же по виду: версия протокола, дата истечения ключа,
  -- идентификатор жалобы. Пусто — повод единственный в своём роде для этой связки.
  --
  -- ⚠️ Часть ключа, а не справочная колонка: сосед, обновившийся ещё раз, должен дать НОВОЕ
  -- оповещение, а не молчать под старой записью «один раз на связку и версию».
  detail TEXT NOT NULL DEFAULT '',
  first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_sent_at TIMESTAMPTZ,
  -- Повод исчез. Строку не удаляем: держатель должен видеть, что связка падала, даже когда она уже
  -- встала, — иначе «почему вчера никто не мог зайти» остаётся без ответа.
  resolved_at TIMESTAMPTZ,
  PRIMARY KEY (kind, instance_id, detail)
);

-- Баннер в админке спрашивает ровно «что сейчас не снято» — по этому индексу.
CREATE INDEX IF NOT EXISTS federation_alerts_open_idx ON federation_alerts (resolved_at) WHERE resolved_at IS NULL;

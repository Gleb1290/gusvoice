-- «Сидишь один — затухание не бьёт» (решение 28.10).
--
-- 🔴 Изъян прежнего правила: затухание считало ВСЁ время в голосе за сутки. Кто днём часами ждал
-- компанию один, к вечеру был уже подбит и в компании получал ~40 % от пришедших сразу. Теперь время
-- одному в затухание не идёт (`coinRules.ts`, `accrue`), а одиночный фарм держит свой суточный порог.
-- Модель на 60 днях боевых данных: ждуны 40 % → 94 %, эмиссия +4,7 %, одиночный фарм не больше 90
-- монет в сутки против ~146 по старому правилу.
--
-- `alone_cap` — монет одному за сутки; 0 = без порога (как у `daily_cap`). Умолчание 90 получают и
-- уже существующие строки: до этой миграции порога не было вовсе, чужого решения тут не перепишем.
ALTER TABLE server_economy ADD COLUMN IF NOT EXISTS alone_cap integer NOT NULL DEFAULT 90;
-- Ценность, набранная за сутки в одиночку, в тысячных монеты. Сбрасывается с остальными суточными
-- счётчиками при смене дня (`rollPeriods`).
ALTER TABLE coin_balances ADD COLUMN IF NOT EXISTS alone_earned_milli integer NOT NULL DEFAULT 0;

-- #212 (этап 0 ЛС, Р5): удаление «как в Telegram» — «Удалить у меня» / «Удалить у обоих». Решение владельца 28.09.
-- «У меня» сообщение не стирает: оно остаётся собеседнику, а у удалившего пропадает навсегда (выдача истории,
-- счётчик непрочитанного). Кто спрятал — id в массиве, а не строка в отдельной таблице: связь с users здесь не
-- нужна (аккаунт при удалении обезличивается, строка users остаётся) и не тянет за собой стража удаления аккаунта.
ALTER TABLE dm_messages ADD COLUMN IF NOT EXISTS hidden_for text[] NOT NULL DEFAULT '{}';

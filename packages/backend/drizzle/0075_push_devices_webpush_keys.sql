--
-- Телефон при регистрации присылает свой открытый ключ P-256 (`p256dh`) и секрет (`auth`), оба base64url;
-- бэкенд шифрует ими тело пуша (`pushCrypto.ts`). Пусто — старая установка без поддержки: ей уходит пуш
-- БЕЗ текста сообщения (только имя и «новое сообщение»), чтобы текст не лежал открытым и у неё.
-- Добавление столбцов, NULL по умолчанию — старый бэкенд и старые клиенты их не замечают.
ALTER TABLE push_devices ADD COLUMN IF NOT EXISTS p256dh text;

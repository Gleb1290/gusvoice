-- Потолок «от ОДНОГО человека за сутки» (#124, В2).
--
-- 🔴 Дыра в защите получателя. Потолок приёма (`tip_daily_in`, по умолчанию 100) при цене типа 5
-- забивается двадцатью типами ОДНОГО отправителя: кулдаун пары 10 секунд, то есть 200 секунд и 100
-- монет — и до конца суток человека не может типнуть больше НИКТО. Плюс двадцать «динь» подряд.
-- Формально каждый тип в своём праве, а по итогу один человек в одиночку и завалил получателя
-- звуками, и запер ему день от всех остальных.
--
-- ⚠️ Массовый тип резать нельзя — так решено: «иногда типают все вместе, потому что шутка была
-- шикарной». Этот потолок массовый тип и НЕ трогает: он про пару «кто→кому», а не про сумму от
-- всех. Село бомбит — на здоровье; один человек в одиночку — нет.
--
-- ⚠️ Потолок считается по ДОШЕДШИМ монетам (строки журнала `tip.in`), как и `tip_daily_in`.
-- При умолчаниях (тип 5, налог 20 % → доходит 4) это шесть типов одному человеку в сутки: чтобы
-- забить чужой потолок приёма в 100, теперь нужно минимум четверо разных отправителей.
-- 0 — потолок выключен.
ALTER TABLE server_economy ADD COLUMN IF NOT EXISTS tip_daily_pair integer NOT NULL DEFAULT 25;

-- Серверный мьют — отдельным фактом от собственного (#124, В1/К1).
--
-- 🔴 Категория, которую в замысле экономики не разбирали ВООБЩЕ: у прав модерации появилась
-- денежная цена. Срез писал `muted = сам замьютился ИЛИ замьютил модератор`, то есть право
-- `MUTE_MEMBERS` при первом же сдвиге ползунка `muted_percent` вниз превращалось в кнопку «лишить
-- заработка» — молча, без следа для жертвы (строк «плюс ноль» в журнале нет) и без возможности
-- прекратить это самой.
--
-- Теперь `muted` — ТОЛЬКО собственный микрофон, а действие модератора живёт рядом отдельным
-- столбцом и на начисление не влияет никак. Ползунок остаётся ползунком про поведение человека,
-- а не про решение модератора.
--
-- ⚠️ Строки, записанные ДО этой миграции, оба случая не различают: там `muted = true` может
-- означать и то, и другое. Столбец заполняется с этого момента; для сухого прогона это неважно
-- (серверный мьют у нас единичный), но при разборе старых данных помнить об этом надо.
ALTER TABLE voice_activity ADD COLUMN IF NOT EXISTS server_muted boolean NOT NULL DEFAULT false;

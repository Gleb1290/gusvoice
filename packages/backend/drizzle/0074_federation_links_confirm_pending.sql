-- #199: наше «подтверждено» соседу ещё не доставлено.
--
-- Кнопка держателя делает связку рабочей у нас и шлёт соседу /link/confirmed один раз. Не дошло
-- (сеть, срок, сбой у соседа) — сосед оставался в `requested` навсегда. Раньше досылку угадывали по
-- отказу соседа в сверке каталога, и соседа без каталога, и кнопку «синхронизировать сейчас» она не
-- видела. Теперь отметка ставится прямо при неудачной доставке и снимается, когда сосед ответил.
--
-- По умолчанию false. Но у РАБОЧИХ на момент выкатки связок отметка ставится один раз: среди них могут
-- быть полуоткрытые с прошлых версий (сосед так и остался в `requested`), и досылка их вылечит. Здоровый
-- сосед ответит `400 wrong-state` — «уже не жду», отметка снимется сама, в журнале одна запись.
ALTER TABLE federation_links ADD COLUMN IF NOT EXISTS confirm_pending boolean NOT NULL DEFAULT false;
UPDATE federation_links SET confirm_pending = true WHERE state = 'active';

-- Уровни и заморозка итогов сезона (этап 4, зонтик #117).
--
-- 🔴 **Уровни считаются от ВРЕМЕНИ, а не от монет — отступление от плана, и вот почему.**
--
-- В плане записано «уровни и звания по `earned_total`». Но у нас уже есть решённый случай ровно той
-- же формы: цены наград хранятся в МИНУТАХ, потому что монета — величина плавающая, и сдвиг ставки
-- разом ломает всё, что в ней измерено. С уровнями получается то же самое, только хуже:
--
--   • считать уровень от накопленных монет — значит раздать всем уровни бесплатно, как только
--     владелец поднимет ставку;
--   • считать порог в минутах и переводить в монеты по текущей ставке — значит ОТОБРАТЬ уровни при
--     повышении ставки, потому что старые накопления копились по старой.
--
-- Оба варианта нарушают «из кошельков ничего не испаряется». Выход один: уровень измеряется тем,
-- что от ставки не зависит вовсе, — временем в голосе. Это и семантически честнее: уровень отвечает
-- на «сколько ты с нами», а не «сколько ты заработал». Заодно уровень перестаёт быть покупаемым в
-- принципе: время не переводится с альта.
ALTER TABLE coin_balances ADD COLUMN IF NOT EXISTS seconds_total bigint NOT NULL DEFAULT 0;

-- Итоги закрытого сезона — НЕИЗМЕНЯЕМЫЕ.
--
-- 🔴 Победитель замораживается записью, а не вычисляется на лету (решение из плана). Считай мы его
-- запросом каждый раз — поздняя правка данных (ретро, выдача руками, чистка) могла бы задним числом
-- отобрать корону у того, кто её уже носил. Корона, которую можно отобрать вчерашним днём, — это не
-- награда.
CREATE TABLE IF NOT EXISTS season_results (
  server_id text NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
  season_id text NOT NULL,
  user_id   text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  earned    integer NOT NULL,
  -- Место в таблице; 1 — победитель, он и носит корону следующий сезон.
  place     integer NOT NULL,
  frozen_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (server_id, season_id, user_id)
);

CREATE INDEX IF NOT EXISTS season_results_place_idx ON season_results (server_id, season_id, place);


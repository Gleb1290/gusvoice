-- Выплата раз в N минут ПРИСУТСТВИЯ + заморозка недосиженного (#117).
--
-- 🔴 Решение 2026-08-30: начислять не поминутно, а раз в 10 минут; если человек не досидел до
-- выплаты и отключился, его время «замерзает» и продолжается с того же места, когда он вернётся.
--
-- 🔴 Копим ЦЕННОСТЬ, а не секунды — это главное. Если складывать сырые секунды и применять
-- множители в момент выплаты, то девять минут в одиночку (25 %) плюс минута в компании (150 %)
-- оплатятся все десять по 150 %. Готовая схема фарма. Каждая минута обязана оцениваться тогда,
-- когда она случилась, поэтому `pending_milli` копит уже посчитанную ценность.
--
-- ⚠️ `carry_milli` переименован в `pending_milli`, потому что смысл поля изменился: раньше это был
-- остаток МЕНЬШЕ монеты, теперь — вся невыплаченная ценность, которая может стоить десятки монет.
-- Старое имя врало бы читателю в коде, где считаются чужие деньги.
ALTER TABLE coin_balances RENAME COLUMN carry_milli TO pending_milli;

-- Засчитанное присутствие с прошлой выплаты. Единственное по-настоящему новое поле: сама заморозка
-- никакого механизма не требует — отключился, и строка просто перестала расти.
ALTER TABLE coin_balances ADD COLUMN IF NOT EXISTS pending_seconds integer NOT NULL DEFAULT 0;

-- Шаг выплаты — под ползунок, как и остальные числа экономики.
-- ⚠️ Это НЕ то же, что ставка «за 5 минут» (`rate_per_5min`): цена времени и шаг выплаты — разные
-- вещи, и сводить их в одно число нельзя.
ALTER TABLE server_economy ADD COLUMN IF NOT EXISTS payout_minutes integer NOT NULL DEFAULT 10;

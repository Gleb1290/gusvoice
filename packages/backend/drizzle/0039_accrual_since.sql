-- Момент, с которого монеты капают вживую (#124, Д1).
--
-- 🔴 Дыра, которая сработала бы в ПЕРВЫЙ же запуск. Ретроначисление брало все срезы
-- `voice_activity` сервера без верхней границы, а живое начисление стартует с `enabled=true`.
-- Штатный сценарий: владелец включает экономику в пятницу, тикер начисляет; в воскресенье жмёт
-- «ретро» — и пятница с субботой оплачиваются людям ВТОРОЙ раз. Отметка `retro_granted_at`
-- защищала только от второго ретро, а не от пересечения с живым начислением.
--
-- Момента включения в схеме не существовало вовсе: `enabled` — булев тумблер без даты. Заводим.
-- Ретро теперь берёт срезы строго ДО `accrual_since`, живое начисление — всё, что после.
--
-- ⚠️ Ставится ОДИН раз, при первом включении, и больше не двигается. Если экономику выключить и
-- включить снова, граница обязана остаться на первом включении: иначе ретро оплатит период, за
-- который уже платили вживую. Цена решения — время «выключенного» промежутка не оплачивается
-- никем, и это правильная сторона ошибки: не создать монеты дважды важнее, чем не потерять их.
ALTER TABLE server_economy ADD COLUMN IF NOT EXISTS accrual_since timestamptz;

-- Догоняем те серверы, где экономику уже включили до этой миграции.
--
-- Границу НЕ угадываем: первая строка журнала с причиной `voice` — это и есть момент, когда живое
-- начисление впервые сработало. Если таких строк нет, значит вживую ещё ничего не начислялось и
-- граница — сейчас.
UPDATE server_economy e
   SET accrual_since = COALESCE(
         (SELECT MIN(l.created_at) FROM coin_ledger l
           WHERE l.server_id = e.server_id AND l.reason = 'voice'),
         now())
 WHERE e.enabled = true AND e.accrual_since IS NULL;

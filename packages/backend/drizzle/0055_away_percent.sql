-- «Отошёл» перестаёт приносить полную ставку (запрос 04.09, первый день живой экономики).
--
-- 🔴 Дыра, которую он назвал: мьют не штрафуется намеренно (человек слушает), но микрофон можно
-- выключить НА ЖЕЛЕЗЕ — приложение о таком мьюте не знает вовсе, — уйти и получать полную ставку до
-- самого потолка. Честному сидению это проигрывает, и «все начнут крутить», как только заметят.
--
-- Ответ — статус «отошёл»: его ставит и человек сам, и автоматика по простою НА УРОВНЕ ОС. Второе
-- важно: играющий в полноэкранную игру двигает мышь и клавиатуру, поэтому в «отошёл» не попадает, а
-- ушедший от компьютера попадает через десять минут.
--
-- ⚠️ Признак пишется и в СЫРЬЁ (`voice_activity.away`): ретро и любой пересчёт по журналу должны
-- видеть ровно то состояние, которое видел тикер, иначе один и тот же вечер даст разные числа.
ALTER TABLE server_economy ADD COLUMN IF NOT EXISTS away_percent integer NOT NULL DEFAULT 25;
ALTER TABLE voice_activity ADD COLUMN IF NOT EXISTS away boolean NOT NULL DEFAULT false;

-- Анимированный аватар за монеты (#117, этап 4).
--
-- 🔴 **Лицензия ГЛОБАЛЬНАЯ, и в магазине об этом сказано прямо.** Аватар лежит на `users` и виден
-- везде, значит купивший на одном сервере получает анимацию на всех. Посерверная подмена задевает
-- КАЖДУЮ поверхность, где рисуется аватар, и раздувает фичу непропорционально поводу. Развилка
-- закрыта разбором: берём честность вместо подмены.
--
-- ⚠️ **Анимация лежит ОТДЕЛЬНЫМ полем, а не подменяет `avatar_url`.** Обычный аватар остаётся
-- статичным кадром для списков и оверлея: `prefers-reduced-motion` сам по себе GIF/WebP/APNG НЕ
-- останавливает (это медиазапрос CSS, а крутит анимацию декодер картинки), да и двадцать
-- анимированных аватар в списке участников — это двадцать непрерывных декодирований. Анимация
-- показывается по наведению и в карточке профиля.
ALTER TABLE users ADD COLUMN IF NOT EXISTS animated_avatar_url text;
-- Право загрузить анимацию. Однажды купленное не отбирается: это покупка, а не подписка.
ALTER TABLE users ADD COLUMN IF NOT EXISTS animated_avatar_unlocked boolean NOT NULL DEFAULT false;

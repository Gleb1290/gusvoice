-- Поручительства дома: за кого и перед каким хостом мы ручались (#139, аудит федерации 19.09, F-04).
--
-- **Зачем.** Индекс членств (`federation_memberships`) дом заполняет со слов ХОСТА: пришло событие
-- «ваш человек вступил на сервер» — записали. Проверялось только одно — что человек наш. Был ли он у
-- этого хоста хоть раз, дом не знал вовсе, и связанный сосед мог объявить гостем ЛЮБОГО нашего человека
-- из каталога. На этом же индексе стояла проверка «просьба разбудить пришла от инстанса, где человек
-- действительно гость»: сосед сам писал в индекс и сам же по нему проходил проверку — то есть мог
-- будить телефон кого угодно, со своим текстом в названии сервера.
--
-- Единственное, что дом знает САМ, без чужих слов, — кому он выдавал токен личности. Гостем человек
-- становится только по этому токену (`/fed/identity-token` → `/fed/v1/session`), значит пара
-- «человек + хост», по которой токен не выдавался, гостем быть не может в принципе. Эта таблица и
-- есть такая память; членства и просьбы о пушах принимаются только по ней.
--
-- 🔴 Строка НЕ удаляется, когда человек уходит с хоста: хост ещё пришлёт «вышел» и догонит сверкой, и
-- принять это нужно. Стирается она при удалении аккаунта — явно, в `accountRows.ts` (строка `users`
-- там обезличивается, а не удаляется, так что каскад ниже — страховка, а не рабочий путь).
CREATE TABLE IF NOT EXISTS federation_guest_grants (
  user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  -- Хост, которому выдавалось поручительство. Без ссылки на `federation_links` намеренно: связку
  -- перепривязывают (личность меняется) и рвут, а память о поручительстве от этого не пропадает.
  instance_id TEXT NOT NULL,
  first_issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_issued_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, instance_id)
);

-- Уже существующие членства заведены по настоящим поручительствам, просто до появления таблицы.
-- Без этой строки первая же сверка после выкатки перестала бы их обновлять, а гости остались бы
-- без пушей, пока каждый не войдёт заново.
INSERT INTO federation_guest_grants (user_id, instance_id)
SELECT DISTINCT user_id, instance_id FROM federation_memberships
ON CONFLICT DO NOTHING;

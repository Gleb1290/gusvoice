-- ЛС (#211, 07.10, признак `conv11`): закреп беседы наверху списка и «Выключить уведомления» со сроком, как в Telegram.
--
-- `conversation_members.pinned_at` — когда Я закрепил беседу (только у своей строки участника; собеседник не видит).
-- `NULL` — не закреплена. Закреплённые идут в списке первыми, свежезакреплённая — выше (`ConvSummary.pinnedAt`);
-- лимит — 5 закреплённых у человека (`convRules.CONV_PIN_LIMIT`).
--
-- `push_mutes.until` — до какого времени действует заглушка. `NULL` — навсегда (так понимают все прежние строки и
-- вставки старых клиентов и старого бэкенда при откате). Истёкшая строка = не заглушено: пуш уходит, список заглушек
-- `GET /push/mutes` её не отдаёт; старый бэкенд при откате понял бы её как «навсегда» — не страшнее, чем было.
--
-- Только добавление: обе колонки допускают `NULL` без умолчания — таблицы не переписываются.
ALTER TABLE conversation_members ADD COLUMN IF NOT EXISTS pinned_at timestamptz;
ALTER TABLE push_mutes ADD COLUMN IF NOT EXISTS until timestamptz;

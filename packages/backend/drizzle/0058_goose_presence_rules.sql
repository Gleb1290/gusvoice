-- Гусь перестаёт быть доходом, не зависящим ни от чего (решение 07.09).
--
-- 🔴 Повод — замер по боевому серверу за 04–07.09. Гусь давал 37 % всего живого дохода и проходил
-- МИМО всей защиты от фарма: он начисляется через `applyCoins`, а не через `accrue`, поэтому его не
-- видят ни суточный потолок, ни затухание, ни множитель «сидишь один». Замерено: 06.09 шестеро
-- упёрлись в потолок 800 между 19:26 и 21:37, и после этого добрали гусём ещё до 345 монет сверху —
-- то есть потолок переставал быть потолком ровно в прайм-тайм.
--
-- Три правила, каждое лечит свой перекос:
--
-- 1. Откат до следующего гуся отсчитывается от ПОИМКИ, а не от выхода (в коде, миграции не нужно).
-- 2. Один в канале — гусь не выходит вовсе (в коде).
-- 3. В деафене гусь даёт меньше — вот эта колонка.
--
-- 🔴 Почему деафен, а не «отошёл». «Отошёл» ставит простой ОС, и клик по гусю его снимает — то есть
-- состояние само себе противоречит и до начисления не доживает. Деафен человек держит осознанно и
-- продолжает при этом кликать: он в канале, но вне разговора, и полная надбавка за это — плата за
-- пустое кресло. Ровно та же логика, по которой `deafened_percent` режет ставку голоса до четверти.
--
-- ⚠️ Отдельным ЧИСЛОМ, а не процентом от `goose_bonus`. Процент пришлось бы подбирать под желаемую
-- пятёрку (15 × 33 % = 4, а не 5), и он бы молча уезжал при каждой правке основной надбавки. Число
-- владелец видит и назначает прямо.
ALTER TABLE server_economy ADD COLUMN IF NOT EXISTS goose_deafened_bonus integer NOT NULL DEFAULT 5;

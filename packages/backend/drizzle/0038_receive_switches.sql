-- Личные выключатели «не принимать» (#122).
--
-- 🔴 Требование: «иногда типают все вместе, потому что шутка была шикарной, но если человек
-- почувствует травлю, отключит принятие сам». Потолком тут ничего не решить — массовый тип обычно
-- радость, резать его нельзя. Решает САМ человек, а не владелец сервера.
--
-- ⚠️ Оба выключателя ПОСЕРВЕРНЫЕ, а не глобальные: травля случается на конкретном сервере, и
-- глушить из-за неё все остальные незачем.
--
-- ⚠️ Отдельно от уже существующего `opted_out` («не участвовать в экономике»). Тот тоже перекрывает
-- входящие типы, но заодно останавливает начисление: человек, которому надоели типы, не должен
-- ради этого переставать зарабатывать.
ALTER TABLE coin_balances ADD COLUMN IF NOT EXISTS tips_opt_out boolean NOT NULL DEFAULT false;

-- Тычки — не экономика, поэтому живут при членстве на сервере, а не в кошельке.
ALTER TABLE server_members ADD COLUMN IF NOT EXISTS pokes_opt_out boolean NOT NULL DEFAULT false;

-- Удаление аккаунта обезличивает строку, а не стирает её (F0 федерации, #139, §5.6.2 плана).
--
-- 🔴 До этого `DELETE FROM users` каскадом (миграция 0014) уносил все сообщения человека в каналах и ЛС —
-- собеседник видел разговор без ответов. Теперь строка остаётся с тем же id, личные данные стираются
-- (`accountRules.ts` → `anonymizedUserFields`), а это поле отмечает, что аккаунта больше нет.
--
-- ⚠️ Каскады 0014 сознательно НЕ снимаются: они срабатывают только на DELETE, а удаление аккаунта больше
-- его не делает. Единственный оставшийся DELETE — уборка брошенных регистраций без следа (`cleanup.ts`),
-- и обезличенные строки она пропускает.
ALTER TABLE users ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ;

-- Качество звука на голосовой канал (#101, как битрейт канала в Discord).
--
-- Зачем: битрейт задаёт публикующий, а платит каждый слушатель — SFU форвардит поток каждому без
-- перекодирования, поэтому входящий трафик слушателя растёт линейно с числом говорящих. На мобильном
-- интернете это и упиралось в потолок «вчетвером уже не тянет».
--
-- NULL = «как у всех», значение берётся из DEFAULT_VOICE_BITRATE (shared/voiceQuality.ts), а НЕ из
-- DEFAULT колонки: умолчание — продуктовое решение, и менять его правкой одной константы честнее,
-- чем миграцией, которая не тронет уже созданные строки.
ALTER TABLE channels ADD COLUMN IF NOT EXISTS voice_bitrate integer;

-- Саундборд сервера: короткие сэмплы, которые выстреливают в голосовой канал за монеты (#21).
--
-- 🔴 **Сэмплы принадлежат СЕРВЕРУ, а не каналу.** Звуки событий (`server_sounds`/`channel_sounds`)
-- живут на двух уровнях, потому что «звук входа именно в этот канал» — осмысленное желание. У
-- саундборда такого желания нет: это общая коллекция шуток сервера, и держать её отдельно в каждом
-- канале значило бы заставлять заливать одно и то же по десять раз.
--
-- ⚠️ `url` ведёт в тот же публичный бакет, что и звуки событий. Ничего приватного в сэмплах нет по
-- определению — их слышит весь канал, — поэтому отдельного приватного хранения не заводим.
--
-- `created_by` без каскада на удаление: сэмпл переживает уход того, кто его залил (иначе уход
-- одного человека молча выносит половину саундборда). Ссылка обнуляется, звук остаётся.
CREATE TABLE IF NOT EXISTS server_soundboard (
  id         text PRIMARY KEY,
  server_id  text NOT NULL REFERENCES servers(id) ON DELETE CASCADE,
  name       text NOT NULL,
  url        text NOT NULL,
  created_by text REFERENCES users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Выборка всегда «все сэмплы этого сервера по порядку добавления»: сетка кнопок не должна
-- перетасовываться между заходами, иначе мышечная память по кнопкам не работает вовсе.
CREATE INDEX IF NOT EXISTS server_soundboard_server_idx ON server_soundboard (server_id, created_at);

-- Одобрение регистрации администратором (мастер установки, О2 плана открытия кода, #142).
--
-- Политика регистрации инстанса живёт в `instance_settings.registration`; при политике «все, но с
-- подтверждением админа» новый аккаунт создаётся с пустым `approved_at` и не может войти, пока
-- супер-админ его не одобрит (`setupRules.ts` → `loginGate`).
--
-- 🔴 Всем уже существующим аккаунтам отметка ставится сразу: у работающих инстансов (прод, коробки у людей)
-- не должно поменяться ничего — ни один человек не должен внезапно оказаться «ждущим одобрения».
ALTER TABLE users ADD COLUMN IF NOT EXISTS approved_at TIMESTAMPTZ;
UPDATE users SET approved_at = created_at WHERE approved_at IS NULL;

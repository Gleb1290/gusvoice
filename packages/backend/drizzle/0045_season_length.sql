-- Помесячные сезоны как ползунок (запрос 2026-09-01).
--
-- 🔴 Времена года дают долгий сезон: смысл появляется только к концу, а корона меняется четыре раза
-- в год. Месяц даёт двенадцать поводов и живую гонку. Что лучше для семнадцати друзей — видно только
-- по живому, поэтому это ползунок, а не константа.
--
-- ⚠️ **Смена разбивки досрочно закрывает текущий сезон.** Идентификатор сезона меняется, и
-- `closeSeasonIfNeeded` видит смену: он замораживает итог по журналу за уже прошедшую часть окна
-- (будущей части в журнале ещё нет, поэтому сумма верна) и переходит на новую разбивку. Поведение
-- правильное, но молчать о нём нельзя — сезон подведён раньше срока и корона выдана. Об этом
-- предупреждает панель.
--
-- ⚠️ Помесячные идентификаторы начинаются с `m` (`m2026-09`): по формату видно, какой разбивкой
-- сделан сезон, и старые записи после смены ползунка продолжают читаться правильно.
ALTER TABLE server_economy ADD COLUMN IF NOT EXISTS season_length text NOT NULL DEFAULT 'quarter';

-- Мьют и «не слышу» — ПРОЦЕНТ ставки, а не запрет (#117).
--
-- 🔴 Решение 2026-08-28: «я часто сижу замьюченный, надо чтоб если человек замьютил микро,
-- никакого штрафа, фул мьют — 0.25 от нормального».
--
-- Почему тумблеры были неверны по сути: выключенный микрофон НЕ означает отсутствия. Человек
-- слушает, читает чат, играет вместе со всеми — просто дома шумно или он ест. Запрет наказывал его
-- за вежливость к остальным, то есть ровно за то, что стоило бы поощрять. А «не слышу» — признак
-- другого рода: человек в разговоре не участвует вовсе, и четверть ставки тут честнее и нуля
-- (он всё-таки в канале и его видно), и полной ставки.
--
-- Двоичного «да/нет» для этого мало: между «не начислять» и «начислять как обычно» лежит вся
-- полезная середина. Поэтому проценты — как у одиночки, компании и затухания.
ALTER TABLE server_economy ADD COLUMN IF NOT EXISTS muted_percent integer NOT NULL DEFAULT 100;
ALTER TABLE server_economy ADD COLUMN IF NOT EXISTS deafened_percent integer NOT NULL DEFAULT 25;

-- Переносим уже настроенное по смыслу старых тумблеров, а не по новым умолчаниям: миграция не
-- вправе молча менять то, что владелец выставил руками. (На проде строк ноль — экономику ещё не
-- включали, — но у dev-баз и будущих self-hosters они быть могут.)
UPDATE server_economy
   SET muted_percent    = CASE WHEN ignore_muted    THEN 0 ELSE 100 END,
       deafened_percent = CASE WHEN ignore_deafened THEN 0 ELSE 100 END;

ALTER TABLE server_economy DROP COLUMN IF EXISTS ignore_muted;
ALTER TABLE server_economy DROP COLUMN IF EXISTS ignore_deafened;

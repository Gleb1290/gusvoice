-- Запрет чужому человеку на весь инстанс и жалоба его держателю (#139 F3, план §5.11).
--
-- Бан на сервере уже есть и для гостя работает сам. Не хватало двух вещей, названных в плане
-- отдельными требованиями (36 и 37): закрыть вход ОДНОМУ человеку соседа, не разрывая связку целиком
-- («у друга один человек ведёт себя плохо, остальных пускать хочется»), и сообщить об этом
-- держателю его инстанса — потому что разбираться с человеком может только он.

-- --- Запрет на инстанс ------------------------------------------------------------------------------

-- 🔴 Ключ — ГЛОБАЛЬНАЯ личность (инстанс + человек там), а не наша теневая строка. Три следствия,
-- и каждое нужно:
--   * запретить можно того, кто ещё ни разу к нам не заходил (нашли в каталоге соседа);
--   * запрет переживает разрыв связки и новую связку с тем же инстансом;
--   * переезжает при перепривязке (§5.1.3) вместе с остальными ссылками на инстанс.
-- Привяжи мы запрет к теневой строке — человек снимал бы его, просто зайдя заново с чистого листа.
CREATE TABLE IF NOT EXISTS instance_bans (
  home_instance_id TEXT NOT NULL,
  home_user_id TEXT NOT NULL,
  -- Причина — для держателя и журнала. Человеку она НЕ показывается (§5.11): он видит нейтральное
  -- «вход закрыт», иначе запрет превращается в переписку.
  reason TEXT,
  -- Пусто = навсегда. Истёк — можно войти снова, но прежние членства не возвращаются: вернуть их
  -- значило бы, что запрет был паузой.
  expires_at TIMESTAMPTZ,
  created_by TEXT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- 🔴 Снятие НЕ стирает строку, а отмечается здесь: «кто, кого, срок, причина, снятие» (§5.11) —
  -- это и есть журнал запретов. Удаляй мы строку, держатель через месяц не смог бы ответить на
  -- вопрос «а этого человека мы раньше не банили?», а именно он чаще всего и возникает.
  removed_at TIMESTAMPTZ,
  removed_by TEXT REFERENCES users(id) ON DELETE SET NULL,
  PRIMARY KEY (home_instance_id, home_user_id)
);

-- --- Жалобы -----------------------------------------------------------------------------------------

-- Одна таблица на обе стороны: `direction` говорит, наша это жалоба или к нам.
--
-- ⚠️ Хранить их врозь было бы честнее «по смыслу», но у них один жизненный цикл (отправлена →
-- прочитана → отвечена → закрыта) и один список во вкладке «Федерация»; две таблицы значили бы два
-- набора состояний, которые обязаны совпадать.
CREATE TABLE IF NOT EXISTS federation_reports (
  id TEXT PRIMARY KEY,
  -- 'out' — мы пожаловались соседу; 'in' — сосед пожаловался нам.
  direction TEXT NOT NULL,
  instance_id TEXT NOT NULL,
  -- Идентификатор жалобы в пространстве ОТПРАВИТЕЛЯ: по нему приходит ответ.
  report_id TEXT NOT NULL,
  -- На кого жалуются — в пространстве ЕГО дома (у 'in' это наш собственный человек).
  reported_user_id TEXT NOT NULL,
  -- instance_ban | server_ban — что мы (или сосед) уже сделали у себя.
  action TEXT NOT NULL,
  server_name TEXT,
  reason TEXT,
  -- 🔴 До пяти сообщений, выбранных ВРУЧНУЮ. Хост не отдаёт соседу переписку сам — иначе жалоба
  -- стала бы способом выгрузить чужой чат, назвав это модерацией.
  evidence JSONB NOT NULL DEFAULT '[]'::jsonb,
  -- sent | delivered | read | answered | closed
  status TEXT NOT NULL DEFAULT 'sent',
  reply TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Повторная жалоба на того же человека за сутки приклеивается к первой (§5.11) — ищем по паре.
CREATE INDEX IF NOT EXISTS federation_reports_target_idx
  ON federation_reports (instance_id, reported_user_id, created_at);

-- Один и тот же `report_id` от одного соседа не должен заводить вторую строку: повтор доставки это
-- норма, а не новая жалоба.
CREATE UNIQUE INDEX IF NOT EXISTS federation_reports_incoming_uniq
  ON federation_reports (instance_id, report_id, direction);

-- --- Квота хранилища на связку (§5.10, требование 30) -----------------------------------------------

-- 🔴 На СВЯЗКУ, а не «на гостей вообще»: файлы лежат у нас, и предел обязан называть виновника —
-- «инстанс «Друзья» занял 2 ГБ». Держателю иначе нечего решать: он видит, что место кончилось, и не
-- знает, с кем об этом говорить.
ALTER TABLE federation_links ADD COLUMN IF NOT EXISTS quota_bytes BIGINT NOT NULL DEFAULT 2147483648;
ALTER TABLE federation_links ADD COLUMN IF NOT EXISTS used_bytes BIGINT NOT NULL DEFAULT 0;

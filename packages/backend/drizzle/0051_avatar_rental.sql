-- Анимированный аватар выдаётся НА 30 ДНЕЙ, а не навсегда (решение 02.09).
--
-- 🔴 **Срок, а не флаг.** Прежний `animated_avatar_unlocked` означал «куплено насовсем». Аренда —
-- это про то, что аватар стоит инфраструктуры постоянно (мегабайтный файл отдаётся каждому зрителю),
-- а не единожды в момент покупки. Разовая плата за постоянный расход — единственная награда в
-- каталоге, где это расходится.
--
-- ⚠️ Срок НЕ привязан ни к сезону, ни к календарному месяцу (тоже так решено): 30 дней от
-- покупки. Сезон у нас три месяца, и привязка к нему сделала бы аренду то длинной, то короткой в
-- зависимости от дня покупки.
--
-- ⚠️ Уже разблокированным (в проде таких нет — экономика выключена) выдаём 30 дней от применения
-- миграции, а не обрубаем: миграция не должна ничего отнимать.
ALTER TABLE users ADD COLUMN IF NOT EXISTS animated_avatar_until timestamptz;

UPDATE users
SET animated_avatar_until = now() + interval '30 days'
WHERE animated_avatar_unlocked = true AND animated_avatar_until IS NULL;

-- 🔴 Старый флаг НЕ удаляем этой миграцией. Откат кода на предыдущую версию должен оставаться
-- возможным, а колонка ничего не стоит; вычистим отдельно, когда аренда отработает сезон.

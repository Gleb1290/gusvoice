-- Источники уровня, кроме времени (этап 4, решение 2026-09-01).
--
-- 🔴 **Уровень поднимают три вещи, и все три НЕПОКУПАЕМЫЕ.** Замечание: одного времени мало —
-- пойманный бонус и благодарность за хорошую шутку тоже участие, и они должны считаться.
--
-- Острый край, который пришлось обойти: монеты ПЕРЕВОДЯТСЯ. Считай мы типы в уровень по сумме —
-- уровни начали бы дариться с альта, а это ровно та дыра, ради которой `earned_total` и не растёт
-- от входящих типов. Поэтому считаем не монеты, а **факт признания**: сколько РАЗНЫХ людей сказали
-- тебе спасибо. Сумма покупается, человек — нет; альту нужен не кошелёк, а новые аккаунты.
--
-- ⚠️ Хранится СЫРЬЁ, а не очки: часы, число пойманных бонусов и число «человеко-дней признания».
-- Очки выводятся формулой в `levelRules.ts`. Веса будут крутить после сухого прогона (числа
-- назначаются 5 сентября), и при таком хранении правка весов меняет только цифру, а не переписывает
-- историю задним числом.

-- Сколько раз человек поймал бонусного гуся. Клик нельзя подарить: надо быть на месте и смотреть.
ALTER TABLE coin_balances ADD COLUMN IF NOT EXISTS bonus_claims integer NOT NULL DEFAULT 0;

-- Сколько «человеко-дней признания» набрано за всё время: +1 за каждого РАЗНОГО человека, который
-- типнул тебя в этот день, в пределах суточного потолка.
ALTER TABLE coin_balances ADD COLUMN IF NOT EXISTS recognition_tippers integer NOT NULL DEFAULT 0;

-- Сколько разных людей типнули СЕГОДНЯ — для суточного потолка. Обнуляется тем же перекатом суток,
-- что и остальные суточные счётчики (`transferCoins`).
ALTER TABLE coin_balances ADD COLUMN IF NOT EXISTS recognition_today integer NOT NULL DEFAULT 0;

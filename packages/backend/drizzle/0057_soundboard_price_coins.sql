-- Своя цена звука саундборда переезжает из МИНУТ сидения в МОНЕТЫ (решение 04.09).
--
-- 🔴 Почему здесь можно то, чего нельзя каталогу. Весь прайс хранится в минутах ровно затем, чтобы
-- сдвиг ползунка ставки не переоценивал магазин: цена «полчаса сидения» остаётся собой при любой
-- ставке. Но цены саундборда владелец назначает РУКАМИ и по одному звуку («будут ультимативные и так
-- себе»), глядя на баланс людей, — и в этом случае минуты не помогают, а мешают: владелец думает
-- «этот выстрел стоит 200 монет», а вводит 100 минут и потом ищет, во что они превратились.
-- Общая цена саундборда остаётся в каталоге и в минутах — меняется только СВОЯ цена звука.
--
-- ⚠️ Плата за решение: после сдвига ставки цены звуков останутся прежними в монетах, то есть
-- подешевеют или подорожают ОТНОСИТЕЛЬНО заработка. Это и есть «ставим руками» — пересматривать
-- их придётся тоже руками.
ALTER TABLE server_soundboard ADD COLUMN IF NOT EXISTS price_coins integer;

-- Перенос уже назначенных цен по ТЕКУЩЕЙ ставке сервера — той же формулой, что и `priceCoins()`
-- (`ceil(минуты * 60 * ставка / 300)`). Ставки нет (экономику не настраивали) — переносить нечего:
-- в монетах такая цена всё равно была бы нулём, а ноль означает «даром», и молча его ставить нельзя.
UPDATE server_soundboard s
SET price_coins = ceil(s.price_minutes::numeric * 60 * e.rate_per_5min / 300)
FROM server_economy e
WHERE e.server_id = s.server_id
  AND s.price_minutes IS NOT NULL
  AND e.rate_per_5min > 0;

ALTER TABLE server_soundboard DROP COLUMN IF EXISTS price_minutes;

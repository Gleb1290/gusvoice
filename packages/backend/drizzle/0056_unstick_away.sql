-- Вернуть в сеть тех, кого СТАРЫЙ клиент увёл в «отошёл» и не смог вернуть (04.09).
--
-- 🔴 Что произошло. Признак «увела автоматика» появился в коде 28.08, а в собранный клиент попал
-- только 04.09 (v0.6.40). До этого авто-уход отправлял `PATCH /users/me/status {status:'away'}` БЕЗ
-- поля `auto`, и сервер честно записывал `presence_auto = false` — «поставлено человеком». Признак
-- при этом жил в localStorage той вкладки, поэтому возврат работал, пока клиент тот же.
--
-- Зацементировало это обновление: новая сборка берёт признак С СЕРВЕРА, видит «ручной» и человека
-- не возвращает — намеренно, потому что ручной статус это заявление, и перетирать его нельзя.
-- Итог: люди играют, а числятся отошедшими. Пока «отошёл» ничего не стоил, никто не замечал; с
-- переходом на 25 % ставки (миграция 0055) это начало тихо резать им заработок вчетверо.
--
-- ⚠️ Правим ТОЛЬКО `presence_auto = false` при статусе `away` — то есть ровно ту комбинацию, которую
-- порождала старая сборка. Цена ошибки минимальна и обратима: тот, кто действительно хотел «Отошёл»,
-- поставит его снова одним нажатием, и новый клиент запишет пометку правильно.
-- ⚠️ На свежем инстансе таких строк нет — миграция там ничего не делает.
UPDATE users SET presence_status = 'online' WHERE presence_status = 'away' AND presence_auto = false;

-- Бонус по клику: гусь выглядывает раз в N минут, кликнул — забрал (план, модель G).
--
-- 🔴 Это ЕДИНСТВЕННОЕ дешёвое доказательство присутствия: спящий не кликнет, а честному сидящему
-- клик ничего не стоит. Приём взят у Twitch, где 50 баллов каждые 15 минут выдаются только по
-- нажатию.
--
-- ⚠️ **Бонус НАДБАВКОЙ, а не заменой базовой ставки.** Человек в полноэкранной игре гуся не увидит,
-- и если бы клик заменял начисление, фича превратилась бы в налог на играющих — то есть на
-- основной сценарий продукта.
--
-- `goose_bonus = 0` означает «гуся нет вовсе», а не «гусь есть и даёт ноль»: выглядывающий маскот,
-- за которым ничего не следует, — это поломка, а не настройка.
ALTER TABLE server_economy ADD COLUMN IF NOT EXISTS goose_bonus integer NOT NULL DEFAULT 0;
-- Через сколько минут гусь может выглянуть снова. Настоящее число назначается по срезу прогона.
ALTER TABLE server_economy ADD COLUMN IF NOT EXISTS goose_minutes integer NOT NULL DEFAULT 20;

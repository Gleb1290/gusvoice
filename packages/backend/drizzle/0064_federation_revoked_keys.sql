-- Отозванные ключи инстансов (федерация, #139, F1, план §5.1.3).
--
-- Когда у соседа украли ключ, он рассылает отзыв, подписанный СТАРЫМ ключом. Мы принимаем такой отзыв
-- автоматически (худшее, что сделает вор, подделав его, — заморозит связку, а не захватит её) и
-- запоминаем отозванную личность НАВСЕГДА: запрос, подписанный отозванным ключом, после этого не просто
-- отвергается, а отвергается с понятной причиной «использован отозванный ключ — возможна кража».
--
-- Разница принципиальная: «ключ неизвестен» — обычное дело (сосед, с которым мы не связаны),
-- а «ключ отозван» — сигнал, который держатель должен увидеть.
--
-- Таблица пуста у всех, кто не включал федерацию.

CREATE TABLE IF NOT EXISTS federation_revoked_keys (
  -- Личность, которая была отозвана. Она выводится из ключа, поэтому запись о ней — это и запись о ключе.
  instance_id TEXT PRIMARY KEY,
  -- На какую личность сосед перешёл (из подписанного отзыва). Нужна человеку при перепривязке:
  -- он сверяет отпечаток, который ему называют, с тем, что пришёл по подписанному каналу.
  replaced_by_instance_id TEXT,
  -- Домен на момент отзыва — чтобы в журнале было видно, о ком речь, даже если связку уже удалили.
  domain TEXT,
  -- own — это МЫ отозвали свой ключ; peer — отзыв пришёл от соседа.
  origin TEXT NOT NULL DEFAULT 'peer',
  revoked_at TIMESTAMPTZ NOT NULL,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Поиск «не отозван ли ключ, которым это подписано» идёт по первичному ключу, отдельный индекс не нужен.

-- Цена анимированного аватара на сервере: своя, но не ниже цены инстанса (решение 14.09).
--
-- 🔴 Зачем колонка стала nullable. Строка каталога сервера создавалась и при простом переключении
-- «продаётся / снята с продажи» — и тогда в неё писалась цена по умолчанию. Пока аватар строку
-- игнорировал, это было безвредно. Но под новым правилом «максимум из цены инстанса и цены сервера»
-- такая наливная цена стала бы НАЦЕНКОЙ, которую никто не ставил: держатель инстанса опускает цену
-- до 1000 минут, а сервер, где владелец однажды щёлкнул тумблером, молча остаётся на 1500.
--
-- ⇒ Теперь NULL означает «своей цены нет, бери умолчание» — для всех наград, не только для аватара.
-- Для остальных наград поведение не меняется: чтение и раньше делало `?? defaultMinutes`.
ALTER TABLE server_shop ALTER COLUMN price_minutes DROP NOT NULL;

-- ⚠️ Существующие цены аватара на серверах — ЗАВЕДОМО наливные: маршрут до этой миграции отвечал 403
-- на любую попытку задать их, поэтому ни одна не поставлена владельцем осознанно. Обнуляем, чтобы
-- ни одна не превратилась в наценку. На боевом инстансе строк нет вовсе (проверено 14.09) — это
-- страховка для turnkey-инстансов.
UPDATE server_shop SET price_minutes = NULL WHERE item = 'animated-avatar';

-- Флаг — у самого сообщения: его несёт DTO (`silent: true`, только у таких) в ответе отправки, истории, `conv.change`,
-- догонке и старом `dm.create`, а получатель по нему не звенит (уведомление и счётчик — как обычно). Пуш уходит
-- всё равно, с `silent: true` в зашифрованной нагрузке. «Без звука» — свойство ОТПРАВКИ: пересылка его не переносит.
--
-- Только добавление: `NOT NULL DEFAULT false` — у прежних строк и у вставок старого бэкенда (откат) флаг ложный, то есть
-- всё как было. Постоянное умолчание Postgres пишет в каталог, таблицу не переписывает (с 11-й версии).
ALTER TABLE conversation_messages ADD COLUMN IF NOT EXISTS silent boolean NOT NULL DEFAULT false;

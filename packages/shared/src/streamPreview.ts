/**
 * Превью показа: маленький свежий кадр чужого стрима, который видно по наведению мышки, **не заходя
 * в канал** (#115).
 *
 * Кадр отдаёт САМ показывающий — он и так через себя его прогоняет. Сервер лишь держит последний,
 * недолго и в памяти. Здесь — правила, по которым обе стороны договариваются, что считается годным
 * превью: одинаковые числа у отправителя и приёмника, иначе клиент шлёт то, что сервер отбивает.
 *
 * ⚠️ Картинка едет data-URL'ом внутри JSON, а не сырыми байтами. Так решено осознанно: нативный
 * сборщик миниатюр в Rust уже отдаёт ровно data-URL, и браузерный `canvas.toDataURL` тоже — сырой
 * путь потребовал бы отдельного разбора тела на сервере ради экономии, которой при наших объёмах
 * никто не заметит.
 */

/**
 * Сколько превью живёт на сервере. Само протухает — значит, «человек закончил показ» не нужно
 * ловить отдельным событием: перестал слать, и через полминуты картинки нет.
 *
 * Заметно больше периода обновления: одна пропущенная отправка (кадр не дался, сеть моргнула) не
 * должна оставлять зрителя с пустотой.
 */
export const STREAM_PREVIEW_TTL_S = 30;

/** Как часто показывающий шлёт новый кадр. */
export const STREAM_PREVIEW_REFRESH_MS = 5_000;

/**
 * Сколько мышка должна повисеть над строкой, прежде чем мы пойдём за картинкой.
 *
 * Без задержки проведённая через список мышка дёргала бы запрос на каждого, мимо кого прошла.
 */
export const STREAM_PREVIEW_HOVER_DELAY_MS = 350;

/**
 * Потолок длины data-URL. 320 px по ширине в PNG укладываются в сотню-полторы килобайт даже на
 * пёстрой игровой сцене; запас взят на кратное превышение, а не впритык.
 *
 * ⚠️ Потолок именно ОТБИВАЕТ превью, а не режет его: обрезанная картинка — это битый файл, и
 * зритель увидел бы половину кадра вместо честного «превью нет».
 */
export const STREAM_PREVIEW_MAX_CHARS = 400_000;

/** Что вообще принимаем. SVG в этом списке нет и быть не может — это исполняемый документ. */
const PREVIEW_PREFIXES = ['data:image/png;base64,', 'data:image/jpeg;base64,'];

export type PreviewCheck = { ok: true } | { ok: false; error: string };

/**
 * Годится ли присланное как превью показа. Одно правило на обе стороны: клиент проверяет ПЕРЕД
 * отправкой (не гонять заведомо отбиваемое), сервер — перед укладкой (клиенту верить нельзя).
 */
export function checkStreamPreview(dataUrl: string): PreviewCheck {
  if (!dataUrl) return { ok: false, error: 'пустое превью' };
  if (dataUrl.length > STREAM_PREVIEW_MAX_CHARS) return { ok: false, error: 'превью слишком большое' };
  const prefix = PREVIEW_PREFIXES.find((p) => dataUrl.startsWith(p));
  if (!prefix) return { ok: false, error: 'превью не картинка' };
  // Пустое тело при верной шапке — тоже мусор: `<img>` на таком показал бы сломанную картинку.
  if (dataUrl.length <= prefix.length) return { ok: false, error: 'пустое превью' };
  return { ok: true };
}

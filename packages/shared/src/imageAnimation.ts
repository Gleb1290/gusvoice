/**
 * Анимирована ли картинка — по СОДЕРЖИМОМУ, а не по типу.
 *
 * 🔴 Зачем отдельно от проверки mime: тип файла про анимацию не говорит ничего. `image/webp` — это и
 * обычная картинка, и анимация; `image/png` — и обычная, и APNG. Разрешить «PNG и WebP» в надежде,
 * что анимация не пролезет, нельзя: пролезет.
 *
 * Где это важно уже сейчас: иконка валюты рисуется 14 пикселями в шапке сервера и висит на глазах у
 * ВСЕХ участников постоянно. Анимация там — не украшение, а то, что дёргается в углу зрения весь
 * вечер, и выбирает её один человек за всех.
 *
 * Пригодится ещё раз с обратным знаком: анимированный аватар за монеты (#117) — там анимация,
 * наоборот, обязательна, и проверять придётся ровно этим же.
 */

/** Есть ли по смещению `at` четырёхбайтовая метка `tag` (ASCII). */
function hasTag(bytes: Uint8Array, at: number, tag: string): boolean {
  if (at + tag.length > bytes.length) return false;
  for (let i = 0; i < tag.length; i++) if (bytes[at + i] !== tag.charCodeAt(i)) return false;
  return true;
}

/** Найти четырёхбайтовую метку в первых `limit` байтах. */
function findTag(bytes: Uint8Array, tag: string, limit: number): boolean {
  const end = Math.min(bytes.length, limit) - tag.length;
  for (let i = 0; i <= end; i++) if (hasTag(bytes, i, tag)) return true;
  return false;
}

/**
 * Сколько байт от начала просматриваем.
 *
 * ⚠️ Не весь файл: метки анимации у всех трёх форматов живут в заголовке, а обходить мегабайты на
 * каждой загрузке незачем. APNG обязан объявить `acTL` ДО первого `IDAT`, WebP — `ANIM` сразу за
 * `VP8X`, так что килобайта хватает с большим запасом.
 */
const HEADER_SCAN = 4096;

/**
 * Похоже ли, что картинка анимирована.
 *
 * ⚠️ Отвечает «да» с запасом: **GIF считаем анимированным всегда**, даже односкадровый. Отличить
 * его от анимированного можно только разбором блоков, а цена ошибки несимметрична — пропущенная
 * анимация мозолит глаза всему серверу, а зря отвергнутая односкадровая гифка чинится пересохранением
 * в PNG.
 */
export function isAnimatedImage(bytes: Uint8Array, mime: string): boolean {
  if (mime === 'image/gif') return true;
  // APNG: обычный PNG-заголовок, но с чанком `acTL` перед кадрами.
  if (mime === 'image/png') return findTag(bytes, 'acTL', HEADER_SCAN);
  // Анимированный WebP — расширенный контейнер `VP8X` с чанком `ANIM`.
  if (mime === 'image/webp') return findTag(bytes, 'ANIM', HEADER_SCAN);
  return false;
}

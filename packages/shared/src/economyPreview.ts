/**
 * Закрытый показ экономики: список тех, кому она видна на включённом инстансе (#117).
 *
 * 🔴 **Зачем отдельный список, когда есть флаг инстанса и выключатель сервера.** Оба они слишком
 * широкие. Флаг инстанса открывает вкладку «Монеты» КАЖДОМУ владельцу сервера (владелец получает
 * все права разом), а выключатель сервера открывает кошелёк ВСЕМ участникам этого сервера. Для
 * обкатки вдвоём нужна третья, самая узкая мера: поимённо.
 *
 * 🔴 **Пустой список = ограничения нет.** Забытая переменная обязана означать «как было», а не
 * «выключить всем»: иначе обычное обновление инстанса, где экономику уже открыли людям, молча
 * отняло бы её у всех.
 *
 * ⚠️ Это НЕ право доступа и не замена правам. Это временная ширма на время закрытой обкатки:
 * решает, ВИДНО ли фичу вообще, до всех вопросов о том, кому что можно.
 */

/** Разобрать переменную окружения: идентификаторы через запятую, пробелы и пустые куски выкидываем. */
export function parsePreviewList(raw: string | null | undefined): string[] {
  return (raw ?? '')
    .split(',')
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
}

/**
 * Пускать ли этого человека к экономике.
 *
 * ⚠️ Неизвестный человек (`null`) при НЕпустом списке не проходит: закрытый показ обязан
 * ошибаться в сторону «не показывать».
 */
export function previewAllows(list: string[], userId: string | null | undefined): boolean {
  if (list.length === 0) return true;
  return !!userId && list.includes(userId);
}

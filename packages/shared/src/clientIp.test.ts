import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { isInternalAddress, normalizeIp, realClientIp } from './clientIp.js';

describe('нормализация адреса клиента', () => {
  it('снимает IPv4-mapped префикс, порты и скобки, а IPv6 приводит к нижнему регистру', () => {
    // Ловит разные формы одного адреса, которые иначе получили бы независимые лимиты.
    assert.equal(normalizeIp('::ffff:172.18.0.5'), '172.18.0.5');
    assert.equal(normalizeIp('203.0.113.9:51234'), '203.0.113.9');
    assert.equal(normalizeIp('[2001:db8::7]:443'), '2001:db8::7');
    assert.equal(normalizeIp('  2001:DB8::ABCD  '), '2001:db8::abcd');
  });
});

describe('доверенные внутренние адреса прокси', () => {
  it('IPv4-диапазоны принимаются ровно на своих границах и отвергаются рядом', () => {
    // Ловит сдвиг маски, который либо доверит публичный узел, либо перестанет видеть наш прокси.
    const cases: Array<[string, boolean]> = [
      ['9.255.255.255', false],
      ['10.0.0.0', true],
      ['10.255.255.255', true],
      ['11.0.0.0', false],
      ['126.255.255.255', false],
      ['127.0.0.0', true],
      ['127.255.255.255', true],
      ['128.0.0.0', false],
      ['172.15.255.255', false],
      ['172.16.0.0', true],
      ['172.31.255.255', true],
      ['172.32.0.0', false],
      ['192.167.255.255', false],
      ['192.168.0.0', true],
      ['192.168.255.255', true],
      ['192.169.0.0', false],
      ['169.253.255.255', false],
      ['169.254.0.0', true],
      ['169.254.255.255', true],
      ['169.255.0.0', false],
      ['100.63.255.255', false],
      ['100.64.0.0', true],
      ['100.127.255.255', true],
      ['100.128.0.0', false],
    ];
    for (const [ip, expected] of cases) assert.equal(isInternalAddress(ip), expected, ip);
  });

  it('IPv6 loopback, unique-local и link-local внутренние, а соседние и мусор — нет', () => {
    // Ловит ошибку битовой границы в IPv6 и доверие к нераспознанной строке.
    const cases: Array<[string, boolean]> = [
      ['::1', true],
      ['fbff::1', false],
      ['fc00::1', true],
      ['fdff::1', true],
      ['fe80::1', true],
      ['febf::1', true],
      ['fec0::1', false],
      ['2606:4700::1111', false],
      ['unknown', false],
    ];
    for (const [ip, expected] of cases) assert.equal(isInternalAddress(ip), expected, ip);
  });
});

describe('настоящий адрес за цепочкой прокси', () => {
  const peer = '192.168.1.20';

  it('берёт ближайший справа публичный hop, а не подставленную клиентом первую запись', () => {
    // Главная регрессия О5: откат к split(',')[0] снова обходит все лимиты по IP.
    assert.equal(realClientIp('198.51.100.77, 203.0.113.9', peer), '203.0.113.9');
  });

  it('соединение от публичного peer полностью запрещает доверять заголовку', () => {
    // Ловит снятие проверки доверенного прокси: прямой клиент снова сможет выбрать себе ключ лимита.
    assert.equal(realClientIp('198.51.100.77', '203.0.113.50'), '203.0.113.50');
  });

  it('без заголовка возвращает нормализованный адрес соединения', () => {
    // Ловит пустой ключ лимита у прямого или неправильно настроенного подключения.
    assert.equal(realClientIp(undefined, '::ffff:172.18.0.5'), '172.18.0.5');
  });

  it('массив строк заголовка объединяет в одну цепочку', () => {
    // Node допускает string[]; потеря части массива выбрала бы подставленный адрес или сам прокси.
    assert.equal(
      realClientIp(['198.51.100.77', '203.0.113.9, 172.18.0.6'], peer),
      '203.0.113.9',
    );
  });

  it('если все записи внутренние, берёт самую правую', () => {
    // Фиксирует осознанную границу доверия для клиента и прокси внутри одной LAN.
    assert.equal(realClientIp('10.0.0.8, 172.18.0.6', peer), '172.18.0.6');
  });

  it('мусор слева от настоящей записи не перехватывает результат', () => {
    // Ловит чтение цепочки слева направо до первого не-внутреннего значения.
    assert.equal(realClientIp('not-an-ip, 203.0.113.9, 172.18.0.6', peer), '203.0.113.9');
  });

  it('клиент из доверенной LAN может подставить адрес — это принятая граница', () => {
    // Не даёт молча превратить локальную модель доверия в другую при будущем ужесточении.
    assert.equal(realClientIp('198.51.100.77', '192.168.1.44'), '198.51.100.77');
  });

  it('публичный прокси перед нашим становится ключом лимита вместо исходного клиента', () => {
    // Это безопасно грубее: общий адрес внешнего прокси нельзя перескочить подделкой слева.
    assert.equal(
      realClientIp('198.51.100.77, 104.16.0.10, 172.18.0.6', peer),
      '104.16.0.10',
    );
  });
});

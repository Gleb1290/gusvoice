/**
 * Проверка строк, которые приходят снаружи и едут в интерфейс (#139, F1; в `shared` с 22.09).
 *
 * Названия инстансов, имена связок, контакты держателя, ники и имена людей из токена личности и из
 * каталога соседа показываются людям. Строка с управляющими символами, невидимыми метками направления
 * письма или разрывом абзаца — это не «некрасиво», а способ выдать одно за другое: невидимая метка
 * меняет порядок символов при отображении, и `voice.friend.org` превращается в глазах человека в
 * другой адрес.
 *
 * 🔴 Живёт в `shared`, а не в бэкенде, потому что те же границы нужны разбору провода (токен
 * личности, записи каталога, визитка) — а провод разбирается здесь (аудит 19.09, F-06, F-15).
 */

/**
 * Есть ли в строке символы, которых в показываемом тексте быть не должно.
 *
 * Диапазоны заданы кодами, а не литералами: сами эти символы невидимы, и в исходнике их правку
 * невозможно ни заметить, ни проверить глазами.
 */
export function hasHiddenChars(value: string): boolean {
  for (const ch of value) {
    const code = ch.codePointAt(0) ?? 0;
    // Управляющие ASCII (включая перевод строки и табуляцию) и DEL.
    if (code <= 0x1f || code === 0x7f) return true;
    // Нулевая ширина и метки направления письма: 200b–200f, 202a–202e, 2066–2069.
    if (code >= 0x200b && code <= 0x200f) return true;
    if (code >= 0x202a && code <= 0x202e) return true;
    if (code >= 0x2066 && code <= 0x2069) return true;
    // Разрыв строки и абзаца.
    if (code === 0x2028 || code === 0x2029) return true;
  }
  return false;
}

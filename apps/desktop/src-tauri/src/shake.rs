//! Нативная тряска ОКНА — часть МЕГА пока (#117, этап 3).
//!
//! 🔴 **Зачем нативная, если тряска интерфейса уже есть.** Веб-тряска двигает содержимое ВНУТРИ
//! окна: рамка стоит на месте, а страница ездит под ней, и по краям обнажается щель. Нативная
//! двигает само окно — это и есть тот удар, ради которого жест покупают. На вебе так нельзя, на
//! десктопе можно, поэтому она здесь.
//!
//! 🔴 **Затухающая синусоида, а не случайные рывки.** Случайное дрожание читается как повисшее
//! приложение (так выглядит окно, которое не успевает перерисоваться). Затухающее колебание
//! читается как удар: сильный первый мах, дальше всё тише — так ведёт себя всё, по чему стукнули.
//!
//! ⚠️ **Исходная позиция запоминается ДО первого шага и возвращается в конце безусловно.** Складывай
//! мы смещения относительно текущего положения, ошибка округления накапливалась бы, и окно
//! потихоньку уползало бы по экрану от тычка к тычку. Возврат стоит и на пути ошибки тоже.
//!
//! ⚠️ Второй вызов во время тряски ИГНОРИРУЕТСЯ, а не запускает вторую. Две одновременные тряски
//! соревновались бы за позицию окна и оставили бы его где угодно, а «запомненная исходная позиция»
//! у второй оказалась бы уже смещённой.
//!
//! # 🔴 Почему на Windows мы двигаем окно САМИ, а не через `window.set_position`
//!
//! Жалоба 07.09: «приложение скукоживается до меньшего размера, когда человека щипают».
//! Причина — не у нас и не в Windows, а в tao, на котором стоит Tauri
//! (`tao-0.35.3/src/platform_impl/windows/window.rs:229`, `set_outer_position`): ПЕРЕД сдвигом он
//! безусловно снимает флаг развёрнутого окна —
//!
//! ```ignore
//! WindowState::set_window_flags(.., |f| f.set(WindowFlags::MAXIMIZED, false));
//! ```
//!
//! — а применение этого флага (`window_state.rs:377`) делает `ShowWindow(hwnd, SW_RESTORE)`. То есть
//! ПЕРВЫЙ же из наших 65 сдвигов выкидывает развёрнутое окно в «восстановленный», маленький размер;
//! в конце тряска возвращает позицию, но не разворот — и окно так и остаётся скукоженным.
//!
//! ⚠️ **Это именно tao, а не поведение Windows.** Проверено опытом: голый `SetWindowPos` с
//! `SWP_NOSIZE` на развёрнутом окне оставляет его развёрнутым (3456×1408 до и после) и просто
//! двигает. Поэтому лечится не «не трясти развёрнутое», а обходом одной чужой строки.
//!
//! ⚠️ Из потока тряски Tauri НЕ дёргаем вовсе — только WinAPI по снятому заранее HWND. Тот же приём
//! и по той же причине, что в `overlay.rs`: работа с окном Tauri из чужого синхронного потока уже
//! приводила здесь к дедлоку событийного цикла.
//! ⚠️ Цена решения: у развёрнутого окна тряска обнажает по краю полоску рабочего стола — заклеить её
//! своим фоном, как сделано для веб-тряски, тут нечем. Это осознанный размен на сам удар.

use std::sync::atomic::{AtomicBool, Ordering};
use std::time::Duration;

use tauri::Manager;

/// Идёт ли тряска прямо сейчас.
static SHAKING: AtomicBool = AtomicBool::new(false);

/// Длительность. Совпадает с `SHAKE_MS` на клиенте: удар должен кончиться одновременно с ним.
const DURATION_MS: u64 = 520;

/// Шаг анимации. 8 мс — примерно кадр при 120 Гц; чаще двигать окно нет смысла, композитор всё
/// равно не покажет.
const STEP_MS: u64 = 8;

/// Начальная амплитуда в физических пикселях.
///
/// ⚠️ Меньше, чем хочется. Окно — крупный объект, и размах, который на маленьком элементе выглядит
/// бодро, на окне выглядит поломкой драйвера.
const AMPLITUDE_PX: f64 = 14.0;

/// Сколько полных колебаний укладывается в длительность.
const OSCILLATIONS: f64 = 6.0;

/// За что дёргаем окно в потоке тряски: на Windows — сырой HWND, иначе — само окно Tauri.
///
/// 🔴 Разные типы намеренно: на Windows путь через Tauri сломан (см. шапку модуля), а на остальных
/// системах он единственный доступный и работает.
#[cfg(target_os = "windows")]
type ShakeTarget = isize;
#[cfg(not(target_os = "windows"))]
type ShakeTarget = tauri::WebviewWindow;

/// Подвинуть окно, НЕ трогая ни размера, ни разворота, ни Z-порядка, ни фокуса.
#[cfg(target_os = "windows")]
fn move_to(target: &ShakeTarget, x: i32, y: i32) {
    use windows::Win32::Foundation::HWND;
    use windows::Win32::UI::WindowsAndMessaging::{
        SetWindowPos, SWP_ASYNCWINDOWPOS, SWP_NOACTIVATE, SWP_NOOWNERZORDER, SWP_NOSIZE,
        SWP_NOZORDER,
    };
    // SAFETY: HWND снят у живого окна в `shake` и передан сюда как число; окно живёт всё время
    // тряски (полсекунды), а на закрытое `SetWindowPos` просто вернёт ошибку, которую мы глотаем.
    unsafe {
        let _ = SetWindowPos(
            HWND(*target as *mut core::ffi::c_void),
            None,
            x,
            y,
            0,
            0,
            SWP_ASYNCWINDOWPOS | SWP_NOZORDER | SWP_NOOWNERZORDER | SWP_NOSIZE | SWP_NOACTIVATE,
        );
    }
}

#[cfg(not(target_os = "windows"))]
fn move_to(target: &ShakeTarget, x: i32, y: i32) {
    let _ = target.set_position(tauri::PhysicalPosition::new(x, y));
}

/// Тряхнуть главное окно. Возвращает управление сразу — сама тряска идёт в отдельном потоке.
pub fn shake(app: &tauri::AppHandle) {
    // Захват и проверка одним действием: между «проверить» и «поставить» пролезал бы второй вызов.
    if SHAKING.swap(true, Ordering::SeqCst) {
        return;
    }
    let release = || SHAKING.store(false, Ordering::SeqCst);

    let Some(window) = app.get_webview_window("main") else {
        release();
        return;
    };
    let Ok(origin) = window.outer_position() else {
        release();
        return;
    };

    // HWND снимаем ЗДЕСЬ, на вызывающем потоке: в потоке тряски к Tauri уже не обращаемся.
    #[cfg(target_os = "windows")]
    let Ok(target) = window.hwnd().map(|h| h.0 as isize) else {
        release();
        return;
    };
    #[cfg(not(target_os = "windows"))]
    let target = window;

    std::thread::spawn(move || {
        let steps = DURATION_MS / STEP_MS;
        for step in 0..steps {
            let t = step as f64 / steps as f64;
            // Затухание линейное: экспоненциальное на полусекунде почти не отличается на глаз, а
            // читается в коде хуже.
            let decay = 1.0 - t;
            let angle = t * OSCILLATIONS * std::f64::consts::TAU;
            let dx = (angle.sin() * AMPLITUDE_PX * decay).round() as i32;
            // По вертикали вдвое меньше и с другой фазой: одинаковый размах по обеим осям даёт
            // движение по диагонали, а это читается как «окно тащат», а не как удар.
            let dy = ((angle * 0.5).cos() * AMPLITUDE_PX * 0.5 * decay).round() as i32;
            move_to(&target, origin.x + dx, origin.y + dy);
            std::thread::sleep(Duration::from_millis(STEP_MS));
        }
        // Безусловный возврат ровно туда, откуда начали.
        move_to(&target, origin.x, origin.y);
        SHAKING.store(false, Ordering::SeqCst);
    });
}

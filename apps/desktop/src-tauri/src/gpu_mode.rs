//! Принудительное ускорение отрисовки окна — и рубильник к нему.
//!
//! 🔴 **Зачем.** Телеметрия 20.09 (#193): у человека на четырёх ядрах процессы отрисовки съедали
//! 26 % машины в покое и 41 % при показе, тогда как сам показ стоил 8,7 %. Подозрение — движок не
//! задействует видеокарту и растеризует картинку процессором: на не самых свежих драйверах он
//! перестраховывается собственным чёрным списком и молча откатывается на программный путь.
//!
//! Аргументы ниже снимают ровно эту перестраховку. Они передаются движку ПЕРЕД созданием окна —
//! позже их не применить, поэтому вызов стоит первой строкой запуска.
//!
//! ⚠️ **Рубильник обязателен.** На битом драйвере принудительное ускорение даёт артефакты или
//! чёрное окно, а человек в таком состоянии не доберётся до настроек внутри приложения — поэтому
//! отметка живёт в ФАЙЛЕ рядом с настройками, и вернуть как было можно, удалив его.
//! Путь считаем вручную (`%APPDATA%\<id>`), а не через `app.path()`: на момент вызова приложения
//! ещё нет.

use std::path::PathBuf;

/// Имя файла-отметки. Содержимое «0» = человек выключил ускорение; файла нет = включено.
const FILE: &str = "gpu-accel";

/// Флаги движку: не доверять чёрному списку видеокарт, растеризовать на карте, не копировать
/// текстуры лишний раз. Ничего экспериментального — это то, что включено в обычном браузере.
const ARGS: &str = "--ignore-gpu-blocklist --enable-gpu-rasterization --enable-zero-copy";

fn dir() -> Option<PathBuf> {
    std::env::var_os("APPDATA").map(|a| PathBuf::from(a).join("tech.gusik.gusvoice"))
}

/// Включено ли ускорение. Нет файла или он нечитаем — ВКЛЮЧЕНО: умолчание должно быть быстрым, а
/// испорченная отметка не повод отбирать у человека видеокарту.
pub fn enabled() -> bool {
    let Some(p) = dir().map(|d| d.join(FILE)) else {
        return true;
    };
    match std::fs::read_to_string(p) {
        Ok(s) => s.trim() != "0",
        Err(_) => true,
    }
}

/// Запомнить выбор человека. Применится при следующем запуске — движок читает аргументы один раз.
pub fn set(on: bool) -> Result<(), String> {
    let d = dir().ok_or_else(|| "нет папки настроек".to_string())?;
    std::fs::create_dir_all(&d).map_err(|e| e.to_string())?;
    std::fs::write(d.join(FILE), if on { "1" } else { "0" }).map_err(|e| e.to_string())
}

/// Передать аргументы движку. Зовётся ПЕРВОЙ строкой запуска, до создания окна.
///
/// ⚠️ Если переменная уже задана снаружи — не трогаем: так человек (или мы сами при разборе беды)
/// может задать свой набор, и наше умолчание не должно его затирать.
pub fn apply_env() {
    if !enabled() {
        return;
    }
    if std::env::var_os("WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS").is_some() {
        return;
    }
    // SAFETY: зовётся до старта Tauri, в единственном потоке — гонки за окружение здесь нет.
    unsafe {
        std::env::set_var("WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS", ARGS);
    }
}


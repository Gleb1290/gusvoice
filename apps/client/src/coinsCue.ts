/**
 * Когда дёрнуть кошелёк на начислении (#117).
 *
 * 🔴 **Выплата проходит ТИХО** (решение 03.09, после первой живой выплаты): отклик — только
 * небольшая анимация кошелька, без звука. Начисление прилетает САМО, без действия человека, и
 * несколько раз за вечер: звук на него — это оповещение о том, чего никто не просил. Звук остался
 * у ТИПА, потому что тип — чужой жест в твою сторону.
 *
 * 🔴 **Смотрим на `earnedTotal`, а не на баланс.** Баланс шевелится от чего угодно: покупка в
 * магазине, отданный тип, налог. Звенеть на покупку — прямая ложь: монеты ушли, а звук говорит, что
 * пришли. `earnedTotal` растёт только на настоящем заработке — на бэкенде это закреплено списком
 * `EARNED_REASONS` (голос, ретро, гусь, стрик), и полученный тип туда СОЗНАТЕЛЬНО не входит.
 *
 * ⚠️ **Поэтому тип не дёргает кошелёк дважды.** Полученный тип в `earnedTotal` не входит: у него
 * свой отклик по событию `tip`, и оба сработали бы на одну монету.
 *
 * 🔴 **Без прошлого значения не дёргаем.** Первый кошелёк приезжает при открытии сервера: там
 * число вырастает с «не знали» до «столько-то», и это не выплата. Иначе кошелёк прыгал бы при
 * каждом входе в приложение — ровно там, где человек ничего не заработал.
 */
export function shouldPulseWallet(before: number | undefined, after: number): boolean {
  if (before === undefined || !Number.isFinite(before) || !Number.isFinite(after)) return false;
  return after > before;
}

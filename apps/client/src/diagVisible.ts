/**
 * Собирает ли диагностику инстанс, на котором мы сейчас сидим.
 *
 * 🔴 **Главный источник — поле профиля `diagPreview`, а не сохранённый конфиг инстанса.** Бэкенд
 * кладёт в него `DIAG_ENABLED` (`serialize.ts`) и присылает при каждом входе — то есть значение
 * всегда свежее.
 *
 * 🔴 **Почему нельзя опираться на `config.diagEnabled`.** Флаги инстанса сохраняются в реестре
 * (`gv_instances`) в момент, когда сервер ДОБАВЛЯЛИ, и после этого не обновляются никогда. Флаг
 * диагностики появился 28.08, а в десктоп вшит пустой `config.js` — падать не на что. Итог, поймано
 * 20.09: в таблице отчётов на проде НОЛЬ строк за всё время, при исправном сервере, живой ручке
 * приёма и включённом флаге. У всех, кто завёл сервер раньше, не было ни тумблера, ни вопроса.
 * Ровно эта грабля уже ловилась 04.09 на экономике — [[economyVisible]] лечит её тем же способом.
 *
 * ⚠️ Поля нет вовсе (инстанс старой версии или профиль ещё не загружен) — падаем на флаг инстанса:
 * это единственное, что известно до входа, и «как было» тут честнее, чем «выключено».
 */
export function diagVisible(preview: boolean | undefined, instanceFlag: boolean): boolean {
  if (preview === true) return true;
  if (preview === false) return false;
  return instanceFlag;
}

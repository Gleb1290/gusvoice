/**
 * Состояние подписок гейтвея — чистое правило «что и когда слать» (#126).
 *
 * 🔴 **Почему это вынесено из `sockets.ts`.** Здесь жил баг, который дважды выглядел как «у всех
 * пропал звук типа и оверлей», и оба раза его не удавалось найти чтением: он живёт не в звуке и не в
 * оверлее, а в ОЧЕРЁДНОСТИ двух кадров при переподключении.
 *
 * Клиент слал `identify` и следом, в том же кадре, `subscribe`. Сервер обрабатывает `identify`
 * асинхронно (внутри `await` на проверку поколения токена), поэтому пришедший вплотную `subscribe`
 * заставал `conn.userId` ещё пустым и отклонялся с «identify first». Клиент отказ не слушал вовсе, а
 * у себя уже пометил сервер подписанным — и не пересылал никогда.
 *
 * Дальше всё сходилось в наблюдаемую картину: соединение живо, **личные** события (`gw:user:*` —
 * баланс) идут, список в голосе идёт своим сокетом, а всё **серверное** (`gw:server:*` — типы,
 * щипки, саундборд, сообщения) не доходит. Отсюда «работает, потом перестало» после каждой выкатки
 * бэкенда и «лечится только перезапуском приложения».
 *
 * 🔴 **На ПЕРВОМ подключении это не срабатывало** — множество ещё пусто, подписки приезжают позже
 * отдельным запросом и успевают после `identify`. Ломалось ровно ПЕРЕПОДКЛЮЧЕНИЕ, поэтому баг и
 * выглядел как «сломалось само собой в середине дня».
 *
 * Правила ниже втроём закрывают три отдельные дыры:
 *   1. до `ready` не слать ничего — гонки больше нет;
 *   2. на каждый `ready` слать ВЕСЬ список заново — переподключение восстанавливает подписки;
 *   3. отказ сервера снимает отметку «отправлено» — иначе один отказ глушит навсегда.
 */

export interface SubsState {
  /** На что хотим быть подписаны. Живёт между подключениями. */
  want: Set<string>;
  /** Что уже отправлено на ТЕКУЩЕМ соединении. Обнуляется при обрыве. */
  sent: Set<string>;
  /** Пришёл ли `ready` — до него сервер не знает, кто мы. */
  ready: boolean;
}

export function newSubsState(): SubsState {
  return { want: new Set(), sent: new Set(), ready: false };
}

/**
 * Захотели подписаться. Возвращает то, что надо отправить прямо сейчас (пусто — значит рано).
 *
 * ⚠️ Множество `want` пополняется ВСЕГДА, даже когда слать нельзя: именно оно переживает обрыв и
 * восстанавливается на `ready`.
 */
export function wantSub(s: SubsState, serverId: string): string[] {
  s.want.add(serverId);
  if (!s.ready || s.sent.has(serverId)) return [];
  s.sent.add(serverId);
  return [serverId];
}

/** Сервер представился. Слать ВЕСЬ список заново — это и есть восстановление после обрыва. */
export function onReady(s: SubsState): string[] {
  s.ready = true;
  s.sent = new Set(s.want);
  return [...s.want];
}

/** Соединение оборвалось: отправленное на нём больше не считается отправленным. */
export function onDisconnect(s: SubsState): void {
  s.ready = false;
  s.sent.clear();
}

/**
 * Сервер отказал в подписке.
 *
 * ⚠️ Снимаем ТОЛЬКО отметку «отправлено», из `want` не убираем: отказ бывает временным (перезапуск
 * бэкенда, недоступная база), а выбывший из `want` сервер не вернётся уже никогда. Пере-попытка
 * произойдёт на следующем `ready`.
 */
export function onSubRejected(s: SubsState, serverId: string): void {
  s.sent.delete(serverId);
}

/** Выход из аккаунта: следующий вход подпишется на серверы СВОЕГО пользователя. */
export function resetSubs(s: SubsState): void {
  s.want.clear();
  s.sent.clear();
  s.ready = false;
}

import { clampAxis } from './popover';

/** Прямоугольник, в границах которого держим подсказку. `null` — панель ещё не измерена. */
export interface HintHost {
  left: number;
  right: number;
  width: number;
}

/**
 * Где начинается подсказка под мышью: центрируем по кнопке и удерживаем в границах.
 *
 * Вынесено из layout-эффекта `SoundboardPicker` по просьбе Codex, и не зря — в этом расчёте я уже
 * находил руками ДВЕ ошибки, а теста на него не было ни одного.
 *
 * 🔴 **Держим в границах ПАНЕЛИ, а не окна.** Панель саундборда стоит вплотную к сайдбару, и кламп
 * по окну уводил карточку левым краем в список каналов — она висела там ничьей, будто относится к
 * каналу под ней.
 *
 * ⚠️ **Ветка `width <= host.width` — не перестраховка.** Кламп «не левее левого, не правее
 * правого» при отрицательном зазоре (подсказка шире панели) вырождается в «прижать влево», и
 * карточка вылезает за правый край. По нынешним стилям это невозможно — подсказка ≤260, панель
 * ≤320, а на узком окне обе ужимаются одинаково, — но молча полагаться на совпадение чисел нельзя.
 * Не поместилась в панель — держим хотя бы окно.
 */
export function hintLeft(
  cx: number,
  width: number,
  host: HintHost | null,
  viewportWidth: number,
  pad = 8,
): number {
  const wanted = cx - width / 2;
  if (host && width <= host.width) {
    return Math.max(host.left, Math.min(wanted, host.right - width));
  }
  return clampAxis(wanted, width, viewportWidth, pad);
}

/**
 * Показывать ли системное уведомление (#77) — чистое правило, без DOM и без часов внутри.
 *
 * До этого решение жило одной строкой в обработчике сокета и звучало так:
 * `if (notify && mentioned && status !== 'dnd')`. То есть **системное уведомление приходило
 * ТОЛЬКО на @-упоминание**: свернул GusVoice — и про обычное сообщение в канале узнаёшь, только
 * вернувшись в окно. При этом уровень уведомлений канала (`all`/`mentions`/`none`) уже считался
 * строкой выше и уже влиял на бейдж и звук — просто до всплывашки провод не дотянули.
 *
 * Здесь два независимых уровня, и путать их нельзя:
 *  • **глобальный** (`OsNotifyLevel`, настройка приложения) — «выключено / только упоминания / все»;
 *  • **канальный** (`ChannelNotify`, ⚙ у конкретного канала) — «все / только упоминания / заглушён».
 * Уведомление проходит, только если ОБА разрешают. Иначе заглушённый канал начал бы звенеть,
 * стоило включить «все сообщения» глобально.
 */

/** Глобальная настройка приложения. */
export type OsNotifyLevel = 'off' | 'mentions' | 'all';
/** Уровень конкретного канала (`channelPrefs.notifyLevel`). */
export type ChannelNotify = 'all' | 'mentions' | 'none';

/**
 * Не чаще одного уведомления на канал за это время.
 *
 * В живом канале сообщения идут пачками, и двадцать всплывашек подряд — это не «уведомили»,
 * а «завалили». Троттл выбран вместо схлопывания («3 новых сообщения»): предсказуемее и не требует
 * хранить очередь. Упоминания через троттл НЕ проходят — они редкие и адресные.
 */
export const NOTIFY_THROTTLE_MS = 20_000;

export interface NotifyInput {
  /** Глобальная настройка. */
  level: OsNotifyLevel;
  /** Уровень канала, откуда пришло сообщение. */
  channelLevel: ChannelNotify;
  mentioned: boolean;
  /** Статус «не беспокоить». */
  dnd: boolean;
  /** Окно приложения в фокусе — тогда всплывашка не нужна, человек и так смотрит. */
  focused: boolean;
}

/** Показывать ли системное уведомление про сообщение в КАНАЛЕ. */
export function shouldOsNotify(i: NotifyInput): boolean {
  // Смотрит в приложение — интерфейс уже всё показывает, всплывашка только мешает.
  if (i.focused) return false;
  // «Не беспокоить» — это про то, чтобы не дёргать. Гасим и звук, и всплывашку.
  if (i.dnd) return false;
  if (i.level === 'off') return false;
  // Заглушённый канал молчит независимо от глобальной настройки.
  if (i.channelLevel === 'none') return false;
  // Упоминание проходит и при глобальном «только упоминания», и при «все».
  if (i.mentioned) return true;
  // Обычное сообщение — нужно разрешение с ОБЕИХ сторон.
  return i.level === 'all' && i.channelLevel === 'all';
}

/**
 * Личные сообщения. Уровень канала к ним не применяется — ЛС пишут лично тебе, а не в общий чат,
 * поэтому они проходят и при глобальном «только упоминания».
 */
export function shouldOsNotifyDm(i: { level: OsNotifyLevel; dnd: boolean; focused: boolean }): boolean {
  return !i.focused && !i.dnd && i.level !== 'off';
}

/**
 * Прошло ли достаточно времени с прошлого уведомления по этому каналу.
 *
 * `important` (упоминание / ЛС) проходит всегда: адресное сообщение важнее защиты от спама.
 * `lastAt === undefined` — по этому каналу ещё не уведомляли.
 */
export function passesThrottle(
  important: boolean,
  lastAt: number | undefined,
  now: number,
  windowMs: number = NOTIFY_THROTTLE_MS,
): boolean {
  if (important) return true;
  if (lastAt === undefined) return true;
  return now - lastAt >= windowMs;
}

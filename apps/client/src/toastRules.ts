import { TIP_HINT_MS } from './tipHints';

/**
 * Всплывающая плашка поверх игры: «кто кого типнул / ущипнул» (запрос 05.09).
 *
 * 🔴 **Зачем ещё одна поверхность.** Их уже три — строка сайдбара, плашка над чужим стримом и
 * подсказка на нике в оверлее-ростере. Все три требуют, чтобы приложение было ВИДНО: либо на втором
 * мониторе, либо постоянным оверлеем, который «многие не любят». Эта — для тех, кто оверлей держит
 * выключенным: окна не видно, пока ничего не происходит, а на событие оно на несколько секунд
 * показывает крупную надпись и само гаснет.
 *
 * 🔴 **Свой список событий, а не `tipHints`** — и это осознанное исключение из правила «одно
 * событие — одна правда». Причины две, обе про механику чужого списка:
 *  1. **Сюда входит щипок, а туда он входить не должен.** Подсказка сайдбара висит на строке
 *     ПОЛУЧАТЕЛЯ и читается как «тебе прибавилось». У щипка получателю не прибавляется ничего —
 *     платит отправитель. «+400» на строке ущипнутого было бы прямой неправдой.
 *  2. **Вытеснение у них разное.** В сайдбаре стопка ограничена ПО ЧЕЛОВЕКУ (три на строку), здесь —
 *     по экрану целиком. Смешав их, щипок вытеснял бы чужую подсказку из сайдбара.
 * ⚠️ Оба списка наполняются из ОДНОГО места — соседних строк обработчика сокета, — поэтому разойтись
 * в трактовке события они не могут: правка формы события видна сразу обоим.
 */

export type ToastKind = 'tip' | 'poke';

/** Событие, уже готовое к показу: имена разрешены в ники ЭТОГО сервера при добавлении. */
export interface ToastEvent {
  id: string;
  kind: ToastKind;
  fromName: string;
  toName: string;
  /** Сколько монет ушло. У типа — сколько дошло получателю, у щипка — сколько заплатил отправитель. */
  amount: number;
  atMs: number;
}

/**
 * Сколько живёт плашка. Та же константа, что у подсказок: жест один, и знать про него два разных
 * срока — значит однажды объяснять человеку, почему одно и то же держится по-разному.
 */
export const TOAST_MS = TIP_HINT_MS;

/**
 * Сколько строк показываем разом.
 *
 * ⚠️ Две, а не три. Плашка КРУПНАЯ и висит поверх игры: башня из трёх строк в середине экрана — уже
 * не подсказка, а помеха, ради избавления от которой фичу и выключают.
 */
export const TOAST_STACK = 2;

/** Добавить событие, вытеснив самое старое. Вытеснение по ЭКРАНУ, а не по человеку. */
export function addToastEvent(list: readonly ToastEvent[], e: ToastEvent): ToastEvent[] {
  const next = [...list, e];
  return next.length > TOAST_STACK ? next.slice(next.length - TOAST_STACK) : next;
}

/** Убрать отжившее. Страховка на случай, если таймер удаления не сработал (спящая вкладка). */
export function pruneToastEvents(list: readonly ToastEvent[], nowMs: number): ToastEvent[] {
  return list.filter((e) => nowMs - e.atMs < TOAST_MS);
}

/**
 * Начинать ли перетаскивание окна по этому нажатию.
 *
 * 🔴 **Кнопка «Готово» живёт ВНУТРИ перетаскиваемой области, и это ловушка.** Нативное
 * перетаскивание запускается на `pointerdown`; система забирает мышь себе, и `click` по кнопке не
 * наступает НИКОГДА — кнопка выглядит мёртвой («нажал готово и ничего не произошло», 05.09).
 * В оверлее-ростере ту же беду решили структурно: кнопку вынесли ЗА drag-region. Здесь вынести
 * некуда — тащится всё окно целиком, — поэтому исключение делается по ЦЕЛИ нажатия.
 *
 * ⚠️ Вынести кнопку наружу и здесь нельзя не из лени: тогда перетаскиваемой осталась бы только сама
 * надпись, а она в один ряд высотой — промахнуться мимо неё легче, чем попасть.
 */
export function shouldStartDrag(i: { positioning: boolean; button: number; onDoneButton: boolean }): boolean {
  return i.positioning && i.button === 0 && !i.onDoneButton;
}

/**
 * Показывать ли событие этого рода.
 *
 * 🔴 Роды переключаются ПОРОЗНЬ (решение 05.09: «тип и щипок»). Один тумблер на оба означал бы,
 * что человек, которому мешает только щипок, вынужден отключить и то, ради чего фичу включал.
 */
export function toastWants(s: { tips: boolean; pokes: boolean }, kind: ToastKind): boolean {
  return kind === 'tip' ? s.tips : s.pokes;
}

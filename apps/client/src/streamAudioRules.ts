/**
 * Громкость чужого стрим-аудио — ЧИСТО, без LiveKit и без React (#71).
 *
 * Отдельным файлом не ради тестов, а потому что это правило применяется из ДВУХ мест сразу:
 * из сцены голосового канала (пока она на экране) и из `VoiceConnection` (всегда, пока вы в
 * голосе). Разъехавшись, эти два места и дали баг: сцена глушила неоткрытые стримы, а
 * `VoiceConnection` их же включал обратно. Одна функция — расходиться нечему.
 */

/**
 * Нативный стрим публикует ВИДЕО на спутнике `<id>#screen`, а ЗВУК — на основном участнике `<id>`.
 * Поэтому по идентификатору аудио-участника нельзя просто искать совпадение: нужно сопоставлять
 * владельца.
 */
export const ownerOf = (identity: string): string => identity.replace(/#screen$/, '');

/**
 * Потолок личной громкости стрима: 200 %.
 *
 * 🔴 Выше единицы — это УСИЛЕНИЕ, а не «громче колонок» (#130). Оно возможно только потому, что
 * комната собрана с `webAudioMix: true`: звук идёт через узел усиления Web Audio, а не через
 * громкость элемента воспроизведения, у которой диапазон жёстко 0…1 по спецификации. Ровно тем же
 * путём давно ходит личная громкость ЧЕЛОВЕКА (`localUserAudio`, там тот же потолок 2).
 *
 * ⚠️ Почему именно 2, а не больше: усиление тихого источника вытаскивает вместе со звуком и его
 * шум, а на громком начинает хрипеть — клиппинг звучит хуже, чем тихо. Двух крат хватает на
 * «человек говорит тихо», и это ещё не та зона, где ломается всё подряд.
 */
export const MAX_STREAM_VOLUME = 2;

/**
 * Привести громкость к допустимому диапазону.
 *
 * ⚠️ Разделение намеренное, и формулировка тут однажды уже разошлась с кодом (поправлено по разбору
 * Codex): **нечисло** (`NaN`, бесконечность, `undefined` из старого хранилища) даёт **1** — молча
 * онеметь хуже, чем играть на обычной громкости, причину будут искать где угодно, кроме настройки.
 * А вот конечное отрицательное — это не мусор, а внятное «тише некуда», и оно даёт **0**.
 */
export function clampStreamVolume(v: number): number {
  if (!Number.isFinite(v)) return 1;
  return Math.min(MAX_STREAM_VOLUME, Math.max(0, v));
}

/**
 * Привести ВЕСЬ разобранный из хранилища набор громкостей.
 *
 * 🔴 Живёт здесь, а не строчкой внутри стора (просьба Codex, и она справедлива). Первая моя
 * попытка оставила цикл в `store.ts`, а тесты объявляли рядом свою копию этого цикла — то есть
 * проверяли сами себя. Убери нормализацию из стора, и они остались бы зелёными: ровно та иллюзия
 * защиты, которую мы в этот же вечер и разбирали.
 *
 * ⚠️ Сначала проверяется ТИП, и только потом значение. Через `Number(v)` контракт разъезжается:
 * строка даёт `NaN` и честную единицу, а `null` — ноль, то есть молча онемевший стрим. Одна и та
 * же мусорная запись не должна давать два разных исхода в зависимости от своей формы.
 */
export function normalizeStreamVolumes(raw: Record<string, unknown>): Record<string, number> {
  const out: Record<string, number> = {};
  for (const [id, v] of Object.entries(raw)) {
    out[id] = clampStreamVolume(typeof v === 'number' ? v : Number.NaN);
  }
  return out;
}

/**
 * Перенести признак «показывает экран» со спутника `<id>#screen` на самого человека.
 *
 * 🔴 Повод: значок показа ПРОПАДАЛ, стоило зайти в канал к показывающему. Снаружи флаг даёт
 * presence, и там перенос есть (`presenceRules.ts`, `screenOwners`); внутри канала его перебивало
 * живое состояние из LiveKit, где у самого человека `isScreenShareEnabled` = false — потому что
 * видео публикует спутник. Тот же разрыв «спутник против владельца», что однажды уже дал баг со
 * звуком стрима, только с другой стороны.
 *
 * Меняет объект НА МЕСТЕ и возвращает его же: вызывается на каждый тик расчёта, и лишняя копия
 * состояния всех участников тут ни к чему.
 */
export function creditScreenOwners<T extends { screensharing: boolean }>(byIdentity: Record<string, T>): Record<string, T> {
  for (const id of Object.keys(byIdentity)) {
    const owner = ownerOf(id);
    if (owner !== id && byIdentity[id].screensharing && byIdentity[owner]) {
      byIdentity[owner].screensharing = true;
    }
  }
  return byIdentity;
}

/**
 * Насколько громко должно звучать стрим-аудио участника `audioIdentity`.
 *
 * 🔴 **Ноль по умолчанию.** Стрим слышно, только если он ОТКРЫТ — «просто сижу в голосовом» не
 * должно приносить чужой звук. Именно этот дефолт и терялся, когда правило жило лишь в сцене.
 */
export function streamAudioVolume(
  audioIdentity: string,
  watched: string[],
  muted: string[],
  volumeOf: (screenId: string) => number,
): number {
  // Аудио принадлежит открытому стриму, если совпал сам идентификатор (звук на спутнике) или его
  // владелец (звук на основном участнике, видео на спутнике).
  const screenId = watched.find((w) => w === audioIdentity || ownerOf(w) === audioIdentity);
  if (!screenId) return 0;
  if (muted.includes(screenId)) return 0;
  return volumeOf(screenId);
}

/**
 * Загрузить сохранённые громкости из хранилища — ЦЕЛИКОМ, вместе с разбором.
 *
 * 🔴 Вынесено с внедрённым чтением из хранилища по разбору Codex. Пока в сторе оставалась хотя бы
 * одна собственная строка — разбор JSON и вызов приведения, — её откат не красил ни одного теста:
 * правило проверялось, а ПРОВОД к нему нет. Теперь боевой путь и тест зовут одну и ту же функцию,
 * и мутировать в сторе стало нечего.
 *
 * ⚠️ Любой отказ хранилища (приватный режим, битый JSON) — это пустой набор, а не исключение:
 * громкости тут удобство, ронять из-за них загрузку приложения нельзя.
 */
export function loadStreamVolumes(getItem: (key: string) => string | null, key: string): Record<string, number> {
  try {
    return normalizeStreamVolumes(JSON.parse(getItem(key) || '{}') as Record<string, unknown>);
  } catch {
    return {};
  }
}

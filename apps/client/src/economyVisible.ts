/**
 * Видна ли экономика ЭТОМУ человеку на ЭТОМ инстансе.
 *
 * 🔴 **Главный источник — поле профиля `economyPreview`, а не сохранённый конфиг инстанса.** Бэкенд
 * кладёт в него `ECONOMY_ENABLED && закрытый показ пускает этого человека` (`serialize.ts`) и
 * присылает при каждом входе — то есть значение всегда свежее.
 *
 * 🔴 **Почему нельзя опираться на `config.economyEnabled`.** Флаги инстанса сохраняются в реестре
 * (`gv_instances`) в момент, когда сервер ДОБАВЛЯЛИ, и после этого не обновляются никогда. Инстанс,
 * заведённый до включения экономики, помнит `false` вечно: в вебе это лечится тем, что рядом лежит
 * свежий `config.js`, а в десктопе — ничем. Поймано 04.09: в браузере вкладка «Монеты» была, в
 * десктопе её не было вовсе, при одинаково включённой фиче на сервере.
 *
 * ⚠️ Поля нет вовсе (старый бэкенд turnkey или профиль ещё не загружен) — падаем на флаг инстанса:
 * это единственное, что известно до входа, и «как было» тут честнее, чем «выключено».
 */
export function economyVisible(preview: boolean | undefined, instanceFlag: boolean): boolean {
  if (preview === true) return true;
  if (preview === false) return false;
  return instanceFlag;
}

import type { FederationOverview } from '@gusvoice/shared';

/**
 * Состояние федерации для вкладки админки, когда сервер его не отдал (30.09, нашёл держатель коробки с GitHub).
 *
 * 🔴 При `FEDERATION_ENABLED=false` (так коробка ставится по умолчанию) сервер НЕ регистрирует маршруты федерации
 * вовсе — и `GET /admin/federation` тоже (`index.ts`: «выключено => маршрутов нет»). Вкладка получала 404, показывала
 * всплывашку «Not Found» и «Состояние федерации недоступно», а её же экран «Федерация выключена, включается так-то»
 * не срабатывал никогда. У нас на проде федерация включена — поэтому не видели.
 *
 * 404 здесь значит ровно «федерации на этом сервере нет» (выключена или сервер старше неё) — это состояние, а не
 * ошибка. Остальные коды — настоящие сбои, их вызывающий показывает как раньше.
 */
export const FEDERATION_OFF: FederationOverview = {
  status: 'off',
  problem: null,
  paused: false,
  contacts: [],
  instance: null,
  links: [],
};

export function overviewAfterError(status: number | undefined): FederationOverview | null {
  return status === 404 ? FEDERATION_OFF : null;
}

/**
 * У инстанса ДВА названия (#204, мегаприёмка 23.09): «Админка › Инстанс › Название» видят свои люди (экран входа, мастер
 * установки), а соседи по федерации — «Федерация › Этот инстанс › Название». Поля хранятся отдельно, и заполненное первое
 * к соседям не уходит: у облака стояло «Яндекс Гнездышко», а соседи видели голый домен.
 *
 * ⚠️ Подставлять первое во второе САМИМ — решение владельца (это меняет то, что видят соседи), поэтому пока только
 * говорим словами и ничего не подставляем. Подсказки две: под каждым из полей — про другое.
 */
export const LOCAL_NAME_FED_HINT =
  'Соседи по федерации видят другое название — его задают на вкладке «Федерация» в разделе «Этот инстанс». Пока оно пустое, соседям виден только домен.';

/** Подсказка под названием для соседей: оно пустое, а своё название у инстанса есть. `null` — говорить нечего. */
export function neighborNameHint(localName: string | null | undefined, neighborName: string | null | undefined): string | null {
  const local = localName?.trim();
  if (!local || neighborName?.trim()) return null;
  return `Сейчас соседи видят только домен: название «${local}» с вкладки «Инстанс» к ним не уходит. Хотите, чтобы видели его, — впишите его сюда и сохраните.`;
}


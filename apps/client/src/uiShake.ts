/**
 * Тряска всего интерфейса — часть МЕГА пока (#117, этап 3).
 *
 * 🔴 **Трясём `body`, а не `#root`.** `ContextMenu`, `BottomSheet` и `Lightbox` рендерятся через
 * `createPortal` в `body`, то есть ВНЕ корня приложения. Тряси мы корень — открытое меню осталось бы
 * стоять на месте, пока трясётся всё вокруг, и это читалось бы как поломка, а не как эффект.
 *
 * ⚠️ Смещение обнажает полосу за краем экрана. Поэтому амплитуда маленькая, а фон под `body` красится
 * тем же цветом — щель есть, но её не видно.
 *
 * 🔴 Тряска — это полноэкранное движение, самый рискованный тип по вестибулярке (см.
 * `docs/animation-playbook.md`, раздел 3). Поэтому решение показывать её принимает `planEffect`
 * вместе с перьями: при выключенной анимации не остаётся ни того, ни другого.
 */

/** Класс живёт на `body` ровно столько, сколько идёт анимация. */
const CLASS = 'ui-shake';

/**
 * Длительность.
 *
 * ⚠️ Заметно короче осыпания и специально: тряска — это УДАР в начале жеста, а не фон под ним.
 * Растяни её на секунды, и вместо «прилетело» получится «сломался монитор».
 */
export const SHAKE_MS = 520;

let timer: number | null = null;

/**
 * Тряхнуть само ОКНО — только в десктопной оболочке.
 *
 * 🔴 Живёт ЗДЕСЬ, а не у вызывающих: тряску запускают из двух мест слоя перьев, и добавь мы вызов
 * в одном — половина ударов осталась бы без окна. Одна дверь на оба вида тряски.
 *
 * ⚠️ Ошибку глотаем молча. Нет оболочки, нет окна, платформа отказала — жест всё равно состоялся, и
 * превращать украшение в ошибку у покупателя значило бы соврать, что покупка не прошла.
 */
function shakeNativeWindow(): void {
  const core = (window as unknown as { __TAURI__?: { core?: { invoke(cmd: string): Promise<unknown> } } })
    .__TAURI__?.core;
  void core?.invoke('gv_shake_window').catch(() => {});
}

export function shakeUi(doc: Document = document): void {
  const body = doc.body;
  if (!body) return;
  shakeNativeWindow();
  // Повторный удар начинает анимацию заново, а не складывается с прежним.
  body.classList.remove(CLASS);
  // Чтение вынуждает браузер применить снятие класса до того, как мы вернём его обратно; без этого
  // повторный запуск подряд не перезапустил бы анимацию.
  void body.offsetWidth;
  body.classList.add(CLASS);

  if (timer !== null) clearTimeout(timer);
  timer = window.setTimeout(() => {
    body.classList.remove(CLASS);
    timer = null;
  }, SHAKE_MS);
}

/** Снять тряску немедленно — нужно, когда эффект гасят клавишей. */
export function stopShake(doc: Document = document): void {
  if (timer !== null) {
    clearTimeout(timer);
    timer = null;
  }
  doc.body?.classList.remove(CLASS);
}

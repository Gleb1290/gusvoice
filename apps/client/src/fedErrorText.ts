import { FED_ERRORS } from '@gusvoice/shared';

/**
 * Код отказа федерации → фраза для человека (#139, §5.8, §5.11).
 *
 * 🔴 **Повод — приёмка 18.09.** Клиент показывал коды как есть: нажав на гостя в списке участников,
 * человек получал тост «federation.dm_unavailable», а на бессрочную ссылку — красное
 * «federation.invite_no_expiry». Оба раза правда была известна, и текст для неё уже был написан, —
 * просто по дороге его никто не подставил. Жаргон протокола в лицо человеку хуже, чем молчание: он
 * выглядит как поломка и не говорит, что делать дальше.
 *
 * Поэтому перевод живёт ОДНОЙ таблицей и подключён в `toastError`: любой отказ федерации, откуда бы
 * он ни прилетел, доходит словами — включая те места, которые ещё не написаны.
 *
 * ⚠️ Возвращает `null` для незнакомого кода, а не выдумывает причину: коды приходят и от ЧУЖОГО
 * инстанса, который может быть новее нас (`docs/federation-compat.md`). Вызывающий сам решает, чем
 * заменить, — «войти не получилось» в окне входа и исходный текст в тосте звучат по-разному.
 * ⚠️ `who` — как назвать инстанс: название от держателя или домен. `null` — не знаем ничего, и
 * тогда фраза строится без имени, а не с затычкой вроде «другой инстанс».
 */
export function fedErrorText(code: string, who?: string | null): string | null {
  const named = who ? `«${who}»` : null;
  switch (code) {
    // --- Вход по ссылке (§4.2.1). Тексты общие с окном приглашения: у одной причины один текст.
    case FED_ERRORS.noLink:
      return named
        ? `С инстансом ${named} у вашего инстанса нет федерации. Попросите админа своего инстанса связать инстансы.`
        : 'С этим инстансом у вашего нет федерации. Попросите админа своего инстанса связать инстансы.';
    case FED_ERRORS.paused:
      return named ? `Федерация с ${named} сейчас приостановлена.` : 'Федерация с этим инстансом сейчас приостановлена.';
    case FED_ERRORS.trustLost:
      return named
        ? `Связь с ${named} разорвана: инстансы больше не доверяют друг другу. Это чинит админ вашего инстанса.`
        : 'Связь с этим инстансом разорвана. Это чинит админ вашего инстанса.';
    case FED_ERRORS.inviteNoExpiry:
      return named
        ? `Эта ссылка работает только для людей с ${named}. Попросите ссылку со сроком действия.`
        : 'Эта ссылка работает только для своих. Попросите ссылку со сроком действия.';
    case FED_ERRORS.serverClosed:
      return 'Этот сервер закрыт для других инстансов.';
    case FED_ERRORS.inviteExpired:
      return 'Срок действия приглашения истёк.';
    case FED_ERRORS.inviteInvalid:
      return 'Приглашение не найдено. Проверьте ссылку или попросите новую.';
    case FED_ERRORS.banned:
      return named ? `Вход на ${named} для вас закрыт.` : 'Вход на этот инстанс для вас закрыт.';
    case FED_ERRORS.unsupported:
      return named
        ? `Для входа нужна новая версия GusVoice на стороне ${named}.`
        : 'Для входа нужна новая версия GusVoice на одной из сторон.';
    case FED_ERRORS.alreadyMember:
      return 'Вы уже на этом сервере.';

    // --- Жизнь гостя (§5.8). Сюда человек приходит УЖЕ внутри, поэтому фразы говорят не «войдите»,
    // а «этого здесь не бывает» — и, где есть, к кому идти.
    case FED_ERRORS.dmUnavailable:
      return 'Личка между инстансами пока не работает — она появится позже.';
    case FED_ERRORS.guestForbidden:
      return 'Гостю с другого инстанса это недоступно: делается дома, на своём инстансе.';
    case FED_ERRORS.ownerMustBeLocal:
      return 'Владельцем сервера может быть только человек этого инстанса — гостю передать нельзя.';
    case FED_ERRORS.quotaExceeded:
      return named
        ? `Место, отведённое гостям с ${named}, закончилось. Скажите об этом держателю этого инстанса.`
        : 'Место, отведённое гостям, закончилось. Скажите об этом держателю этого инстанса.';

    // --- Служебные отказы. Человек их не чинит, поэтому текст сразу называет того, кто чинит.
    case FED_ERRORS.clockSkew:
      return 'Часы инстансов разошлись — запрос отклонён. Это чинит админ инстанса.';
    case FED_ERRORS.identityInvalid:
      return 'Поручительство вашего инстанса не принято — попробуйте войти заново по свежей ссылке.';
    default:
      return null;
  }
}

/** Похоже ли сообщение на код федерации: коды и только они начинаются с `federation.`. */
export function isFedErrorCode(text: string): boolean {
  return /^federation\.[a-z_]+$/.test(text);
}

import { useMemo } from 'react';
import { nameFromRoster } from './memberNameRules';
import { useStore } from './store';

/**
 * Имя человека В ПРЕДЕЛАХ СЕРВЕРА: ник перекрывает обычное имя (#19/#73).
 *
 * Почему резолвер на отрисовке, а не поле в DTO. Ник — свойство пары «человек↔сервер», а сообщения
 * и участники голоса приходят с ОБЫЧНЫМ именем: у сообщения автор сериализуется из `users`, у голоса
 * имя вшито в LiveKit-токен на 4 часа. Разослать ник во все эти места означало бы либо джойн
 * `server_members` в горячем запросе сообщений, либо перевыпуск токенов при каждой смене ника.
 * Вместо этого имя подставляется из ростера, который у клиента и так есть (`loadMembers` на открытии
 * сервера) и который обновляется живьём по `member.update`.
 *
 * ⚠️ Область действия — ровно текущий сервер. В ЛС резолвер не передаётся вовсе (см. `MessagePane`):
 * серверный ник в личке — это чужая настройка, применённая не к месту.
 *
 * Чистые правила — в `memberNameRules.ts` (этот модуль тянет стор и потому непроверяем).
 */
export type NameResolver = (userId: string, fallback: string) => string;

/**
 * Резолвер имён текущего сервера. Отдаёт ФУНКЦИЮ, а не хук на каждого человека: имена рисуются в
 * циклах (список сообщений, плитки участников), а хук в цикле не вызвать.
 */
export function useNameResolver(): NameResolver {
  const members = useStore((s) => s.members);
  return useMemo(() => {
    const roster = new Map(members.map((m) => [m.user.id, m.nickname]));
    return (userId: string, fallback: string) => nameFromRoster(roster, userId, fallback);
  }, [members]);
}

/**
 * Тот же ник, но для ИМПЕРАТИВНЫХ мест — обработчиков сокета и тостов, куда хук не вставить.
 *
 * ⚠️ Читает ростер в момент вызова, и это правильно: отметка показывается один раз, «живое»
 * обновление ей не нужно. Не знаем человека — отдаём запасное имя из события.
 * 🔴 Годится ТОЛЬКО для событий текущего сервера (канальные: тип, щипок, саундборд). Событие,
 * которое может прийти с ДРУГОГО сервера (личный тычок), сюда пускать нельзя: ростер открытого
 * сервера подставил бы чужой ник — хуже, чем обычное имя.
 */
export function resolveMemberName(userId: string, fallback: string): string {
  const roster = new Map(useStore.getState().members.map((m) => [m.user.id, m.nickname]));
  return nameFromRoster(roster, userId, fallback);
}

/**
 * Какие роли показывать значками на карточке человека.
 *
 * Отдельным файлом не ради тестов, а потому что правило нужно ДВУМ местам сразу: нижней шторке
 * профиля (`MemberProfileSheet`, список участников) и карточке наведения в голосовом сайдбаре.
 * Разъехавшись, они показали бы одному и тому же человеку разный набор ролей в двух местах одного
 * экрана — этот проект уже дважды ловил баги ровно из-за двух копий одного расчёта.
 */

/** Всё, что нужно от роли для значка. Структурно — чтобы правило не тянуло за собой весь `Role`. */
export interface RoleForBadge {
  id: string;
  name: string;
  /** 0xRRGGBB; 0 = цвета нет. */
  color: number;
  position: number;
  isEveryone: boolean;
}

/**
 * Сколько значков влезает, не превращая карточку в простыню.
 *
 * ⚠️ Отсечка идёт ПОСЛЕ сортировки по старшинству, поэтому обрезаются всегда младшие роли:
 * человек видит то, что о собеседнике важнее всего.
 */
export const ROLE_BADGES_MAX = 6;

/**
 * Роли этого человека, от старшей к младшей.
 *
 * ⚠️ `@everyone` отсеивается всегда: она есть у каждого и потому не сообщает ничего.
 * ⚠️ Незнакомые id молча пропускаются — состав ролей мог смениться, пока карточка открыта, и
 * падать из-за этого нельзя.
 */
export function topRoles<T extends RoleForBadge>(
  all: readonly T[],
  roleIds: readonly string[],
  limit: number = ROLE_BADGES_MAX,
): T[] {
  return (
    all
      .filter((r) => !r.isEveryone && roleIds.includes(r.id))
      // `filter` уже вернул новый массив — сортировка на месте исходный не трогает.
      .sort((a, b) => b.position - a.position)
      .slice(0, limit)
  );
}

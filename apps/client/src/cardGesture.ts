/**
 * Что делать с карточкой человека по очередному жесту.
 *
 * Карточка ОДНА на весь сайдбар, и её судьбу решают три жеста: наведение, клик и повторный клик по
 * тому же человеку. Правило вынесено, потому что каждый его пункт — это уже случившаяся ошибка:
 *
 * 🔴 **Закреплённую карточку не крадёт наведение.** Пока правила не было, достаточно было провести
 *    мышкой по соседней строке показывающего — и открытая КЛИКОМ карточка подменялась чужой.
 *    Человек её закрепил, значит собирается в ней читать или нажимать; отнимать её у него из-за
 *    случайного движения мышки нельзя.
 * 🔴 **Повторный клик по тому же человеку закрывает.** Иначе карточка гасла и тут же открывалась
 *    заново — на вид просто моргала, и закрыть её кликом было невозможно.
 *
 * ⚠️ Вся возня с `pointerdown`-мимо и захватом указателя живёт в компоненте: сюда приходит уже
 * готовое «закреплена ли и на ком».
 */

export type CardAction =
  /** Открыть закреплённой (клик). */
  | 'open-pinned'
  /** Открыть по наведению — с задержкой, закрывается уводом мышки. */
  | 'open-hover'
  /** Закрыть: повторный клик по тому же человеку. */
  | 'close'
  /** Ничего не делать: наведение при закреплённой карточке. */
  | 'ignore';

export function cardGesture(p: {
  gesture: 'hover' | 'click';
  /** Кто сейчас показан ЗАКРЕПЛЁННОЙ карточкой; `null` — закреплённой нет. */
  pinnedUserId: string | null;
  targetUserId: string;
}): CardAction {
  if (p.gesture === 'click') {
    return p.pinnedUserId === p.targetUserId ? 'close' : 'open-pinned';
  }
  // Наведение при закреплённой карточке игнорируем ЦЕЛИКОМ — в том числе на том же человеке:
  // иначе увод и возврат мышки понизили бы закреплённую до обычной, и она бы исчезла сама.
  return p.pinnedUserId === null ? 'open-hover' : 'ignore';
}

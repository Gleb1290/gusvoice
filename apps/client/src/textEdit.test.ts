import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { selectedSlice, spliceText } from './textEdit.js';

describe('замена текста в поле', () => {
  it('пустое выделение вставляет текст в позицию курсора', () => {
    // Ловит ошибку, при которой обычная вставка съедает соседний символ.
    assert.deepEqual(spliceText('привет', 3, 3, '—'), { value: 'при—вет', caret: 4 });
  });

  it('выделение до конца строки заменяется целиком', () => {
    // Ловит забытый хвост либо лишний последний символ из-за ошибки полуинтервала.
    assert.deepEqual(spliceText('привет мир', 7, 10, 'чат'), { value: 'привет чат', caret: 10 });
  });

  it('вставка в пустое поле создаёт значение и ставит курсор после него', () => {
    // Ловит отрицательную или потерянную каретку на предельном пустом входе.
    assert.deepEqual(spliceText('', 0, 0, 'текст'), { value: 'текст', caret: 5 });
  });

  it('null-выделение вставляет в конец, а не портит начало строки', () => {
    // Ловит браузерный случай type=email, где selectionStart/End недоступны.
    assert.deepEqual(spliceText('адрес', null, null, '@gus.dev'), {
      value: 'адрес@gus.dev',
      caret: 13,
    });
  });

  it('перевёрнутое выделение нормализуется', () => {
    // Ловит мусор от slice, если браузер или вызывающий передал end меньше start.
    assert.deepEqual(spliceText('abcdef', 5, 2, 'X'), { value: 'abXf', caret: 3 });
  });

  it('координаты за границами строки безопасно прижимаются', () => {
    // Ловит дублирование строки и неверную каретку на отрицательных или слишком больших индексах.
    assert.deepEqual(spliceText('abc', -10, 99, 'X'), { value: 'X', caret: 1 });
  });
});

describe('чтение выделенного текста', () => {
  it('возвращает выбранный полуинтервал', () => {
    // Ловит копирование соседнего символа из-за включённой правой границы.
    assert.equal(selectedSlice('abcdef', 1, 4), 'bcd');
  });

  it('перевёрнутое выделение читается в обычном порядке', () => {
    // Ловит пустое копирование при направлении выделения справа налево.
    assert.equal(selectedSlice('abcdef', 5, 2), 'cde');
  });

  it('null-границы означают отсутствие выделения', () => {
    // Ловит случайное копирование всего поля, когда браузер не поддерживает selectionStart.
    assert.equal(selectedSlice('секрет', null, null), '');
  });
});

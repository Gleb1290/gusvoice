import { EFFECT_MS } from './effects';

/**
 * Физика падения перьев — ЧИСТАЯ, без канвы и React (#117, этап 3).
 *
 * 🔴 Вынесено из слоя после живой проверки, где перья **не долетали до низа экрана**. Причина была
 * арифметическая: скорость задавалась в пикселях в секунду, то есть эффект вообще не масштабировался
 * под окно — на ноутбуке частица проходила почти весь экран, на широком мониторе четверть. Такое
 * ловится расчётом за секунду и не ловится глазами, если смотреть на одном экране. Поэтому модель
 * живёт здесь и проверяется тестом на разных раскладках, а слой только рисует.
 *
 * 🔴 Из физики берём ХАРАКТЕР, а не скорость. Измеренная предельная скорость падающей пластины —
 * 0.145 м/с; настоящее перо пересекало бы окно 4–10 секунд. Скорость завышена сознательно, разбор —
 * `docs/animation-playbook.md`, раздел 5. В сторону реализма не «чинить».
 */

/**
 * Боевой размер частицы по большей стороне.
 *
 * 🔴 Это **перья МАСКОТА**, и числа взяты от него, а не на глаз: гусь на экране примерно 200 px, у
 * птицы перо составляет от пятой до третьей части тела — отсюда 30–64.
 * ⚠️ 10–22 → 30–64 → **38–86**, оба раза по живой проверке: сначала «супер маленькие», потом «перьев
 * маловато». Размер работает на плотность сильнее числа частиц — покрытие растёт как КВАДРАТ размера,
 * а от количества линейно, поэтому подняли и его.
 * 🔴 Исходники 44–48 px, значит верхняя граница тянется почти вдвое и на плотном экране будет слегка
 * мылить. Ради нужной плотности это принято осознанно; чтобы стало резко, нужны кадры в 128 px —
 * заказывать их, а не растягивать эти дальше.
 */
/**
 * Политика отступления при медленных кадрах — вынесена из слоя по разбору Codex.
 *
 * 🔴 Пока она жила внутри цикла отрисовки, проверить её было НЕЧЕМ: цикл требует канвы, картинок и
 * настоящих кадров. А вопрос она решает не косметический — сколько частиц останется на слабой
 * машине, то есть выполняется ли вообще обещание «на полсекунды перья занимают весь экран».
 * ⚠️ Ответ честный: на слабой машине НЕ выполняется, и это осознанный размен. Лучше дать нужный вид
 * всем, кто тянет, и отступить по факту, чем занизить заранее для каждого.
 */

/** Кадр длиннее этого считается медленным (меньше 50 в секунду). */
export const SLOW_FRAME_MS = 20;
/** Столько медленных кадров подряд — и режем частицы. */
export const SLOW_FRAMES_BEFORE_CUT = 6;
/** Сколько остаётся от текущего числа при каждом отступлении. */
export const CUT_FACTOR = 0.75;
/** Ниже этого не опускаемся: при таком числе эффект перестаёт читаться как осыпание. */
export const ACTIVE_MIN = 150;
/**
 * Первые миллисекунды не считаем: там разогрев и декодирование картинок, по ним судить нельзя.
 * ⚠️ Без этой отсечки эффект резал бы себя на КАЖДОМ запуске, включая мощные машины.
 */
export const WARMUP_MS = 400;

export interface DegradeState {
  active: number;
  slowFrames: number;
}

/**
 * Шаг политики отступления. Возвращает новое состояние; вход не меняет.
 *
 * ⚠️ Число частиц НИКОГДА не растёт обратно. Восстановление выглядело бы как пульсация плотности —
 * машина то тянет, то нет, — а это заметнее, чем просто чуть более редкий дождь.
 */
export function degradeStep(state: DegradeState, elapsed: number, frameMs: number): DegradeState {
  if (elapsed <= WARMUP_MS || frameMs <= SLOW_FRAME_MS) return state;
  const slowFrames = state.slowFrames + 1;
  if (slowFrames < SLOW_FRAMES_BEFORE_CUT) return { active: state.active, slowFrames };
  return { active: Math.max(ACTIVE_MIN, Math.round(state.active * CUT_FACTOR)), slowFrames: 0 };
}

/**
 * Занятость экрана перьями — по СЕТКЕ, а не суммой площадей (разбор Codex).
 *
 * 🔴 Сумма площадей отвечала не на тот вопрос. Она считает наложения по нескольку раз и ничего не
 * знает о том, ГДЕ частицы: стопка перьев в центре экрана даёт ту же сумму, что и равномерный
 * дождь, — и проходит проверку «перья занимают всё пространство», не занимая ничего, кроме центра.
 * Сетка отвечает буквально: в скольких клетках экрана перо есть хоть одно.
 *
 * ⚠️ Клетка считается занятой по ГАБАРИТУ пера, а не по его центру: перо на границе видно в обеих
 * клетках, и считать его только в одной значило бы занижать край экрана — ровно там, где на широком
 * мониторе и была дыра.
 */
export function gridCoverage(
  fs: Feather[],
  w: number,
  h: number,
  elapsed: number,
  cols = 8,
  rows = 6,
): number {
  const cellW = w / cols;
  const cellH = h / rows;
  const filled = new Set<number>();
  for (const f of fs) {
    if (elapsed < f.delay) continue;
    const half = f.size / 2;
    const c0 = Math.max(0, Math.floor((f.x - half) / cellW));
    const c1 = Math.min(cols - 1, Math.floor((f.x + half) / cellW));
    const r0 = Math.max(0, Math.floor((f.y - half) / cellH));
    const r1 = Math.min(rows - 1, Math.floor((f.y + half) / cellH));
    // Частица целиком за кромкой — её и не видно.
    if (c1 < c0 || r1 < r0) continue;
    for (let r = r0; r <= r1; r++) for (let c = c0; c <= c1; c++) filled.add(r * cols + c);
  }
  return filled.size / (cols * rows);
}

export const SIZE_MIN = 38;
export const SIZE_MAX = 86;

/** Сколько миллисекунд в конце уходит на затухание: последние перья должны истаять, а не пропасть. */
export const FADE_MS = 900;

/**
 * Окно появления: за это время подходят все частицы.
 *
 * 🔴 Оно же и создаёт «момент, когда перья занимают всё пространство». Одновременно на экране
 * находится примерно `N × время_полёта / (окно + время_полёта)` — то есть чем шире окно, тем более
 * растянуто и жидко осыпание. 1600 мс подобраны так, чтобы пик набрался быстро и держался, а не
 * мелькнул одним кадром.
 * ⚠️ Было 700 при длительности 4200. Растянуто вместе с самим эффектом.
 */
export const MAX_DELAY_MS = 1600;

/**
 * Насколько средняя скорость за полёт ниже предельной.
 *
 * Перо стартует медленно и разгоняется, приближаясь к предельной скорости, — то есть проходит
 * меньше, чем `vTerm × время`. Множитель подобран к модели сопротивления ниже и нужен, чтобы
 * «долетит до низа» считалось честно, а не с запасом на глазок.
 */
export const AVG_OF_TERMINAL = 0.82;

export interface Feather {
  x: number;
  y: number;
  /** Горизонтальная скорость сноса, px/с. */
  vx: number;
  /** Вертикальная скорость, px/с. */
  vy: number;
  /** Предельная скорость этой частицы — к ней её и тянет сопротивление. */
  vTerm: number;
  size: number;
  angle: number;
  /** Угловая скорость, рад/с. */
  spin: number;
  /** Порхание — колебание вбок; кувыркание — непрерывное вращение. */
  mode: 'flutter' | 'tumble';
  /** Частота порхания, Гц, и его фаза — чтобы частицы не качались строем. */
  freq: number;
  phase: number;
  sprite: number;
  /** Задержка старта, мс. */
  delay: number;
}

/** Источник случайности — параметром, чтобы тест мог задать свой и получить воспроизводимость. */
export type Rand = () => number;

/**
 * Раздать частицам стартовые состояния.
 *
 * 🔴 **Скорость выводится из ВЫСОТЫ ОКНА и оставшегося времени**, а не задана в пикселях в секунду:
 * для каждой частицы считается, сколько ей лететь и сколько у неё на это времени. Именно это делает
 * эффект одинаковым на ноутбуке и на широком мониторе.
 */
export function makeFeathers(width: number, height: number, count: number, rand: Rand = Math.random): Feather[] {
  const out: Feather[] = [];
  for (let i = 0; i < count; i++) {
    // ⚠️ Появление ЗА краями по горизонтали тоже: осыпание идёт «отовсюду», а частицы, начинающиеся
    // ровно от кромок, дают заметные пустые углы.
    const x = -80 + rand() * (width + 160);
    const size = SIZE_MIN + rand() * (SIZE_MAX - SIZE_MIN);
    /**
     * 🔴 Полоса старта — ДОЛЯ высоты окна, а не 320 пикселей. Это ровно та же ошибка, что уже
     * чинили здесь для бокового сноса, и нашлась она тем же способом — измерением.
     *
     * Стая растянута по вертикали настолько, насколько растянуты точки старта. Абсолютная полоса на
     * ноутбуке (768) занимала 42 % высоты, а на вертикальном мониторе (2560) — 12 %: там перья шли
     * узкой лентой, и НИЖНЯЯ ТРЕТЬ экрана оставалась пустой в самый плотный момент. Замер по сетке:
     * 32 клетки из 48, два нижних ряда пустые совсем.
     * ⚠️ Доля подобрана так, чтобы на ноутбуке получилось прежнее число — вид, который уже
     * приняли глазами, менять незачем.
     */
    const startAbove = 40 + rand() * (height * 0.42);
    const delay = rand() * MAX_DELAY_MS;

    // Сколько лететь: от точки старта над экраном до полного ухода за нижний край.
    const travel = height + startAbove + size * 2;
    // Сколько на это есть: до НАЧАЛА затухания, иначе перо истает на полпути.
    const usableS = Math.max(0.7, (EFFECT_MS.feathers - delay - FADE_MS) / 1000);
    // Крупные перья падают чуть быстрее мелких — разнобой размеров читается и в движении. Нижняя
    // граница разброса подобрана так, чтобы даже самое медленное перо успело дойти до низа.
    const spread = 0.92 + ((size - SIZE_MIN) / (SIZE_MAX - SIZE_MIN)) * 0.22 + rand() * 0.16;
    const vTerm = ((travel / usableS) / AVG_OF_TERMINAL) * spread;

    out.push({
      x,
      // Стартуем ВЫШЕ экрана, вразнобой по высоте: иначе первый кадр — ровная строка перьев.
      y: -startAbove,
      // Сносим вбок: вертикальное падение читается как дождь, а не как осыпание.
      // 🔴 Снос считается от ШИРИНЫ окна, а не от скорости падения. Привязка к скорости выглядела
      // логичной и была неверной: скорость растёт с ВЫСОТОЙ, поэтому на высоком узком экране
      // (1440×2560) перья за полёт уносило больше чем на ширину окна — они улетали за правый край
      // и осыпания там просто не было. Теперь снос — это 10–32 % ширины за полёт, одинаково везде.
      vx: (0.1 + rand() * 0.22) * (width / usableS),
      vy: vTerm * 0.25,
      vTerm,
      size,
      angle: rand() * Math.PI * 2,
      spin: (rand() < 0.5 ? -1 : 1) * (0.6 + rand() * 1.6),
      // Порхающих больше: кувыркание красиво поодиночке, но толпой превращается в мельтешение.
      mode: rand() < 0.68 ? 'flutter' : 'tumble',
      freq: 0.6 + rand() * 1.1,
      phase: rand() * Math.PI * 2,
      sprite: i % 4,
      delay,
    });
  }
  return out;
}

/**
 * Продвинуть частицу на шаг.
 *
 * ⚠️ `dt` приходит из РАЗНИЦЫ кадров, а не из константы: на 144 Гц и на 30 Гц перья обязаны падать
 * одинаково, иначе эффект живёт разное время у разных людей.
 * ⚠️ Ускорение считается ОТ предельной скорости частицы, а не постоянным: с постоянным разгон до
 * высокой скорости на большом экране занимал бы заметную долю полёта, и перо снова не успевало бы.
 */
export function stepFeather(f: Feather, elapsedMs: number, dt: number): void {
  if (elapsedMs < f.delay) return;
  const t = (elapsedMs - f.delay) / 1000;

  // Квадратичное сопротивление: ускорение падает по мере приближения к предельной скорости.
  const k = 1 - (f.vy / f.vTerm) ** 2;
  f.vy += f.vTerm * 2.4 * Math.max(0, k) * dt;

  if (f.mode === 'flutter') {
    // Порхание — колебание вбок; вращение следует за ним, а не идёт само по себе.
    const sway = Math.sin(t * f.freq * Math.PI * 2 + f.phase);
    f.x += (f.vx + sway * f.vTerm * 0.5) * dt;
    f.angle = sway * 0.9;
  } else {
    f.x += f.vx * dt;
    f.angle += f.spin * dt;
  }
  f.y += f.vy * dt;
}

/** Прозрачность на этом миллисекунде: последние перья истаивают, а не исчезают разом. */
export function featherFade(elapsedMs: number): number {
  const tail = EFFECT_MS.feathers - FADE_MS;
  if (elapsedMs <= tail) return 1;
  return Math.max(0, (EFFECT_MS.feathers - elapsedMs) / FADE_MS);
}

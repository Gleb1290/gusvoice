/**
 * Сколько осталось до закрытия опроса (#17) — чистая функция, без React и без часов внутри.
 *
 * Вынесено из `PollCard.tsx` по замечанию Codex: расчёт сидел внутри компонента и потому не
 * проверялся, а ошибка в нём была настоящая (см. ниже про округление).
 */

/**
 * `null` — опрос уже закрыт (время вышло).
 *
 * ⚠️ Округление ВВЕРХ, а не к ближайшему. С `Math.round` остаток в 20 секунд превращался в
 * «осталось 0 мин» — надпись, которая читается как «всё, поздно», хотя проголосовать ещё можно.
 * Вверх — единственный вариант, при котором подпись никогда не обещает меньше, чем есть.
 */
export function pollTimeLeft(closesAt: string, now: number = Date.now()): string | null {
  const ms = new Date(closesAt).getTime() - now;
  if (!Number.isFinite(ms) || ms <= 0) return null;

  // Единицу выбираем по ФАКТИЧЕСКОМУ остатку, а округляем вверх только минуты.
  // ⚠️ Цепочка ceil (минуты → часы → дни) давала скачок: «час и одна миллисекунда» показывались
  // как «2 ч», а сутки с миллисекундой — как «2 дн». Нашёл Codex.
  const d = Math.floor(ms / 86_400_000);
  if (d >= 1) return `осталось ${d} дн`;
  const h = Math.floor(ms / 3_600_000);
  if (h >= 1) return `осталось ${h} ч`;
  const min = Math.ceil(ms / 60_000);
  // 59:31 округляется вверх до 60 минут — это уже час, а не «60 мин».
  return min >= 60 ? 'осталось 1 ч' : `осталось ${min} мин`;
}

import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { hintLeft } from './hintPlacement.js';

/** Панель саундборда: 320 шириной, стоит у левого края экрана. */
const panel = { left: 12, right: 332, width: 320 };
const VW = 1920;

describe('где встаёт подсказка', () => {
  it('в спокойном случае центрируется по кнопке', () => {
    // Кнопка в середине панели, подсказка узкая — ничего никуда не упирается.
    assert.equal(hintLeft(172, 200, panel, VW), 72);
  });

  it('🔴 у левого края держится за ПАНЕЛЬ, а не за окно', () => {
    // Была моя ошибка: кламп по окну пускал карточку до 8 px, то есть левее панели — в список
    // каналов. Она висела там ничьей, будто относится к каналу под ней.
    assert.equal(hintLeft(30, 240, panel, VW), panel.left);
  });

  it('у правого края панели тоже не вылезает', () => {
    assert.equal(hintLeft(330, 240, panel, VW), panel.right - 240);
  });

  it('🔴 подсказка ШИРЕ панели — держим окно, а не вырождаемся в «прижать влево»', () => {
    // Вторая моя ошибка, найденная на стенде: при отрицательном зазоре кламп «не левее левого, не
    // правее правого» схлопывается в левый край, и карточка вылезает за правый край панели.
    // По нынешним стилям такого не бывает, но полагаться на совпадение чисел молча нельзя.
    const wide = 400;
    const left = hintLeft(172, wide, panel, VW);
    assert.ok(left + wide <= VW - 8, 'в окно вписались');
    assert.notEqual(left, panel.left, 'и это НЕ вырожденный «прижать влево»');
  });

  it('подсказка шире панели остаётся внутри окна у обеих его кромок', () => {
    // Ловит ложнозелёный wide-кейс: проверки только правого края и panel.left пропускают отрицательный left.
    assert.equal(hintLeft(0, 400, panel, VW), 8);
    assert.equal(hintLeft(VW, 400, panel, VW), VW - 400 - 8);
  });

  it('панель ещё не измерена — работает кламп по окну', () => {
    assert.equal(hintLeft(10, 200, null, VW), 8);
    assert.equal(hintLeft(VW, 200, null, VW), VW - 200 - 8);
  });

  it('ровно по ширине панели — граничный случай идёт по «панельной» ветке', () => {
    // `width <= host.width`, не `<`: подсказка шириной ровно с панель обязана встать в панель.
    assert.equal(hintLeft(0, panel.width, panel, VW), panel.left);
    assert.equal(hintLeft(9999, panel.width, panel, VW), panel.left);
  });
});

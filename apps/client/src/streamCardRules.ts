/**
 * Откуда карточка неоткрытого показа берёт картинку: готовое превью показа (#115) или кадр с самого
 * потока — без React, LiveKit и сети на импорте, всё живое приходит параметрами.
 *
 * Вынесено из `VoiceChannelView.tsx` по просьбе Codex (2026-09-26): компонент тянет React и LiveKit, и
 * главное правило #207 — «есть превью → на поток не подписываемся вовсе» — проверить было нечем.
 *
 * 🔴 Почему превью ПЕРВЫМ (#207, 25.09). Телеметрия показала: снимок с живого потока раз в минуту будил
 * у показывающего ВСЕ три слоя (сервер сначала отдаёт верхний, просьба о нижнем приходила уже после
 * подписки) — три сеанса NVENC и опорные кадры на 4–5 секунд. С dynacast в остальное время кодировщик
 * спит, и этот рывок раз в минуту совпал с микрофризами мыши у показывающего. Картинку #115 он отдаёт
 * и так, кодировщик она не трогает. Снимок с потока остаётся запасным путём (человек выключил отдачу
 * превью), и тогда нижний слой просим СРАЗУ после подписки.
 */

/** Как часто обновляется снимок с потока (запасной путь): свежий кадр раз в минуту. */
export const SNAPSHOT_EVERY_MS = 60_000;

/**
 * Как часто карточка берёт готовое превью показа (#115). Оно дешёвое — картинка, которую показывающий
 * и так отдаёт раз в 5 с для подсказки по наведению, — поэтому чаще, чем снимок с живого потока.
 */
export const PREVIEW_EVERY_MS = 20_000;

/**
 * Чистое: рисует ли карточка снимки (чужой показ, у публикации есть управление подпиской) или живой трек.
 *
 * Свой браузерный показ остаётся живым: это наш же захват, декодировать его ничего не стоит. Всё
 * остальное — снимком, чтобы неоткрытый показ не декодировался в полном размере без остановки.
 */
export function canSnapshotStream(isLocal: boolean, pub: { setSubscribed?: unknown } | null | undefined): boolean {
  return !isLocal && typeof pub?.setSubscribed === 'function';
}

/** Всё живое для одного захода карточки: сеть, подписка LiveKit, захват кадра и таймер. */
export interface StreamCardCycleDeps<T> {
  /** Голосовой канал; без него превью спросить негде — сразу запасной путь. */
  channelId: string | null | undefined;
  /** Чей показ (владелец, не идентификатор спутника `#screen`). */
  ownerId: string;
  /** Карточка размонтирована или сменила поток — дальше ничего не делаем. */
  cancelled: () => boolean;
  /** Готовое превью показа (#115); ошибка = превью нет. */
  getPreview: (channelId: string, ownerId: string) => Promise<{ image?: string | null }>;
  setSnapshot: (url: string) => void;
  setSubscribed: (on: boolean) => void;
  /** Попросить у сервера нижний слой. */
  requestLow: () => void;
  /** Дождаться живого трека после подписки; `null` — не дождались. */
  waitTrack: () => Promise<T | null>;
  /** Снять один кадр с трека; `null` — кадра нет. */
  capture: (track: T) => Promise<string | null>;
  /** Запланировать следующий заход через `ms`. */
  next: (ms: number) => void;
}

/**
 * Один заход карточки показа; без побочных эффектов на импорте — всё живое только через `d`.
 *
 * 1. Есть канал → спрашиваем готовое превью. Пришла картинка → показываем её, следующий заход через
 *    `PREVIEW_EVERY_MS`, на поток НЕ подписываемся вовсе.
 * 2. Превью нет (ошибка, пустой ответ) или нет канала → запасной путь: подписка и просьба о нижнем
 *    слое в ТОМ ЖЕ такте, до ожидания трека (иначе сервер успеет отдать верхний и разбудит его у
 *    показывающего), кадр, отписка, следующий заход через `SNAPSHOT_EVERY_MS`.
 * ⚠️ После отмены ничего не пишем и не планируем; отписку при отмене делает сам компонент в очистке.
 */
export async function streamCardCycle<T>(d: StreamCardCycleDeps<T>): Promise<void> {
  if (d.cancelled()) return;
  if (d.channelId) {
    try {
      const { image } = await d.getPreview(d.channelId, d.ownerId);
      if (d.cancelled()) return;
      if (image) {
        d.setSnapshot(image);
        d.next(PREVIEW_EVERY_MS);
        return;
      }
    } catch {
      /* превью нет (выключено у показывающего) — берём кадр с потока */
    }
  }
  if (d.cancelled()) return;
  try {
    d.setSubscribed(true);
    // Нижний слой — сразу, до того как сервер начнёт отдавать верхний и разбудит его у показывающего.
    d.requestLow();
    const track = await d.waitTrack();
    if (d.cancelled()) return;
    if (track) {
      const url = await d.capture(track);
      if (!d.cancelled() && url) d.setSnapshot(url);
    }
  } catch {
    /* keep the previous snapshot */
  } finally {
    if (!d.cancelled()) {
      d.setSubscribed(false);
      d.next(SNAPSHOT_EVERY_MS);
    }
  }
}

/**
 * Что делать, когда Rust сообщил, что второй слой качества показа выключен не человеком (#112/#109).
 *
 * 🔴 Это МЕЖЪЯЗЫКОВОЙ контракт, и до 06.09 его не было ни с одной стороны. Строки приходят из
 * `screenshare.rs` (`LayersOff::as_str()`), а решение «трогать ли настройку насовсем» принимается
 * здесь. Разбор Codex показал цену такой бесшовности: **перепутай `crash` и `crash-final` в Rust —
 * и временный отказ станет постоянным, а все Rust-тесты останутся зелёными.** Теперь строки
 * закреплены тестами с ОБЕИХ сторон, и это единственное, что связывает половины.
 *
 * ⚠️ Разделение временного и постоянного — суть починки #109, а не оттенок. Одно падение (обычно
 * наш собственный баг) снимает слой на ОДИН показ и настройку НЕ трогает; постоянное выключение
 * заслуживают только свойство железа и серия падений подряд. Пока разделения не было, одна беда
 * навсегда лишала человека слоя, а расплачивался за это весь канал.
 */
export interface LayersOffPlan {
  /** Править ли сохранённую настройку показа (то есть выключить слой насовсем). */
  persistOff: boolean;
  title: string;
  text: string;
}

export function layersOffPlan(reason: string): LayersOffPlan {
  if (reason === 'crash') {
    return {
      persistOff: false,
      title: 'Этот показ идёт одним слоем качества',
      text: 'Прошлый показ оборвался падением приложения. Следующий снова пойдёт двумя слоями.',
    };
  }
  if (reason === 'old-gpu') {
    return {
      persistOff: true,
      title: 'Показ идёт одним слоем качества',
      text: 'На вашей видеокарте второй слой роняет приложение. Включить обратно можно в настройках показа.',
    };
  }
  if (reason === 'crash-final') {
    return {
      persistOff: true,
      title: 'Показ идёт одним слоем качества',
      text: 'Показ оборвался падением три раза подряд. Оставили один слой; включить второй можно в настройках показа.',
    };
  }
  // ⚠️ Незнакомая причина ПОСТОЯННА (ошибиться в эту сторону дешевле: временная по умолчанию тихо
  // вернула бы слой туда, где его осознанно отобрали), но текст ей — общий. Раньше сюда падал и
  // `crash-final`, и любое будущее значение получало вместе с ним чужое объяснение «три падения
  // подряд» — то есть приложение сообщало человеку выдуманный факт. Поймал Codex.
  return {
    persistOff: true,
    title: 'Показ идёт одним слоем качества',
    text: 'Второй слой качества отключён. Включить обратно можно в настройках показа.',
  };
}

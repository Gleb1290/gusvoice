/**
 * Сколько канал уже занят — счёт на стороне клиента (решение 02.09).
 *
 * 🔴 **Сервер присылает число ОДИН раз, дальше клиент считает сам.** Так и было предложено, и это
 * заметно лучше периодических пушей: секунду тикает вкладка, а сеть трогают только когда канал
 * реально занялся или опустел. На двадцати каналах разница между «пуш раз в секунду» и «два пуша за
 * вечер» — это разница между шумом и тишиной.
 *
 * 🔴 **Приходит ПРОШЕДШЕЕ ВРЕМЯ, а не отметка времени.** Иначе клиент вычитал бы серверное время из
 * своего, а часы у людей разъезжаются на минуты — таймер врал бы у каждого по-своему.
 *
 * 🔴 **Якорь — `performance.now()`, а не `Date.now()`.** Он монотонный: не прыгает от перевода
 * часов и синхронизации по NTP, и продолжает идти, пока вкладка в фоне. `setInterval` в фоне
 * душится браузером, поэтому досчитывать надо ОТ ЯКОРЯ, а не складывать тики: вернувшись во вкладку
 * через час, человек должен увидеть плюс час, а не плюс столько, сколько успело тикнуть.
 */

export interface Occupancy {
  /** Сколько канал был занят на момент, когда сервер это сказал. */
  ms: number;
  /** Показание монотонного счётчика в момент получения. */
  anchor: number;
}

/** Сколько канал занят СЕЙЧАС. */
export function occupiedNow(o: Occupancy, now: number): number {
  return Math.max(0, o.ms + (now - o.anchor));
}

/**
 * Подпись таймера.
 *
 * 🔴 Часы появляются, только когда они есть: `7:12` в первые минуты честнее, чем `0:07:12` — ведущий
 * ноль часа читается как «что-то сломалось». Минуты при этом ВСЕГДА двузначные после часа
 * (`1:05:09`), иначе строка прыгает по ширине каждую минуту и дёргает соседний текст.
 * ⚠️ Отрицательное и нечисловое схлопываем в ноль: расхождение часов или битое число не должны
 * рисовать «-1:59:59».
 */
export function occupancyText(ms: number): string {
  if (!Number.isFinite(ms) || ms < 0) ms = 0;
  const total = Math.floor(ms / 1000);
  const h = Math.floor(total / 3600);
  const m = Math.floor((total % 3600) / 60);
  const s = total % 60;
  const ss = String(s).padStart(2, '0');
  if (h === 0) return `${m}:${ss}`;
  return `${h}:${String(m).padStart(2, '0')}:${ss}`;
}

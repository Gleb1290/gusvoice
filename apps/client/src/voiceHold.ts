/**
 * Жест кнопки записи голосового на телефоне (#159, как в Telegram).
 *
 * Пока поле ввода пустое, на месте «отправить» стоит микрофон:
 * - **держишь** — пишет, **отпустил** — ушло;
 * - **смахнул вверх** — запись фиксируется и идёт без рук, до кнопки «отправить» или корзины;
 * - **смахнул влево** — запись выброшена;
 * - **коснулся и сразу отпустил** — это не сообщение, а промах: запись выбрасываем и подсказываем жест.
 *
 * Правило вынесено из компонента, потому что каждый порог — это решение о чужом сообщении: слишком
 * чуткая фиксация не даёт отпустить и отправить, слишком чуткая отмена выбрасывает сказанное.
 * Вся возня с указателем и захватом живёт в `MessagePane`; сюда приходит уже готовое смещение пальца.
 */

export const VOICE_HOLD = {
  /** На сколько пикселей поднять палец, чтобы запись пошла без рук. */
  lockDy: 70,
  /** На сколько пикселей увести палец влево, чтобы выбросить запись. */
  cancelDx: 110,
  /**
   * Короче — промах, а не сообщение. Совпадает с порогом, ниже которого `finishRec` и так молча
   * выбрасывает запись: иначе короткое касание не отправлялось бы, но и подсказки бы не было.
   */
  minHoldMs: 500,
} as const;

export type VoiceHoldStep =
  /** Держит — продолжаем писать. */
  | 'hold'
  /** Поднял палец достаточно высоко — запись идёт без рук. */
  | 'lock'
  /** Увёл влево — выбросить. */
  | 'cancel';

/**
 * Что значит очередное смещение пальца от точки касания. `dx < 0` — влево, `dy < 0` — вверх
 * (экранные координаты). Движение вправо и вниз не значит ничего.
 *
 * ⚠️ Если за одно событие пройдены ОБА порога (быстрый рывок по диагонали), побеждает фиксация: она
 * ничего не теряет — из неё можно выбросить корзиной, а выброшенное уже не вернуть.
 */
export function voiceHoldStep(dx: number, dy: number): VoiceHoldStep {
  if (-dy >= VOICE_HOLD.lockDy) return 'lock';
  if (-dx >= VOICE_HOLD.cancelDx) return 'cancel';
  return 'hold';
}

/** Насколько палец продвинулся к фиксации и к отмене, 0..1 — для подсказок, которые едут за пальцем. */
export function voiceHoldProgress(dx: number, dy: number): { lock: number; cancel: number } {
  const clamp = (v: number) => Math.max(0, Math.min(1, v));
  return { lock: clamp(-dy / VOICE_HOLD.lockDy), cancel: clamp(-dx / VOICE_HOLD.cancelDx) };
}

/** Палец отпущен без фиксации и отмены: отправить или это был промах. */
export function voiceHoldRelease(heldMs: number): 'send' | 'short' {
  return heldMs < VOICE_HOLD.minHoldMs ? 'short' : 'send';
}

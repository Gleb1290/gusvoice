/**
 * Намерение «зайти в канал и открыть показ этого человека» (клик по кадру в карточке наведения).
 *
 * 🔴 Почему это отдельная сущность, а не запись сразу в «открытые показы». Между кликом и моментом,
 * когда чужой трек реально появится, лежит запрос токена, подключение к комнате, ICE и подписка —
 * секунды. Положить идентификатор в `watchedStreams` заранее нельзя по трём независимым причинам,
 * и каждая убивает намерение молча:
 *
 * 1. `VoiceChannelView` на размонтировании зовёт `clearWatchedStreams`. Переход между каналами
 *    размонтирует сцену — и стирает всё, что мы положили ДО перехода.
 * 2. У открытых показов есть грейс (`watchGrace`): идентификатор, которому нет живого трека,
 *    снимается через `STREAM_VIEW_GRACE_MS`. Медленное подключение — и намерение испарится само.
 * 3. **Идентификатор заранее неизвестен.** Браузерный показ публикует сам человек (`<userId>`),
 *    нативный — спутник (`<userId>#screen`). Угадывать пришлось бы вслепую.
 *
 * Поэтому намерение хранится в терминах ЧЕЛОВЕКА (`userId`), а в идентификатор трека превращается
 * уже на месте — сопоставлением через `ownerOf`, которое разбирает оба случая одной проверкой.
 */

import { ownerOf } from './streamAudioRules';

export interface PendingWatch {
  /** Куда идём. Намерение действительно только для ЭТОГО канала. */
  channelId: string;
  /** Чей показ открываем. Именно человек, а не идентификатор трека — см. причину 3 выше. */
  userId: string;
  /** Когда намерение возникло: по нему оно и истекает. */
  at: number;
}

/**
 * Сколько ждём появления чужого показа после клика.
 *
 * Заметно больше обычного подключения: сюда укладываются токен, комната, ICE и подписка на трек,
 * а на плохой сети это растягивается. Лучше подождать лишнее, чем сказать «не вышло» тому, у кого
 * показ уже почти открылся.
 */
export const PENDING_WATCH_TIMEOUT_MS = 20_000;

/** Намерение просрочено — показа мы так и не дождались. */
export function pendingWatchExpired(p: PendingWatch, now: number, timeoutMs = PENDING_WATCH_TIMEOUT_MS): boolean {
  return now - p.at >= timeoutMs;
}

/**
 * Какой трек открыть по намерению — или `null`, если открывать пока нечего.
 *
 * ⚠️ Канал сверяется обязательно: пока `joinVoice` не довёл нас до места, живые треки принадлежат
 * ПРЕЖНЕМУ каналу, и там вполне может оказаться показ человека с тем же `userId` — например, если
 * мы уже смотрели его и решили перезайти. Открыть чужой трек «досрочно» значит показать не то.
 */
export function matchPendingWatch(
  pending: PendingWatch | null,
  currentChannelId: string | null,
  screenIdentities: readonly string[],
): string | null {
  if (!pending || currentChannelId !== pending.channelId) return null;
  return screenIdentities.find((id) => ownerOf(id) === pending.userId) ?? null;
}

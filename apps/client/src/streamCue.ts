/**
 * Звуки начала и конца показа, устойчивые к МОРГАНИЮ трека.
 *
 * 🔴 Повод — самолечение залипшего показа (#111). Когда показ залипает на четырёх кадрах, мы
 * пересоздаём публикацию у стримера. Для всех остальных это выглядит как обычные снятие и
 * публикация трека — то есть в канале играет «конец стрима», а через секунду «начало». За сеанс
 * такое может случиться до трёх раз, и звучало бы это так, будто человек дёргает показ туда-сюда.
 *
 * ⚠️ Починка НЕ в том, чтобы отличить наше лечение от настоящего рестарта: другим клиентам этого
 * знать неоткуда, и придумывать для этого протокол — лишняя сущность. Правило проще и общее:
 * **если трек вернулся почти сразу, ничего не произошло**. Заодно это чинит фантомные звуки при
 * переподключениях, где трек точно так же пропадает и возвращается.
 *
 * Цена — звук «конец стрима» отстаёт от реальности на грейс. Это не замечают: уход картинки виден
 * глазами сразу, звук лишь подтверждает.
 */

/**
 * Сколько ждать возвращения трека, прежде чем счесть показ законченным и дать звук.
 *
 * Пересоздание публикации — снятие, 400 мс паузы, публикация, две пересогласовки — укладывается
 * примерно в секунду-полторы. Три секунды дают запас и при этом не превращают «конец стрима» в
 * звук из прошлого.
 */
export const STREAM_CUE_GRACE_MS = 3_000;

/**
 * Сколько сцена голосового канала ждёт возвращения пропавшего показа, прежде чем закрыть окно
 * просмотра. Больше звукового грейса СОЗНАТЕЛЬНО: пока трека нет, смотреть всё равно нечего, а
 * вот заставить всех зрителей заново открывать показ после секундного моргания — обидно.
 */
export const STREAM_VIEW_GRACE_MS = 6_000;

export type StreamCueEvent = 'stream' | 'streamStop';

export interface StreamCueDeps {
  play: (event: StreamCueEvent) => void;
  /** Таймеры инъекцией — чтобы правило проверялось тестом без ожидания в реальном времени. */
  setTimer: (fn: () => void, ms: number) => number;
  clearTimer: (id: number) => void;
  graceMs?: number;
}

export interface StreamCue {
  /** Трек показа пропал у этого участника. */
  gone: (identity: string) => void;
  /** Трек показа появился у этого участника. */
  back: (identity: string) => void;
  /** Снять все отложенные звуки (уход из канала) — молча. */
  dispose: () => void;
}

export function createStreamCue(deps: StreamCueDeps): StreamCue {
  const grace = deps.graceMs ?? STREAM_CUE_GRACE_MS;
  // Ключ — участник: у одного человека показ ровно один, а вот разные люди начинают и заканчивают
  // независимо, и путать их таймеры нельзя.
  const pending = new Map<string, number>();

  return {
    gone(identity) {
      if (pending.has(identity)) return; // уже ждём по этому участнику — второй таймер не заводим
      pending.set(
        identity,
        deps.setTimer(() => {
          pending.delete(identity);
          deps.play('streamStop');
        }, grace),
      );
    },
    back(identity) {
      const t = pending.get(identity);
      if (t === undefined) {
        deps.play('stream'); // обычное начало показа
        return;
      }
      // Вернулся внутри грейса: показ не прерывался по смыслу — молчим ОБА раза, и за конец, и за
      // начало. Именно это делает самолечение неслышным.
      deps.clearTimer(t);
      pending.delete(identity);
    },
    dispose() {
      for (const t of pending.values()) deps.clearTimer(t);
      pending.clear();
    },
  };
}

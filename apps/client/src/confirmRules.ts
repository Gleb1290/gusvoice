/**
 * Правила окна подтверждения (#139 round 8) — чистые, без React и DOM.
 *
 * 🔴 **Повод.** 23 места звали нативный `window.confirm`, а два — `alert`. Это не только чужой вид
 * (серая коробка браузера с адресом страницы в заголовке, в десктопной оболочке похожая на
 * системную ошибку), но и настоящая поломка: нативный диалог замораживает вкладку целиком, и
 * приложение перестаёт отвечать, пока его не закроют.
 *
 * ⚠️ Вид здесь НЕ решается: окно собрано на существующей `.modal`, а его облик придёт макетом
 * round 8. Здесь — поведение, которое от облика не зависит и от него не изменится.
 */

/**
 * Насколько тяжёлое действие подтверждаем.
 *
 * `danger` — то, что нельзя отменить (удаление, кик, бан); `info` — просто «прочитал» (бывший
 * `alert`, одна кнопка).
 */
export type ConfirmTone = 'neutral' | 'danger' | 'info';

export interface ConfirmSpec {
  title: string;
  /** Что именно произойдёт и чего НЕ произойдёт: почти у каждого нашего текста есть такая половина. */
  body?: string;
  /** Список внутри окна — например, имена серверов, с которых человек выходит разом. */
  items?: string[];
  tone?: ConfirmTone;
  /** Подпись действия: всегда глагол («Удалить», «Покинуть»), никогда «ОК». */
  confirmLabel?: string;
  cancelLabel?: string;
  /**
   * Слово, которое надо набрать, чтобы кнопка ожила, — для необратимого (имя сервера).
   * ⚠️ Не «защита от дурака», а пауза: удаление сервера со всей перепиской стоит одного лишнего
   * движения.
   */
  requireText?: string;
  /**
   * Галочка под текстом — второе решение в том же вопросе (#212: «Также удалить для …» при удалении в ЛС).
   * Ответ читает `confirmWithOption`; `confirmAction` её просто показывает.
   */
  option?: { label: string; checked: boolean };
}

/** Подпись кнопки подтверждения по умолчанию: у «прочитал» она другая по смыслу. */
export function confirmLabelOf(spec: ConfirmSpec): string {
  if (spec.confirmLabel) return spec.confirmLabel;
  return spec.tone === 'info' ? 'Понятно' : 'Подтвердить';
}

/** Показывать ли кнопку отмены: у «прочитал» отменять нечего. */
export function hasCancel(spec: ConfirmSpec): boolean {
  return spec.tone !== 'info';
}

/**
 * Можно ли подтвердить прямо сейчас.
 *
 * ⚠️ Сравнение с набранным — по обрезанным краям и без учёта регистра: человек списывает имя
 * глазами, и «  Гуси бабуси» от «Гуси бабуси» отличается только нашей придирчивостью.
 */
export function canConfirm(spec: ConfirmSpec, typed: string): boolean {
  if (!spec.requireText) return true;
  return typed.trim().toLowerCase() === spec.requireText.trim().toLowerCase();
}

/**
 * Подтверждает ли Enter.
 *
 * 🔴 Для опасного — НЕТ. Enter прилетает из привычки (только что человек жал его в поле ввода), и
 * «удалить сервер» не должно случаться от клавиши, нажатой по инерции. Там же, где надо набрать
 * имя, Enter в поле — естественное завершение, поэтому разрешаем, когда слово уже совпало.
 */
export function submitsOnEnter(spec: ConfirmSpec, typed: string): boolean {
  if (spec.requireText) return canConfirm(spec, typed);
  return spec.tone !== 'danger';
}

/**
 * Что написать в подсказке про Enter внизу окна.
 *
 * ⚠️ Подсказка НЕ украшение: у опасного окна Enter намеренно не работает, и человек, привыкший
 * заканчивать им диалоги, должен увидеть почему, а не решить, что окно сломалось.
 */
export function enterHintOf(spec: ConfirmSpec, typed = ''): string {
  if (spec.requireText) return canConfirm(spec, typed) ? 'подтвердить' : 'сначала наберите имя';
  return spec.tone === 'danger' ? 'здесь не подтверждает' : 'подтвердить';
}

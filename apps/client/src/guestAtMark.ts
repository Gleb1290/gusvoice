import type { AdminUser } from '@gusvoice/shared';

type GuestAt = NonNullable<AdminUser['guestAt']>[number];

/**
 * Отметка «скрыт от соседей, но виден» (#139, F4, план §5.2.1, требование 14).
 *
 * 🔴 Зачем она вообще. Скрытие убирает человека из КАТАЛОГА, но войти по ссылке он вправе — и там
 * он обычный участник, которого видят все. Админ, который скрывал, без этой отметки считает, что у
 * соседей человека нет вовсе, и решает по неверной картине: например, разрывает связку «на всякий
 * случай» или, наоборот, не разрывает, думая, что и так не видно.
 *
 * ⚠️ Текст строится ЗДЕСЬ, а не в разметке: тех же слов ждёт подсказка (`title`) — а два места с
 * одной формулировкой однажды разъезжаются.
 */
export function guestAtLine(g: GuestAt): string {
  const when = new Date(g.at).toLocaleDateString('ru-RU', { day: 'numeric', month: 'short' });
  const how = g.method === 'invite' ? 'вошёл по ссылке' : 'вошёл';
  // Пригласившего называем ИМЕНЕМ из кеша каталога; не нашлось — молчим. Показать сырой
  // идентификатор хоста значило бы занять строку тем, что человеку ничего не говорит.
  const who = g.invitedByName ? `, ссылку создал: ${g.invitedByName}` : '';
  return `«${g.instance}» → сервер «${g.serverName}» — ${how} ${when}${who}`;
}

/** Все строки одной отметки. Пусто — человек нигде не гость, отметку показывать не надо. */
export function guestAtLines(list: GuestAt[] | undefined): string[] {
  return (list ?? []).map(guestAtLine);
}

/**
 * Короткая подпись рядом с переключателем.
 *
 * ⚠️ Число мест в подписи намеренно: одно место и пять мест — разные поводы для разговора, а
 * раскрывать весь список прямо в таблице негде.
 */
export function guestAtSummary(list: GuestAt[] | undefined): string | null {
  const n = list?.length ?? 0;
  if (n === 0) return null;
  // Предложный падеж: «на 1 сервере», «на 2 серверах», «на 21 сервере» — форма зависит от
  // последней цифры, кроме подростковых чисел (11, 111).
  const one = n % 10 === 1 && n % 100 !== 11;
  return `скрыт, но виден на ${n} ${one ? 'сервере' : 'серверах'}`;
}

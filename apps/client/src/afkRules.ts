/**
 * Правила авто-«отошёл» — чистые, БЕЗ импорта стора и api.
 *
 * Отдельным файлом по той же причине, что и разбор `<head>` на бэкенде: `afk.ts` на импорте тянет
 * стор и сеть, а те трогают `window` — тест такого модуля не запускается вовсе («window is not
 * defined»). Логика переходов, в которой и была ошибка, живёт здесь и проверяется напрямую.
 */

/** Сколько простоя до «отошёл». */
export const IDLE_MS = 10 * 60 * 1000;

/**
 * Пора ли уводить в «отошёл».
 * Не трогаем статус, который человек поставил сам: «не беспокоить» и «невидимка» — это заявление,
 * молча перетереть его через десять минут хуже, чем не иметь авто-«отошёл» вовсе.
 */
export function shouldGoAway(p: {
  now: number;
  lastActive: number;
  status?: string;
  autoAway: boolean;
}): boolean {
  if (p.autoAway) return false; // уже увели, второй раз не надо
  if (p.status !== 'online') return false;
  return p.now - p.lastActive >= IDLE_MS;
}

/**
 * Пора ли возвращать в «в сети». Только если в «отошёл» увели МЫ — иначе возврат затирал бы
 * «отошёл», выставленный руками.
 *
 * ⚠️ Это про СЛАБЫЕ признаки жизни: мышь, клавиши, возврат в окно. Человек мог поставить «отошёл»
 * и продолжать возить мышью, читая чат, — снимать заявление на этом основании нельзя.
 */
export function shouldReturnOnline(p: { status?: string; autoAway: boolean }): boolean {
  return p.autoAway && p.status === 'away';
}

/**
 * Отменяет ли «отошёл» голосовое действие — включение микрофона или речь (решение 04.09).
 *
 * 🔴 **ОТМЕНЕНО 20.10 (решение владельца: «как Discord»): клиент (`afk.ts`) больше НЕ вызывает эту функцию — речь и
 * микрофон активностью не считаются.** Оставлена только потому, что на неё ссылается `afk.test.ts` (Codex, 04.09).
 *
 * 🔴 **Тут ручной статус снимается тоже, и это осознанное исключение из правила выше.** «Отошёл»
 * означает «меня нет»; человек, который включил микрофон и заговорил, этим же и опроверг своё
 * заявление — держать после этого «отошёл» значит показывать остальным заведомую неправду. Заодно
 * лечится любое застревание: что бы ни записалось в статус, первое же слово в канале его снимает.
 *
 * ⚠️ Только `away`. «Не беспокоить» и «невидимка» — не про присутствие, а про то, как с человеком
 * обращаться: он вполне может говорить и при этом не хотеть уведомлений или показа в списке.
 */
export function shouldReturnOnVoice(status?: string): boolean {
  return status === 'away';
}

/**
 * Момент последней активности с учётом простоя уровня ОС (десктоп, `gv_os_idle_ms`).
 *
 * Берём БОЛЕЕ СВЕЖИЙ из двух источников, потому что ни один не полон:
 *  * ОС знает про ввод вне нашего окна — мышь и клавиатуру в полноэкранной игре, где DOM-событий
 *    до нас не доходит вовсе;
 *  * веб знает про возврат фокуса/видимость окна и ввод, который ОС не засчитала (тач, эмуляторы).
 *    (Речь и микрофон с 20.10 не считаются — решение владельца «как Discord».)
 * Отсюда `Math.max` по времени (= минимум по простою): достаточно одного признака жизни.
 *
 * `osIdleMs === null` — не десктоп либо API недоступен: тогда поведение ровно прежнее, по DOM.
 */
export function effectiveLastActive(p: {
  webLastActive: number;
  osIdleMs: number | null;
  now: number;
}): number {
  if (p.osIdleMs == null) return p.webLastActive;
  return Math.max(p.webLastActive, p.now - p.osIdleMs);
}

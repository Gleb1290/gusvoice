/**
 * Где оставить РОДНОЕ меню браузера, а где погасить (#75).
 *
 * Приложение не должно предлагать «Печать» и «Сохранить как» по правому клику — в десктопе это
 * читается как «я всё ещё в браузере». Но глушить всё подряд нельзя: в поле ввода правый клик даёт
 * «Вставить», и без него в десктопе вставить текст мышью станет НЕЧЕМ. Ровно этим ломаются
 * приложения, где `contextmenu` погасили одной строкой.
 *
 * Модуль чистый — принимает уже вычисленные признаки, не лезет в document сам, поэтому проверяется
 * тестом.
 */

/** Признаки цели правого клика — их собирает вызывающий из события. */
export interface ClickTarget {
  /** Поле ввода или элемент с `contenteditable`. */
  editable: boolean;
  /** Есть ли непустое выделение текста на странице. */
  hasSelection: boolean;
  /** Цель внутри ссылки (`<a href>`) — своей или чужой. */
  inLink: boolean;
  /**
   * Цель — сохраняемое медиа-СОДЕРЖИМОЕ (картинка в сообщении, кадр в просмотрщике), а НЕ картинка
   * интерфейса.
   *
   * 🔴 Признак ставит вызывающий по маркеру `data-ctxsave` на самом элементе, а НЕ по тегу `img`.
   * Аватар, иконка сервера и кастомное эмодзи — тоже `<img>`, и «Сохранить изображение» на аватаре
   * это ровно тот браузерный мусор («Отправить вкладку на устройство», «Проверить»), из-за которого
   * всё и затевалось. «Сохранить» осмысленно только над тем, что человек в чат ПОЛОЖИЛ, а не над
   * тем, что приложение нарисовало.
   */
  savableMedia: boolean;
}

/**
 * `true` — не мешаем браузеру, показываем его меню.
 *
 * Четыре исключения, каждое закрывает конкретную потерю:
 *  • поле ввода → «Вставить» (иначе мышью в десктопе не вставить);
 *  • выделенный текст → «Копировать»;
 *  • ссылка → «Копировать адрес ссылки»;
 *  • медиа-контент чата → «Сохранить изображение».
 */
export function keepNativeMenu(t: ClickTarget): boolean {
  if (t.editable) return true;
  if (t.hasSelection) return true;
  if (t.inLink) return true;
  return t.savableMedia;
}

/**
 * Типы `<input>`, куда РЕАЛЬНО печатают. Остальные — ползунок громкости, флажок, переключатель,
 * кнопка — на вид элементы управления, а не поля: «Вставить» в них бессмысленно, зато родное меню
 * с «Печать» и «Отправить вкладку на устройство» вылезало прямо на ползунке громкости стрима
 * (найдено тестером). `''` — это `<input>` без атрибута `type`, по умолчанию текстовый.
 */
const TEXT_INPUT_TYPES = new Set(['', 'text', 'search', 'url', 'tel', 'email', 'password', 'number']);

/**
 * Поле ввода ли это. Для `<input>` решает ТИП, а не тег: `type="range"` — это ползунок, и родное
 * меню на нём — тот же браузерный мусор, ради которого всё затевалось.
 */
export function isEditableTag(tag: string, inputType = ''): boolean {
  const t = tag.toLowerCase();
  if (t === 'textarea') return true;
  if (t === 'input') return TEXT_INPUT_TYPES.has(inputType.toLowerCase());
  return false;
}

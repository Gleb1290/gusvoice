/**
 * Удержание всплывающей карточки, пока мышка идёт со строки НА НЕЁ.
 *
 * 🔴 Повод. Карточка превью показа (#115) была объявлена `pointer-events: none`, и это было
 * осознанно: иначе она перехватывала наведение сама у себя. Мышка «уходила со строки» на карточку,
 * строка получала `mouseleave`, карточка исчезала, мышка снова оказывалась над строкой — и превью
 * моргало. Пока внутри карточки не на что было нажимать, отказ от событий мыши был честной ценой.
 * Как только по кадру надо КЛИКНУТЬ, платить эту цену больше нельзя.
 *
 * Замена — отсрочка закрытия: строка отпускает карточку не мгновенно, и мышка успевает пройти
 * зазор между ними. Мостик-перехватчик не нужен: карточка стоит СБОКУ от строки с зазором в 10 px,
 * то есть по дороге курсор не пересекает соседние строки — ему просто нужна пауза.
 *
 * ⚠️ Отсрочка держит ТОЛЬКО закрытие. Переход на другого человека закрывает карточку немедленно
 * (`closeNow`): там мышка уже на новой цели, и пауза показывала бы чужой профиль поверх неё.
 */

export interface HoverHoldDeps {
  /** Что значит «закрыть». Вызывается и по отсрочке, и немедленно. */
  close: () => void;
  setTimer: (fn: () => void, ms: number) => number;
  clearTimer: (id: number) => void;
  /** Сколько ждать возвращения курсора, прежде чем закрыть. */
  graceMs: number;
}

export interface HoverHold {
  /** Курсор на строке ИЛИ на карточке — отменить отложенное закрытие. */
  hold(): void;
  /** Курсор ушёл — закрыть, но не сейчас. */
  release(): void;
  /** Закрыть прямо сейчас: перевели на соседа, кликнули, размонтировали. */
  closeNow(): void;
  /** Снять отложенное, ничего не закрывая: дерево уходит, `close` звать уже некуда. */
  dispose(): void;
}

export function createHoverHold(deps: HoverHoldDeps): HoverHold {
  let timer: number | null = null;

  const stop = (): void => {
    if (timer !== null) {
      deps.clearTimer(timer);
      timer = null;
    }
  };

  return {
    hold: stop,
    release() {
      // Повторный `release` без `hold` между ними не должен копить таймеры: гасим прежний.
      stop();
      timer = deps.setTimer(() => {
        timer = null;
        deps.close();
      }, deps.graceMs);
    },
    closeNow() {
      stop();
      deps.close();
    },
    dispose: stop,
  };
}

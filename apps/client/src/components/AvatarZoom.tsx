import type { ReactNode } from 'react';
import { viewImage } from '../imageViewer';

/**
 * Оборачивает аватар в карточке профиля: по клику открывает картинку целиком.
 *
 * Аватар везде обрезан в круг, а в профиль приходят посмотреть на человека — значит должен быть
 * способ увидеть картинку как она есть. Аватара нет (буква или силуэт) — обёртки нет вовсе: кнопка,
 * которая ничего не открывает, врёт курсором ещё до нажатия.
 *
 * ⚠️ Какую ссылку сюда передать, решает вызывающий, и решение везде одно: движущийся аватар, если
 * анимация у ЗРИТЕЛЯ включена, иначе обычный. Выключивший анимацию не должен получить её через
 * просмотрщик — выключатель бережёт трафик, а не только глаза.
 */
export function AvatarZoom({ url, name, children }: { url: string | null; name: string; children: ReactNode }) {
  if (!url) return <>{children}</>;
  return (
    <button
      type="button"
      className="ava-zoom"
      title="Открыть аватар"
      aria-label={`Открыть аватар: ${name}`}
      onClick={() => viewImage({ url, name, sub: 'Аватар' })}
    >
      {children}
    </button>
  );
}

import { Icon } from './Icon';
import { useStore } from '../store';

/**
 * Регалии победителя сезона: корона над аватаркой и свечение ника (этап 4, решено).
 *
 * 🔴 **Одним модулем, а не условием в каждом компоненте.** Человек рисуется на пяти-шести
 * поверхностях (список голосового канала, плитка сцены, участники сервера, автор в чате). Размажь
 * проверку по ним — и она разойдётся: где-то корона появится, где-то нет, а свечение будет считаться
 * от другого цвета. Здесь одна точка правды и один способ спросить.
 *
 * ⚠️ Корона НЕ покупается. Она выдаётся автоматически победителю прошлого сезона и висит ровно один
 * сезон (так решено). Продавать её нельзя по тому же принципу, что и права: награда, которую
 * можно купить, перестаёт быть наградой.
 */

/**
 * Носит ли этот человек корону на этом сервере.
 *
 * ⚠️ Читает общий снимок экономики из стора — своего запроса не делает. Экономика выключена или
 * снимок не приехал — короны просто нет, и это правильное поведение: украшение не должно ни ходить
 * на сервер само, ни задерживать отрисовку человека.
 */
export function useIsCrowned(userId: string | undefined, serverId: string | undefined): boolean {
  const crownId = useCrownId(serverId);
  return !!userId && !!crownId && crownId === userId;
}

/**
 * Кто носит корону на этом сервере.
 *
 * ⚠️ Отдельно от `useIsCrowned`, потому что хук нельзя звать внутри `map`: там, где люди рисуются
 * списком, идентификатор надо получить ОДИН раз на компонент и дальше сравнивать обычным `===`.
 */
export function useCrownId(serverId: string | undefined): string | undefined {
  return useStore((s) => (serverId ? s.economy[serverId]?.crown?.userId : undefined));
}

/**
 * Корона над аватаркой.
 *
 * ⚠️ Ставится в контейнер с `position: relative` — сама позиционируется абсолютно, чтобы не
 * раздвигать раскладку. Значок, меняющий размер строки, дёргал бы весь список при каждом закрытии
 * сезона.
 * ⚠️ `aria-hidden` намеренно: рядом всегда есть имя, и подпись «корона» в озвучке — шум. Смысл
 * несёт `title` для мыши.
 *
 * 🔴 Значок из НАШЕГО набора, а не эмодзи. Эмодзи рисуется по-разному в Windows, Android и
 * браузере, не красится темой и стоит чужеродно рядом с остальными иконками — а корона висит
 * ровно там же, где `mic` и `headphones`.
 */
export function CrownMark({ size = 14 }: { size?: number }) {
  return (
    <span className="crown-mark" title="Победитель прошлого сезона" aria-hidden>
      <Icon name="crown" size={size} />
    </span>
  );
}

/**
 * Класс свечения для ника.
 *
 * 🔴 **Свечение считается ОТ цвета ника, а не задано фиксированным оттенком.** Ник уже может быть
 * покрашен ролью — от жёлтого до тёмно-синего, — и одно и то же свечение поверх них читается
 * по-разному: где-то нимб, где-то грязь. В CSS это сделано через `currentColor`, поэтому свечение
 * всегда родственно самому нику, какой бы цвет ему ни дала роль.
 *
 * ⚠️ Анимация медленная и уважает `prefers-reduced-motion`: мигающий ник в списке, который человек
 * видит весь вечер, надоедает за час и мешает читать остальные.
 */
export function crownGlow(crowned: boolean): string {
  return crowned ? ' crowned-name' : '';
}

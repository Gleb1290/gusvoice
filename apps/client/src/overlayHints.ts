/**
 * Подсказки «кто кого типнул» В ОВЕРЛЕЕ поверх игры (запрос 04.09).
 *
 * 🔴 **Подсказка ложится ПОВЕРХ ника, а не рядом с ним.** Оверлей — окно фиксированного размера,
 * которое само ужимается под содержимое (`gv_overlay_set_size`), и любая добавленная строка или
 * колонка раздувает прозрачный прямоугольник поверх игры, а потом ещё и пере-якорит его к углу.
 * Поэтому подсказка не занимает места вовсе: она рисуется абсолютом на месте ника и на три секунды
 * его заменяет. Ник читается и без хвоста, а «кто заплатил» видно ровно тогда, когда это случилось.
 *
 * 🔴 **Одна подсказка на человека, самая свежая** — в отличие от сайдбара, где их стопка. Причина
 * та же: в строке оверлея ровно одна линия, стопка полезла бы вверх за край окна и обрезалась бы.
 * Полная летопись жеста и так есть в канале и в кошельке; оверлей — поверхность одного взгляда.
 *
 * 🔴 **Получателя задаёт СТРОКА, поэтому в тексте только отправитель и сумма** — то же правило, что
 * в сайдбаре (`tipHints.ts`). Писать обоих пришлось бы только там, где строки нет вовсе: над стримом
 * (`StreamTipFeed`).
 *
 * ⚠️ Живёт на ТЕХ ЖЕ данных (`store.tipHints`) и с тем же временем жизни `TIP_HINT_MS` — второй
 * список означал бы вторую правду об одном событии.
 */

/** Готовая к отрисовке подсказка: имя отправителя УЖЕ разрешено в ник этого сервера. */
export interface OverlayHint {
  /** Идентификатор исходной подсказки — по нему React держит узел, и анимация не перезапускается
   *  на каждом повторном пуше состояния в окно оверлея. */
  id: string;
  toUserId: string;
  from: string;
  amount: number;
}

/**
 * Оставить по ОДНОЙ (самой свежей) подсказке на человека и только тем, кто в оверлее вообще есть.
 *
 * ⚠️ Отсутствующих отбрасываем не для экономии: подсказке негде появиться — её место задаёт строка
 * получателя. Тип из соседнего канала иначе доехал бы в окно и молча никуда не лёг.
 */
export function overlayHints<T extends { id: string; toUserId: string; amount: number; atMs: number }>(
  list: readonly T[],
  present: ReadonlySet<string>,
  nameOf: (hint: T) => string,
): OverlayHint[] {
  const newest = new Map<string, T>();
  for (const h of list) {
    if (!present.has(h.toUserId)) continue;
    const cur = newest.get(h.toUserId);
    if (!cur || h.atMs >= cur.atMs) newest.set(h.toUserId, h);
  }
  return [...newest.values()].map((h) => ({
    id: h.id,
    toUserId: h.toUserId,
    from: nameOf(h),
    amount: h.amount,
  }));
}

/**
 * Кого показывать в оверлее. В списке — всех; в компактном виде — говорящих **и** тех, кому только
 * что типнули.
 *
 * 🔴 Получатель добавляется временно и осознанно: в компактном виде ников нет, подсказке не на что
 * лечь, а молчащий получатель в списке вообще отсутствует — без этого жест на его счёт исчез бы
 * бесследно. Окно при этом меняет размер ровно так же, как оно меняет его каждый раз, когда кто-то
 * начал или перестал говорить, — это уже штатное поведение компактного вида, а не новое.
 */
export function overlayRows<P extends { id: string; speaking: boolean }>(
  participants: readonly P[],
  compact: boolean,
  hints: readonly OverlayHint[],
): P[] {
  if (!compact) return [...participants];
  const hinted = new Set(hints.map((h) => h.toUserId));
  return participants.filter((p) => p.speaking || hinted.has(p.id));
}

/**
 * Системные уведомления про монеты — «кто кого типнул» и «кто кого ущипнул» (запрос 04.09).
 *
 * 🔴 **Своя настройка, отдельная от уведомлений о сообщениях.** Человек может не хотеть всплывашек
 * про болтовню и хотеть про монеты — и наоборот. Смешать их в один тумблер значит заставить
 * выбирать между тем, что не связано.
 *
 * 🔴 **Два положения «мне» и «все в канале» — потому что событие приходит ВСЕМУ каналу.** Адресное
 * («тебя типнули») редкое: у типа кулдаун 10 секунд, щипок стоит полтора дня сидения. Чужое — это
 * лента, и в живой вечер семерых она пойдёт очередью, поэтому пропускается не чаще раза в 20 секунд.
 * ⚠️ Троттл НЕ применяется к адресному: пропустить «тебя ущипнули» из-за того, что минуту назад
 * кто-то типнул соседа, — ровно та потеря, ради которой уведомление и заводили.
 *
 * ⚠️ В фокусе не уведомляем никогда: подсказка у ника, перья и кошелёк уже всё показали. И «не
 * беспокоить» уважаем — это статус, а не украшение.
 */

export type CoinNotifyLevel = 'off' | 'mine' | 'all';

/** Не чаще одной всплывашки про ЧУЖИЕ монеты за это время. Столько же, сколько у сообщений. */
export const COIN_NOTIFY_THROTTLE_MS = 20_000;

export interface CoinNotifyInput {
  level: CoinNotifyLevel;
  /** Событие адресовано мне: типнули/щипнули именно меня. */
  mine: boolean;
  /** Статус «не беспокоить». */
  dnd: boolean;
  /** Окно в фокусе — человек и так смотрит. */
  focused: boolean;
  /** Когда показывали прошлую всплывашку про ЧУЖОЕ (0 — ещё ни разу). */
  lastOtherAt: number;
  now: number;
}

export function shouldNotifyCoin(i: CoinNotifyInput): boolean {
  if (i.level === 'off') return false;
  if (i.focused) return false;
  if (i.dnd) return false;
  if (i.mine) return true;
  if (i.level !== 'all') return false;
  return i.now - i.lastOtherAt >= COIN_NOTIFY_THROTTLE_MS;
}

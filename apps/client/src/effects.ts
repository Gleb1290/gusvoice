/**
 * Правила показа эффектов экономики — чистые, БЕЗ React и DOM (#120).
 *
 * 🔴 Класс бага, ради которого этот модуль существует: **эффект, у которого нет цели**. Монета
 * летит «в чип баланса», а чипа на экране нет — окно узкое, открыты ЛС, человек смотрит другой
 * сервер, поверх лежит модалка. Полёт уходит в угол или в никуда. Такое не ловится ни типами, ни
 * тестами и вылезает у одного человека из семнадцати — того, кто держит окно не как все.
 *
 * Поэтому решение «что именно показать» принимается ЗДЕСЬ, по обстановке, и проверяется тестом, а
 * не размазано по компонентам.
 */

/** Точка на экране в пикселях окна. */
export interface Point {
  x: number;
  y: number;
}

export interface EffectConditions {
  /** Вкладка скрыта: `requestAnimationFrame` в фоне не идёт вовсе (Chrome 57+). */
  tabHidden: boolean;
  /** Открыт полноэкранный показ или видео — не лезем поверх. */
  fullscreen: boolean;
  /** Событие относится к серверу, который человек сейчас смотрит. */
  sameServer: boolean;
  /** Человек просил не двигать интерфейс. */
  reducedMotion: boolean;
  /** Куда лететь: живой чип баланса на экране. `null` — его нет или он за краем окна. */
  target: Point | null;
}

export type EffectPlan =
  /**
   * Показывать нельзя.
   * ⚠️ `hidden` и `fullscreen` слой ОТКЛАДЫВАЕТ и показывает, когда станет можно (решение
   * 03.09: услышал звук — альт-табнулся — увидел). `other-server` выбрасывается: вспышка про чужой
   * сервер без контекста читается как сбой. Срок ожидания и потолок — `pendingEffects`.
   */
  | { kind: 'skip'; reason: 'hidden' | 'fullscreen' | 'other-server' }
  /** Смена состояния без движения: число обновится, эффекта не будет. */
  | { kind: 'static' }
  /** Цели нет — показываем на месте события, а не летим по угаданным координатам. */
  | { kind: 'inplace' }
  /** Полный вид: летим в цель. */
  | { kind: 'fly'; to: Point };

/**
 * Что показать при таких условиях.
 *
 * ⚠️ Порядок проверок — часть правила. Сначала отказы (показывать негде и незачем), потом
 * доступность, и только потом выбор между полётом и запасным видом. Переставь `reducedMotion`
 * выше отказов — и человек с выключенной анимацией начнёт «показывать» эффекты в скрытой вкладке.
 *
 * 🔴 `other-server` — именно отказ, а не запасной вид: человек смотрит другой сервер, и вспышка без
 * понятного контекста читается как сбой, а не как награда.
 */
export function planEffect(c: EffectConditions): EffectPlan {
  if (c.tabHidden) return { kind: 'skip', reason: 'hidden' };
  if (c.fullscreen) return { kind: 'skip', reason: 'fullscreen' };
  if (!c.sameServer) return { kind: 'skip', reason: 'other-server' };
  if (c.reducedMotion) return { kind: 'static' };
  if (!c.target) return { kind: 'inplace' };
  return { kind: 'fly', to: c.target };
}

/**
 * Где цель, если она вообще на экране.
 *
 * ⚠️ Вопрос не «есть ли узел в DOM», а «попадает ли он в окно»: свёрнутый сайдбар оставляет чип в
 * дереве, но за краем экрана, и полёт туда уходит за границу.
 * ⚠️ Нулевые размеры (`display: none`, ещё не смонтирован) тоже считаем отсутствием цели.
 */
export function targetPoint(
  rect: { left: number; top: number; width: number; height: number } | null,
  viewport: { width: number; height: number },
): Point | null {
  if (!rect || rect.width <= 0 || rect.height <= 0) return null;
  const x = rect.left + rect.width / 2;
  const y = rect.top + rect.height / 2;
  if (x < 0 || y < 0 || x > viewport.width || y > viewport.height) return null;
  return { x, y };
}

/**
 * Сколько длится эффект, миллисекунды.
 *
 * 🔴 Числа не с потолка. Повторяемое действие не должно быть длиннее **500 мс** — дальше оно
 * начинает ощущаться задержкой, а не откликом. Тип человек видит десятки раз за вечер, поэтому он
 * в этом пределе. Перья — редкое событие (МЕГА пок), им можно больше, но и там нужен потолок:
 * бесконечный эффект читается как зависание. Обоснование и источники — `docs/animation-playbook.md`.
 */
export const EFFECT_MS = {
  /**
   * Подсказка о монетах (тип и надбавка гуся): самый частый эффект, поэтому самый короткий.
   *
   * ⚠️ Рядом жила `coin: 420` — длительность ПОЛЁТА монеты. Полёт удалён целиком 02.09 (так
   * решено), разбор и вся его реализация — в `docs/animation-playbook.md`, раздел про удалённое.
   */
  tip: 320,
  /**
   * Осыпание перьев: редкое и праздничное, потолок мягче.
   *
   * ⚠️ 2600 → 4200 → **6500**, оба раза по живой проверке. Сначала перья не успевали пролететь окно,
   * потом эффект оказался слишком коротким для своей цены — а он покупается за монеты, и жест
   * обязан ощущаться дороже обычного тыка. Правило «не длиннее 500 мс» здесь не действует: оно про
   * ЧАСТЫЕ действия. Потолок всё равно нужен — бесконечный эффект читается как зависание.
   */
  feathers: 6500,
} as const;

/**
 * Сколько частиц выпускаем.
 *
 * 🔴 Замеры: 2D-канва держит 60 кадров на 200–300 частицах, а на 1000–1500 падает до 22. Мы целимся
 * заведомо ниже границы, потому что эффект срабатывает у человека, который в этот момент играет или
 * смотрит чужой показ — то есть когда запас производительности минимальный.
 */
export const FEATHER_COUNT = 150;

/**
 * Сколько площади окна приходится на одно перо.
 *
 * 🔴 **Число подобрано расчётом под требование: «должен быть момент, когда перья занимают
 * всё пространство, на любом экране».** Симуляция даёт при этом значении пик покрытия ~58 % и
 * удержание выше 50 % больше двух секунд — ОДИНАКОВО на 1366×768, 1920×1080 и 3440×1440. Это
 * габаритное покрытие; сами кадры наполовину прозрачные, поэтому «чернил» примерно вдвое меньше, и
 * читается это как плотный снегопад, а не как глухая стена.
 *
 * ⚠️ Предыдущая версия считала от эталонного экрана с потолком 300 и давала 30 % на ноутбуке против
 * **13.6 %** на широком мониторе — то есть потолок бил ровно по большому экрану, где перьев и так
 * не хватало. Отсюда «перьев маловато» на живой проверке.
 */
export const FEATHER_AREA_PER = 7000;

/**
 * Потолок числа частиц.
 *
 * ⚠️ Поднят с 300: старое значение было осторожным прочтением общего замера «200–300 частиц = 60
 * кадров», и именно оно не давало набрать плотность на широком мониторе. Ниже потолка держит
 * САМ ЭФФЕКТ: слой мерит время кадра и прореживает частицы, если машина не тянет (см. `FeatherLayer`).
 * Целиться в картинку и отступать по факту честнее, чем занижать заранее для всех.
 */
export const FEATHER_COUNT_MAX = 900;

export function featherCount(width: number, height: number): number {
  const wanted = Math.round((width * height) / FEATHER_AREA_PER);
  return Math.max(FEATHER_COUNT, Math.min(FEATHER_COUNT_MAX, wanted));
}

/**
 * Очередь ОТЛОЖЕННЫХ эффектов: положить новый, выкинув протухшее и лишнее.
 *
 * 🔴 Правило вынесено из слоя, потому что ошибается оно молча. Забудь срок — и человек, вернувшийся
 * через час, получит залп перьев за весь вечер; забудь потолок — и очередь запрёт его под осыпанием
 * на минуту. Ни то, ни другое не видно в типах и не падает в тестах компонента.
 *
 * `front` — вернуть в НАЧАЛО то, что играло, когда показывать стало негде: оно прилетело раньше
 * тех, что встали за ним, и порядок «кто когда щипнул» переврать нельзя.
 */
export function pendingEffects<T extends { at: number }>(
  list: T[],
  item: T,
  opts: { now: number; maxAgeMs: number; max: number; front?: boolean },
): T[] {
  const fresh = list.filter((q) => opts.now - q.at < opts.maxAgeMs);
  const next = opts.front ? [item, ...fresh] : [...fresh, item];
  return next.slice(0, opts.max);
}

/** Убрать протухшее перед показом: ждало слишком долго — уже не «только что прилетело». */
export function freshEffects<T extends { at: number }>(list: T[], now: number, maxAgeMs: number): T[] {
  return list.filter((q) => now - q.at < maxAgeMs);
}

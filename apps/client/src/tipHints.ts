/**
 * Всплывающие подсказки «кто кого типнул» в списке голосового канала (#117, решение 02.09).
 *
 * 🔴 **Подсказка висит на строке ПОЛУЧАТЕЛЯ и называет отправителя.** Кто кому — самое ценное в
 * этом жесте: звук слышит весь канал, но без подписи он говорит только «кому-то что-то перепало».
 * Получателя задаёт место, отправителя — текст; писать обоих в узкую строку сайдбара некуда.
 *
 * 🔴 **Стопка, а не очередь.** Несколько типов подряд одному человеку показываются ОДНОВРЕМЕННО,
 * друг над другом, и гаснут независимо. Очередь растянула бы серию из пяти типов на десять секунд,
 * то есть подсказка приходила бы уже после того, как всё кончилось.
 *
 * ⚠️ Правила здесь чистые и без таймеров: время приходит аргументом. Сама уборка — у вызывающего.
 */

/**
 * Сколько живёт одна подсказка. 🔴 **Обязана совпадать с длительностью анимации в CSS**
 * (`tip-hint-rise` и `tip-hint-fade` в `styles.css`): разъедутся — подсказка либо мигнёт и
 * останется висеть невидимой, либо исчезнет на полуслове.
 * ⚠️ 2200 → 3200 (03.09) → **5000** (04.09) по запросу: «пусть держится чуть больше», а после
 * вечера на живых людях — ровно пять секунд. Добавленное время каждый раз уходит ЦЕЛИКОМ в
 * удержание: проценты ключевых кадров пересчитываются так, чтобы проявление (≈320 мс) и угасание
 * (≈670 мс) оставались прежними по АБСОЛЮТНОМУ времени. Просто растянуть анимацию — значит сделать
 * и всплытие, и растворение вялыми.
 * ⚠️ Константа общая для трёх поверхностей: строка сайдбара, плашка над стримом и подсказка в
 * игровом оверлее. Меняя её, править ВСЕ соответствующие анимации в `styles.css`.
 */
export const TIP_HINT_MS = 5000;

/**
 * Сколько подсказок одному человеку показываем одновременно.
 *
 * ⚠️ Потолок нужен не ради памяти, а ради глаз: без него серия быстрых типов заваливает строку
 * башней подписей выше самого сайдбара. Три — столько, сколько читается одним взглядом.
 */
export const TIP_HINT_STACK = 3;

export interface TipHint {
  /** Свой у каждой подсказки: по нему её и убирают, а не по «последней». */
  id: string;
  toUserId: string;
  /**
   * 🔴 Держим ИДЕНТИФИКАТОР отправителя, а имя разрешаем при отрисовке (`useNameResolver`).
   * Событие приносит обычное имя из `users`, а показать надо ник НА ЭТОМ СЕРВЕРЕ — ник живёт в
   * паре «человек↔сервер» и приходит ростером (правка 03.09; та же причина, что в #73).
   */
  fromUserId: string;
  /** Запасное имя из события: на случай, если ростера ещё нет или человек в нём не найден. */
  fromName: string;
  amount: number;
  atMs: number;
}

/**
 * Добавить подсказку, вытеснив самую старую в стопке ЭТОГО человека.
 *
 * ⚠️ Вытесняем по получателю, а не по всему списку: иначе один активный канал стирал бы подсказки
 * в другом, и человек не увидел бы адресованного ему.
 */
export function addTipHint(list: TipHint[], hint: TipHint): TipHint[] {
  const mine = list.filter((h) => h.toUserId === hint.toUserId);
  const others = list.filter((h) => h.toUserId !== hint.toUserId);
  const kept = mine.length >= TIP_HINT_STACK ? mine.slice(mine.length - TIP_HINT_STACK + 1) : mine;
  return [...others, ...kept, hint];
}

/** Убрать всё, что отжило своё. Страховка на случай, если таймер удаления не сработал. */
export function pruneTipHints(list: TipHint[], nowMs: number): TipHint[] {
  return list.filter((h) => nowMs - h.atMs < TIP_HINT_MS);
}

/** Подсказки для одной строки, в порядке появления. */
export function hintsFor(list: TipHint[], userId: string): TipHint[] {
  return list.filter((h) => h.toUserId === userId);
}

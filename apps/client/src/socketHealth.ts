/**
 * Живость веб-сокета — чистое правило, без таймеров и без `Date.now()` внутри.
 *
 * Проблема, ради которой это существует: после сна или гибернации сокет остаётся `OPEN`, но не
 * доставляет ничего. `onclose` не срабатывает, переподключения не будет, и человек просто перестаёт
 * получать сообщения, ничего об этом не зная (issue #50). Единственный признак — тишина в эфире.
 *
 * Пороги здесь связаны между собой, и связь неочевидная, поэтому вынесена вместе с ними:
 * пинг обязан быть заметно ЧАЩЕ, чем реверс-прокси рвёт простаивающее соединение (~90 с), а порог
 * «протух» — заметно БОЛЬШЕ пары пингов, иначе один потерянный pong вызовет лишний реконнект.
 */

/** Как часто шлём ping. Меньше ~90 с — иначе NPM закроет простаивающий сокет сам. */
export const PING_MS = 30_000;

/** Через сколько тишины считаем сокет мёртвым: два пинга плюс запас. */
export const STALE_MS = PING_MS * 2 + 10_000;

/**
 * Протух ли сокет. `lastRecv` — время ЛЮБОГО последнего принятого кадра, включая pong сервера;
 * он проставляется и в `onopen`, иначе свежий сокет считался бы мёртвым на первом же тике.
 */
export function socketStale(lastRecv: number, now: number): boolean {
  return now - lastRecv > STALE_MS;
}

/**
 * Сколько ждём САМО РУКОПОЖАТИЕ, прежде чем считать попытку провалившейся.
 *
 * 🔴 Дыра, которую это закрывает (найдена 03.09): сторож живости (`heartbeat`) ставится в `onopen`,
 * а `pokeSocket` намеренно не трогает сокет в состоянии `CONNECTING` — «пусть достучится». Если
 * рукопожатие ЗАВИСЛО (реверс-прокси принял TCP и молчит — обычное дело, пока бэкенд
 * перезапускается), то не срабатывает НИЧЕГО: ни `onopen`, ни `onclose`, ни сторож. Клиент тихо
 * остаётся без событий — без сообщений, без присутствия, без обновления прав — и лечится только
 * перезагрузкой страницы. Ровно этот симптом («право доехало лишь после перезахода») и наблюдался.
 *
 * ⚠️ Значение с запасом: нормальное рукопожатие укладывается в доли секунды, а собственный таймаут
 * браузера на зависший коннект измеряется десятками секунд и на него полагаться нельзя.
 */
export const CONNECT_TIMEOUT_MS = 15_000;

import type { EffectConditions, Point } from './effects';

/**
 * Шина эффектов: одна точка входа для всех, кто хочет что-то показать (#120).
 *
 * 🔴 Зачем шина, а не прямой вызов из компонентов. Эффект запускают РАЗНЫЕ места: приход события по
 * шлюзу, ответ на собственный жест, стенд. Если каждое будет дёргать слой напрямую, стенд
 * превратится в отдельный путь — и начнёт расходиться с боевым поведением ровно там, где мы этого
 * не увидим. Здесь все ходят одной дорогой.
 *
 * ⚠️ Шина НЕ решает, показывать ли: это делает `planEffect` уже в слое, по живой обстановке. Здесь
 * только «случилось вот это, вот откуда».
 */

/** Осыпание перьев — МЕГА пок. Цели нет: эффект на весь экран, лететь некуда. */
export interface Feathers {
  kind: 'feathers';
  /** Чей подарок — подпись обязательна, иначе непонятно, что вообще произошло. */
  fromName: string;
  /**
   * Сообщение отправителя. ⚠️ Приезжает в событии с самого начала, но до 03.09 нигде не рисовалось:
   * человек писал текст, платил за щипок — и текст улетал в пустоту. Пусто — подписи просто нет.
   */
  message?: string;
  serverId: string | null;
  /** Подмена условий — ставит ТОЛЬКО стенд, см. `Feathers.benchOverrides`. */
  benchOverrides?: Partial<EffectConditions>;
}

/**
 * Тряска интерфейса.
 *
 * ⚠️ Отдельный вид, а не флаг внутри перьев: так её можно выстрелить в одиночку и подобрать
 * амплитуду, не глядя каждый раз на шесть секунд осыпания. МЕГА пок стреляет обоими.
 */
export interface Shake {
  kind: 'shake';
  serverId: string | null;
  benchOverrides?: Partial<EffectConditions>;
}

export type EffectRequest = Feathers | Shake;

type Listener = (req: EffectRequest) => void;

const listeners = new Set<Listener>();

/** Показать эффект. Вызывают и боевой код, и стенд — намеренно одним и тем же способом. */
export function fireEffect(req: EffectRequest): void {
  for (const l of [...listeners]) {
    try {
      l(req);
    } catch {
      // Эффект — украшение поверх основного: упавший слушатель не должен ронять то, что его вызвало.
    }
  }
}

export function onEffect(fn: Listener): () => void {
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

/**
 * Подсказка названия кнопки саундборда по ИМЕНИ ФАЙЛА (запрос 05.09).
 *
 * 🔴 Порядок в панели перевёрнут: сначала выбирают файл, потом дают ему имя. Причина не в удобстве
 * расстановки полей, а в том, как это делают на самом деле: у человека ворох записей, он лезет в
 * папку, слушает, выбирает — и только увидев, ЧТО выбрал, придумывает подпись кнопке. Требовать имя
 * заранее означало требовать его до того, как выбор сделан.
 *
 * ⚠️ Раз файл выбирают первым, его имя — лучшая заготовка для подписи: «vzhuh.mp3» почти всегда
 * значит кнопку «vzhuh». Подставляем её как ПРЕДЛОЖЕНИЕ, поле остаётся обычным и правится.
 */

/** Потолок длины имени кнопки — тот же, что стоит у поля ввода (`maxLength`). */
export const SOUNDBOARD_NAME_MAX = 24;

/**
 * Имя кнопки из имени файла: без расширения, разделители — в пробелы, лишние пробелы схлопнуты,
 * длина обрезана.
 *
 * ⚠️ Расширение режем по ПОСЛЕДНЕЙ точке и только если после неё что-то есть: «vzhuh.2.mp3» должен
 * дать «vzhuh.2», а файл без расширения («vzhuh») — остаться собой, а не потерять хвост.
 * ⚠️ Пустой результат — пустая строка, а не «звук»: выдуманное имя человек может не заметить и
 * залить кнопку с чужой подписью. Пусть лучше поле останется пустым и попросит ввод.
 */
export function nameFromFileName(fileName: string): string {
  const dot = fileName.lastIndexOf('.');
  const base = dot > 0 ? fileName.slice(0, dot) : fileName;
  return base
    .replace(/[_-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, SOUNDBOARD_NAME_MAX);
}

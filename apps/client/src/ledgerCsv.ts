/**
 * Выгрузка журнала операций в таблицу (#117, запрос 03.09: «показывать 20, остальное за
 * неделю/месяц/сезон выгружать в удобоваримом формате»).
 *
 * 🔴 **CSV, а не JSON и не наш собственный формат.** «Удобоваримый» здесь значит «открывается
 * двойным щелчком в том, что у человека уже стоит», — то есть в Excel или Таблицах. JSON пришлось
 * бы куда-то нести, а свой формат никто не откроет вовсе.
 *
 * 🔴 **Разделитель — ТОЧКА С ЗАПЯТОЙ, и в начале файла BOM.** Русский Excel по умолчанию считает
 * запятую десятичным знаком, а не разделителем колонок: файл с запятыми открывается ОДНИМ столбцом,
 * и выгрузка выглядит сломанной. BOM нужен ему же — без него кириллица приезжает кракозябрами.
 * ⚠️ Это ровно тот случай, когда «правильный» rfc4180-файл хуже: он формально верен и практически
 * непригоден для того, кто его открывает.
 */

/** Одна строка выгрузки — уже человеческими словами, без внутренних кодов. */
export interface LedgerCsvRow {
  /** Дата и время в местном формате: файл читает человек, а не машина. */
  at: string;
  /** Что случилось: «Тип от Маши», «За время в голосовом канале». */
  what: string;
  /** Изменение баланса со знаком. */
  amount: number;
  /** Подробности: сгоревший налог, день серии, разбор начисления. Пусто — колонка пустая. */
  detail: string;
}

/** Экранирование по правилам CSV: кавычки удваиваются, поле в кавычках — если есть спецсимвол. */
function cell(v: string): string {
  return /[";\n\r]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v;
}

/**
 * Собрать файл.
 *
 * ⚠️ Заголовок колонки с суммой несёт НАЗВАНИЕ ВАЛЮТЫ сервера: у каждого инстанса оно своё, и
 * «Сумма» без единицы в выгрузке за сезон уже ни о чём не говорит.
 */
export function ledgerCsv(rows: LedgerCsvRow[], currency: string): string {
  const head = ['Дата и время', 'Операция', `Изменение, ${currency}`, 'Подробности'];
  const body = rows.map((r) => [cell(r.at), cell(r.what), String(r.amount), cell(r.detail)].join(';'));
  // BOM обязателен — см. шапку модуля.
  return `﻿${[head.join(';'), ...body].join('\r\n')}\r\n`;
}

/** Имя файла: сервер, период и дата — чтобы три выгрузки подряд не перезаписывали друг друга. */
export function ledgerFileName(period: 'week' | 'month' | 'season', now: Date): string {
  const label = { week: 'nedelya', month: 'mesyac', season: 'sezon' }[period];
  const d = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
  return `guscoins-${label}-${d}.csv`;
}

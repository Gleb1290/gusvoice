/**
 * Текст отказа старта показа для окна выбора источника (`ScreenShareDialog.tsx`) — без React и
 * Tauri, чтобы его можно было проверить из Node (просьба Codex, 2026-09-26).
 */

/**
 * Чистое: ошибка старта показа → строка под кнопкой «Начать» в окне выбора.
 *
 * 🔴 Оболочка отказывает СТРОКОЙ, а не `Error` (так устроен `invoke` Tauri): раньше здесь читали
 * только `.message`, и причина вроде «signal connection timed out» терялась за общей фразой — на
 * пробной сборке 23.09 разбирать пришлось через отладчик. Причины нет — общая фраза без двоеточия.
 */
export function shareStartErrorText(e: unknown): string {
  const reason = typeof e === 'string' ? e : (e as Error)?.message;
  return reason ? `Не удалось начать трансляцию: ${reason}` : 'Не удалось начать трансляцию';
}

/**
 * Объяснение, которое ждёт человека НА ЭКРАНЕ ВХОДА (#139, §5.7).
 *
 * 🔴 Повод — авария 18.09. Гостевая сессия у соседа протухает, `App.loadMe` возвращает человека
 * домой и говорит об этом тостом. Но `ToastHost` живёт внутри `MainLayout`, то есть на экране
 * входа тостов НЕТ ВООБЩЕ: если дома человек тоже не залогинен, его молча переносит на другой
 * инстанс без единого слова. Он вводит пароль от соседа, свой инстанс отвечает «неверный пароль»,
 * и выглядит это как «меня не пускает с верным паролем».
 *
 * ⚠️ Живёт в памяти вкладки и читается ОДИН раз: пережившее перезагрузку объяснение всплывало бы
 * через неделю у того, кто давно забыл про этот переход.
 */

let notice: string | null = null;

export function setLoginNotice(text: string): void {
  notice = text;
}

/** Забрать объяснение (и забыть его). */
export function takeLoginNotice(): string | null {
  const t = notice;
  notice = null;
  return t;
}

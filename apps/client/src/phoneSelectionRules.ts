/**
 * Застрявшее системное выделение на телефоне (Android 0.8.21, снимок владельца: подпись «Профиль» на нижней панели
 * осталась выделенной бирюзовой заливкой и каплями-маркерами «всё время»).
 *
 * Причина: Chromium не снимает выделение тапом по `<button>` (кнопка не начинает и не сворачивает выделение), а у вкладок
 * `.mobile-nav` не было `user-select: none` — долгое нажатие по подписи выделяло её, и тапы по вкладкам уже не помогали.
 * Основное лечение — CSS (`styles.css`, телефонная раскладка: у всего интерфейса `user-select: none`, у полей ввода
 * `text`). Это правило — страховка: выделение, которому в телефонной раскладке быть негде (якорь на элементе с
 * `user-select: none`), снимается сразу, а не ждёт тапа по тексту.
 *
 * Модуль чистый — признаки собирает `main.tsx`; проверяется тестом.
 */

/** Признаки текущего выделения страницы. */
export interface SelectionState {
  /** Телефонная раскладка (`max-width: 760px`, как у CSS). */
  phone: boolean;
  /** Выделение свёрнуто (каретка) — снимать нечего. */
  collapsed: boolean;
  /** Фокус в поле ввода: выделение внутри него хранится как выделение страницы с якорем на соседнем узле. */
  fieldFocused: boolean;
  /** Вычисленный `user-select` элемента, где выделение началось. */
  anchorUserSelect: string;
}

/** Снять ли выделение: только телефон, только настоящий диапазон, не поле ввода и не место, где выделять разрешено. */
export function shouldDropSelection(s: SelectionState): boolean {
  if (!s.phone || s.collapsed || s.fieldFocused) return false;
  return s.anchorUserSelect === 'none';
}

/**
 * Действующий `user-select` места по значениям `getComputedStyle(...).userSelect` от самого элемента к предкам: `auto` в
 * вычисленном стиле остаётся словом `auto` (не `none` родителя), поэтому идём вверх до первого явного значения
 * (`none`, `text`, `all`, `contain`…); пустое значение пропускаем; явного нет — `auto`. Список собирает `main.tsx`.
 */
export function effectiveUserSelect(values: readonly (string | null | undefined)[]): string {
  for (const v of values) {
    if (v && v !== 'auto') return v;
  }
  return 'auto';
}

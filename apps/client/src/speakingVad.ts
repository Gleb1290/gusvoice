/**
 * Обводка говорящего: говорит человек или нет по уровню его звука — чистое правило, без Web Audio и часов.
 *
 * 🔴 **Повод (29.09, замечено владельцем на живых людях):** порог был ОДИН на всех — уровень 0.015. Кто говорит тихо
 * или шепчет, того слышно (его звук доходит), но под порог он не дотягивал, и обводка не загоралась. Одним числом
 * это не лечится: порог гейта у каждого свой (1–60 %, `micProcessorRules.clampVadThreshold`; до 29.09 по умолчанию
 * стоял выключенным), поэтому у одного в тишине идёт почти ноль, у другого — фон комнаты, который гейт пропустил.
 * Опусти общий порог — у второго обводка будет гореть от фона.
 *
 * Поэтому порог СВОЙ у каждой дорожки — от её же тишины (так делает автоматическая чувствительность у Discord):
 * - **пол шума** — МИНИМУМ уровня за последние `FLOOR_WINDOW_MS` (5 с). Живая речь хоть раз за пять секунд
 *   проваливается до тишины (вдох, пауза между фразами), поэтому пол держится у фона комнаты даже в долгом
 *   монологе. ⚠️ Не «медленно ползёт вверх»: такой пол у тихого говорящего поверх фона дорастал до уровня
 *   провалов между слогами, и обводка горела 46 % речи (прогон 29.09). Ровный новый шум (включили вентилятор)
 *   перестаёт зажигать обводку, как только уйдёт из окна;
 * - **говорит**, когда уровень в `OVER_FLOOR` раз выше пола, но не ниже `MIN_OPEN` (тишина закрытого гейта — ноль,
 *   и без нижней границы обводку зажигало бы любое шевеление);
 * - закрывается на доле порога (`CLOSE_RATIO`) и ещё `HOLD_MS` держится — паузы между словами не мигают.
 *
 * Уровень — RMS формы волны за окно анализатора (~21 мс), 0..1. Замеры 26.06: тишина без гейта ≈ 0.005–0.006,
 * речь 0.04–0.2 с провалами между слогами до 0.005–0.009; шёпот — между ними.
 */

export const VAD = {
  /** Ниже этого — тишина при любом поле (закрытый гейт отдаёт ноль, шёпот — от ~0.006). */
  MIN_OPEN: 0.004,
  /** Во сколько раз выше пола шума (≈ +6 дБ). */
  OVER_FLOOR: 2,
  /** Закрыть на этой доле порога открытия — гистерезис против дребезга на границе. */
  CLOSE_RATIO: 0.65,
  /** Сколько держать обводку после того, как уровень упал, — мост через паузы между словами. */
  HOLD_MS: 500,
  /** Окно, минимум по которому — пол шума. */
  FLOOR_WINDOW_MS: 5000,
  /** Окно режется на корзины: храним минимум каждой, а не каждый замер (десять чисел вместо сотни). */
  FLOOR_BUCKET_MS: 500,
} as const;

export interface VadState {
  /** Открыт ли порог сейчас (для гистерезиса). */
  open: boolean;
  /** Когда уровень последний раз был над порогом, мс. */
  lastAbove: number;
  /** Минимумы закрытых корзин окна, старые — в начале. */
  mins: number[];
  /** Минимум текущей корзины и когда она началась; `null` — ещё не мерили. */
  cur: number | null;
  curStart: number;
}

export function vadInitial(): VadState {
  return { open: false, lastAbove: -Infinity, mins: [], cur: null, curStart: 0 };
}

/** Пол шума: минимум по окну (закрытые корзины + текущая). `null` — замеров ещё не было. */
export function vadFloor(s: VadState): number | null {
  if (s.cur === null) return null;
  return Math.min(s.cur, ...s.mins);
}

/** Порог открытия для этого пола шума. */
export function vadOpenLevel(floor: number): number {
  return Math.max(VAD.MIN_OPEN, floor * VAD.OVER_FLOOR);
}

/**
 * Один шаг: новый уровень → новое состояние и «говорит ли».
 * ⚠️ Первый замер становится полом: начни мы с нуля, у человека с шумным фоном обводка горела бы первые
 * секунды после входа. Если первый замер пришёлся на речь — первый же провал между слогами (~0.2 с) опустит пол.
 */
export function vadStep(s: VadState, level: number, now: number): { state: VadState; speaking: boolean } {
  let mins = s.mins;
  let cur = s.cur;
  let curStart = s.curStart;
  if (cur === null) {
    cur = level;
    curStart = now;
  } else if (now - curStart >= VAD.FLOOR_BUCKET_MS) {
    // Корзина закрылась — её минимум уходит в окно, самые старые выпадают.
    const keep = Math.max(0, Math.round(VAD.FLOOR_WINDOW_MS / VAD.FLOOR_BUCKET_MS) - 1);
    mins = [...mins, cur].slice(-keep);
    cur = level;
    curStart = now;
  } else if (level < cur) {
    cur = level;
  }
  const state: VadState = { open: s.open, lastAbove: s.lastAbove, mins, cur, curStart };
  const openAt = vadOpenLevel(vadFloor(state) ?? level);
  const above = level >= (s.open ? openAt * VAD.CLOSE_RATIO : openAt);
  state.open = above;
  if (above) state.lastAbove = now;
  return { state, speaking: now - state.lastAbove < VAD.HOLD_MS };
}

/**
 * Мягкий переход в другой инстанс — БЕЗ перезапуска приложения (#139, §5.7).
 *
 * 🔴 Раньше «сделать активным» означало перезапуск: `config` считался один раз на загрузке модуля,
 * `api` держал токен в переменной, сокеты и кеши модулей поднимались под тот инстанс, что был
 * активным в момент старта. Перезапуск честно решал всё это разом — ценой того, что переход между
 * своим сервером и сервером соседа выглядел как падение приложения. После того как серверы всех
 * инстансов встали в рейл (`railRules.ts`), такой переход стал обычным кликом, и перезапускать на
 * каждый клик нельзя.
 *
 * **Порядок шагов важен и другим быть не может:**
 *
 * 1. **Разбираем прежний инстанс, ПОКА он ещё активен.** Голос, счётчик игры и регистрация пушей
 *    пишут в хранилище с ключом активной записи и ходят с её токеном; сделай это после подмены —
 *    и выход из голоса стёр бы сохранённую сессию НОВОГО инстанса, а отписка от пушей ушла бы не
 *    туда.
 * 2. **Подменяем активную запись** — с этого мгновения `config` отвечает новым адресом.
 * 3. **Перечитываем токен и объявляем новое поколение** (`reloadToken`): ответы запросов, ушедших к
 *    прежнему инстансу, с этого момента выбрасываются, а не пишутся в стор.
 * 4. **Сбрасываем кеши, привязанные к инстансу** — они уже перечитаются под новую запись.
 * 5. **Чистим стор и растим `instanceEpoch`** — на него подписан `App`, он и проходит заново весь
 *    вход: «узнать себя → серверы → сокеты».
 *
 * ⚠️ Голос при переходе обрывается намеренно. §5.7 обещает «голос строго один», а соединение
 * принадлежит SFU прежнего инстанса; тащить его за собой значило бы держать человека в комнате,
 * которой он в интерфейсе больше не видит. Перезапуск вёл себя так же — поведение не изменилось.
 * ⚠️ Регистрацию пушей снимаем: устройство может быть зарегистрировано только у одного инстанса, и
 * оставить её у покинутого значит получать оттуда уведомления, по которым некуда перейти. Обратная
 * сторона честная: вернувшись домой, человек регистрируется заново.
 */
export async function switchInstance(localId: string): Promise<void> {
  if (!localId || localId === activeInstanceId()) return;
  teardownCurrent(); // 1 — пока прежняя запись ещё активна
  setActiveInstance(localId); // 2
  adoptActive(); // 3–5
}

/**
 * Открыть админку СВОЕГО инстанса (`configRules.adminTarget`, 23.09). Стоим гостем у соседа — сперва домой:
 * окно админки говорит с API активного инстанса. Флаг ставим ПОСЛЕ перехода — переход закрывает окна
 * прежнего инстанса (`switchedInstance`), и поставленный раньше он бы сбросился.
 */
export async function openOwnAdmin(homeId: string | null): Promise<void> {
  if (homeId) await switchInstance(homeId);
  useStore.getState().setAdminOpen(true);
}

/**
 * Активная запись сменилась ПОМИМО нас — принять её тем же порядком.
 *
 * Так бывает в двух местах: добавили инстанс (он сразу активен и без токена — впереди экран входа) и
 * удалили ту запись, в которой стояли (активной становится соседняя). Отдельный вход нужен ровно
 * потому, что подмену там делает не этот модуль, а `switchInstance` в таком случае увидел бы «этот
 * инстанс уже активен» и не сделал бы ничего.
 */
export async function adoptActiveInstance(): Promise<void> {
  teardownCurrent();
  adoptActive();
}

/** Шаг 1: отпустить всё, что держит прежний инстанс. Зовётся, пока он ещё активен. */
function teardownCurrent(): void {
  useStore.getState().leaveVoice();
  stopGameActivity();
  stopPushRegistration();
  disconnectSockets();
  // Фоновые шлюзы пересобираются целиком: прежняя запись становится фоновой, новая — живой. Порядок
  // тот же, что у остальных шагов, — сперва отпустить, потом принять.
  stopBgGateways();
}

/** Шаги 3–5: принять активную запись как свою. */
function adoptActive(): void {
  // Токен и новое поколение запросов: ответы прежнего инстанса с этого мгновения выбрасываются.
  reloadToken();
  // Кеши, чьи ключи принадлежат инстансу (каналы, люди, серверы).
  reloadChannelPrefs();
  reloadUserAudio();
  clearTyping();
  clearEconomyInFlight();
  resetFederationProbe();
  // 🔴 Гасим счётчики записи, КУДА пришли, до того как поднимется её основной шлюз: иначе значок
  // «5 непрочитанных» висел бы на сервере, который человек уже открыл, до следующего сообщения.
  const active = activeInstanceId();
  if (active) clearBgUnread(active);
  syncBgGateways(active);
  // Стор и новый заход в загрузку — эффект `App` на `instanceEpoch`.
  useStore.getState().switchedInstance();
}

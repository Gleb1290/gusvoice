/**
 * Когда в меню/карточке человека показывать личную громкость («Громкость 100%» и «Заглушить для себя»).
 *
 * 🔴 C3 (эмулятор, 08.10): лист по удержанию аватарки в ТЕКСТОВОЙ группе предлагал громкость и
 * заглушение — голосовые пункты в чате, где голоса нет. Регулятор имеет смысл, только когда человек
 * сейчас в голосе: он живой участник звонка с нами, или в голосовом канале (метка зовущего), или в
 * списке присутствия какого-нибудь голосового канала.
 *
 * Модуль чистый — принимает уже вычисленные признаки, поэтому проверяется тестом.
 */
export function showUserAudio(opts: { isSelf: boolean; hasParticipant: boolean; voiceChannelId?: string | null; inPresence: boolean }): boolean {
  if (opts.isSelf) return false;
  return opts.hasParticipant || !!opts.voiceChannelId || opts.inPresence;
}

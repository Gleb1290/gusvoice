/**
 * Правила звуковых подсказок и авто-возврата в голосовой канал — чистые, БЕЗ таймеров и стора.
 *
 * Задача звучит просто («играть звук при потере связи»), но вся сложность в том, когда МОЛЧАТЬ:
 * `reconnecting` возникает от любого чиха вайфая и в большинстве случаев закрывается за секунду.
 */

/**
 * Через сколько после пропажи связи играть «связь потеряна» — ПОЛОВИНА окна, после которого нас
 * выкидывает из канала (так решено). Половина, а не фиксированные N секунд, чтобы подсказка не
 * разъехалась с моментом реального отключения, если окно когда-нибудь поменяют.
 */
export function lostCueDelayMs(graceMs: number): number {
  return Math.floor(graceMs / 2);
}

/**
 * Сколько после обрыва мы ещё готовы вернуться в канал сами. Дальше человек уже занялся другим, и
 * приложение, внезапно втащившее его обратно в разговор, пугает больше, чем помогает.
 */
export const REJOIN_WINDOW_MS = 5 * 60_000;

export interface VoiceSessionLike {
  serverId: string;
  channelId: string;
  /** Момент последнего «живого» сердцебиения — фактически время обрыва. */
  ts: number;
}

/**
 * Возвращаться ли в канал автоматически после того, как связь восстановилась.
 *
 * ⚠️ **Сохранённая сессия — это и есть признак НЕПРЕДНАМЕРЕННОГО обрыва**, отдельного флага не надо:
 * при своём выходе, при входе с другого устройства и при выключении сервера сессия стирается
 * (`leaveVoice()` без `keepSession`), а переживает только тот выход, который мы сделали сами, сдавшись
 * по грейсу (`leaveVoice(true)`). Поэтому «сессия есть» ⇒ «человек не хотел уходить».
 *
 * ⚠️ Если мы УЖЕ в голосе — не трогаем: человек мог за это время зайти в другой канал руками, и
 * выдёргивать его оттуда нельзя.
 */
export function shouldAutoRejoin(p: {
  session: VoiceSessionLike | null;
  inVoice: boolean;
  now: number;
  windowMs?: number;
}): boolean {
  if (!p.session || p.inVoice) return false;
  const age = p.now - p.session.ts;
  if (age < 0) return false; // часы разъехались — не угадываем
  return age <= (p.windowMs ?? REJOIN_WINDOW_MS);
}
